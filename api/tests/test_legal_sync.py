"""Документы, на которые ссылается бот, обязаны отдаваться по этим адресам.

Контракт здесь межъязыковой, и поэтому проверяется с питоновской стороны.
`bot/config.py: legal_url` строит адрес вида `{SITE_URL}/privacy.html`, где
`SITE_URL` в разметке деплоя — это веб-сервис (`DEPLOY.md`, шаг 6). По этому
адресу отдаётся не лендинг, а `web/dist`, то есть то, что Vite скопировал из
`web/public`. Значит любое имя, которое умеет вернуть `legal_url`, обязано лежать
в `web/public` настоящим файлом — иначе человек на экране согласия жмёт «Политика
конфиденциальности» и получает 404 ровно в тот момент, когда его просят
согласиться с тем, что он не может прочитать.

Сами копии порождает `web/scripts/sync-landing.mjs` (он же вызывается из
`prebuild` и из CI как `npm run check:landing`), и его собственные тесты лежат
рядом с ним: `web/scripts/__tests__/sync-landing.test.mjs`. Здесь не
пересказывается ни его логика, ни его список файлов — список читается из него же,
чтобы третьего места с перечнем документов не появилось.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
ЛЕНДИНГ = КОРЕНЬ / "landing"
МИНИ_АПП = КОРЕНЬ / "web" / "public"
ГЕНЕРАТОР = КОРЕНЬ / "web" / "scripts" / "sync-landing.mjs"


def _список_из_генератора(имя_массива: str) -> tuple[str, ...]:
    """Перечень файлов — из генератора, а не второй копией в тесте.

    Разошедшийся перечень был бы худшим видом зелёного теста: он проверял бы
    файлы, которых больше никто не синхронизирует. Поэтому массив читается из
    самого скрипта, а пустой результат — это ошибка, а не «нечего проверять»:
    иначе переименование массива превратит весь модуль в тишину.
    """
    assert ГЕНЕРАТОР.is_file(), (
        f"нет {ГЕНЕРАТОР.relative_to(КОРЕНЬ)}: копии юридических страниц в "
        f"web/public остались без источника"
    )
    текст = ГЕНЕРАТОР.read_text(encoding="utf-8")
    блок = re.search(rf"export const {имя_массива} = \[(.*?)\]", текст, re.S)
    assert блок, (
        f"в {ГЕНЕРАТОР.name} не найден массив {имя_массива} — он переименован или "
        f"переехал. Пока он не найден, этот тест ничего не проверяет"
    )
    найдено = tuple(re.findall(r'"([^"]+)"', блок.group(1)))
    assert найдено, f"массив {имя_массива} пуст: синхронизировать нечего"
    return найдено


ДОКУМЕНТЫ = _список_из_генератора("ДОКУМЕНТЫ")
АССЕТЫ = _список_из_генератора("АССЕТЫ")

#: Имена, которые умеет вернуть `bot/config.py: legal_url`. Расширение он
#: дописывает сам, поэтому в вызовах встречаются обе формы.
СТРАНИЦЫ_БОТА = ("privacy", "terms", "guidelines", "moderation", "support")

_СВОЯ_ССЫЛКА = re.compile(r'(?:href|src)="([^"]+)"')
_ВНЕШНЯЯ = re.compile(r"^(?:https?:|//|#|mailto:|tel:|data:|/)")


def _относительные(текст: str) -> list[str]:
    """Ссылки на файлы рядом: только они могут не доехать при копировании."""
    найдено = []
    for ссылка in _СВОЯ_ССЫЛКА.findall(текст):
        if _ВНЕШНЯЯ.match(ссылка):
            continue
        путь = ссылка.split("#")[0].split("?")[0]
        if путь:
            найдено.append(путь)
    return найдено


@pytest.mark.parametrize("страница", СТРАНИЦЫ_БОТА)
def test_бот_ссылается_на_то_что_отдаётся(страница: str):
    """`legal_url("privacy")` → `{SITE_URL}/privacy.html` → файл в web/public."""
    имя = f"{страница}.html"
    assert имя in ДОКУМЕНТЫ, (
        f"бот ссылается на {имя}, но синхронизация {ГЕНЕРАТОР.name} его не знает: "
        f"страница уедет в прод устаревшей или не уедет вовсе"
    )
    цель = МИНИ_АПП / имя
    # Порядок важен: is_file() идёт по ссылке и рапортует про файл в landing/ —
    # ровно та слепота, из-за которой сборка образа падала, а тесты молчали.
    assert not цель.is_symlink(), (
        f"web/public/{имя} — символическая ссылка. Образ веба собирается из "
        f"контекста web/, где ../../landing нет: ссылка висит в воздухе и "
        f"vite build падает целиком"
    )
    assert цель.is_file(), (
        f"мини-апп не отдаёт {имя}: по этой ссылке бот отправляет человека на "
        f"экране согласия. Починить: npm run sync:landing"
    )


@pytest.mark.parametrize("имя", АССЕТЫ)
def test_оформление_документов_на_месте(имя: str):
    """Без styles.css человек получает юридический документ голым HTML."""
    цель = МИНИ_АПП / имя
    assert not цель.is_symlink(), f"web/public/{имя} — символическая ссылка"
    assert цель.is_file(), (
        f"мини-апп не отдаёт {имя}: документы откроются без вёрстки. "
        f"Починить: npm run sync:landing"
    )


@pytest.mark.parametrize("имя", ДОКУМЕНТЫ)
def test_в_копиях_нет_ссылок_на_корень_мини_аппа(имя: str):
    """`/#how` в мини-аппе — переход в чужую деку вместо раздела сайта.

    Копия не может быть побайтовой: в подвале лендинга ссылки на его же
    разделы, а в мини-аппе корень отдаёт SPA (`web/Dockerfile`: `serve dist -s`),
    лендинга по этому адресу нет.
    """
    текст = (МИНИ_АПП / имя).read_text(encoding="utf-8")
    мёртвые = re.findall(r'href="(/#[^"]*)"', текст)
    assert not мёртвые, (
        f"web/public/{имя} ссылается в корень: {мёртвые}. Там SPA, анкор "
        f"потеряется. Ссылки на разделы сайта в копиях обязаны быть абсолютными"
    )


@pytest.mark.parametrize(
    "дерево,имя",
    [("landing", и) for и in sorted(p.name for p in ЛЕНДИНГ.glob("*.html"))]
    + [("web/public", и) for и in sorted(p.name for p in МИНИ_АПП.glob("*.html"))],
)
def test_относительные_ссылки_ведут_в_существующие_файлы(дерево: str, имя: str):
    """Стили, скрипт, иконка и соседние документы должны быть в том же дереве.

    Копирование по файлу этим и опасно: страницу перенесли, а `styles.css` рядом
    не положили — человек получает документ без вёрстки и без навигации.
    """
    папка = КОРЕНЬ / дерево
    текст = (папка / имя).read_text(encoding="utf-8")
    мёртвые = sorted({с for с in _относительные(текст) if not (папка / с).exists()})
    assert not мёртвые, (
        f"{дерево}/{имя} ссылается на то, чего рядом нет: {мёртвые}. "
        f"В этом дереве человек получит 404 — оформление или соседний документ"
    )


def test_список_документов_совпадает_с_лендингом():
    """Новый юридический документ обязан попасть и в список, и в оба дерева."""
    в_лендинге = {p.name for p in ЛЕНДИНГ.glob("*.html")} - {"index.html"}
    assert set(ДОКУМЕНТЫ) == в_лендинге, (
        f"landing/ и ДОКУМЕНТЫ в {ГЕНЕРАТОР.name} разошлись: "
        f"{sorted(в_лендинге ^ set(ДОКУМЕНТЫ))}. Документ, которого нет в списке, "
        f"не доедет до мини-аппа"
    )
