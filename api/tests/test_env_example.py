"""`.env.example` как правда о переменных: ни мёртвых, ни незадокументированных.

Файл-пример — единственная инструкция для того, кто поднимает сервис. Обе
ошибки в нём стоят одинаково дорого и обе не видны при запуске:

* Мёртвый ключ читается как настройка. `PREMIUM_PRICE_STARS=250` был в примере,
  когда цены уже переехали в `api/services/plans.py`: человек правил цену,
  перезапускал бота и получал прежнюю. Так же `API_BASE_URL` числился
  обязательной переменной бота в DEPLOY.md, хотя бот ходит в базу напрямую.
* Незадокументированный ключ существует только для тех, кто читал исходники.
  `CORS_ORIGINS` не был описан нигде: на проде оставался дефолт с localhost,
  браузер молча отбрасывал каждый ответ API, и приложение показывало пустые
  экраны при зелёных логах.

Проверка идёт по факту: ключи вычитываются из `os.getenv`/`os.environ`, из полей
`api/config.py::Settings` (pydantic читает каждое поле из окружения) и из
`import.meta.env` во фронтенде — то есть отовсюду, откуда значение реально
попадает в код.

Строка вида `KEY=` или `# KEY=` — это утверждение «код читает KEY». Прозаические
комментарии свободны: раздел «что ещё не подключено» описывает отсутствующий
Stripe словами, а не ключом-заглушкой, именно поэтому.
"""

from __future__ import annotations

import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ПРИМЕР = КОРЕНЬ / ".env.example"

#: Переменные, которые подставляет хостинг, а не человек. `PORT` Railway
#: выдаёт web-сервисам сам, и в примере он был бы вредным советом: задав его
#: руками, оператор перебьёт то, что назначила платформа.
ДАЮТ_ХОСТИНГИ = frozenset({"PORT"})

#: Контракты чужих образов в docker-compose: их читает entrypoint postgres,
#: а не наш код. Наш код видит только собранный из них DATABASE_URL.
ЧУЖИЕ_ОБРАЗЫ = frozenset({"POSTGRES_DB", "POSTGRES_USER", "POSTGRES_PASSWORD"})

#: Где искать чтение окружения. `web/dist`, `build` и venv'ы исключены: там
#: лежит собранное, и одна и та же переменная нашлась бы дважды.
СУФФИКСЫ = ("*.py", "*.ts", "*.tsx", "*.mjs", "*.cjs")
ИСКЛЮЧИТЬ = (".venv", "node_modules", "/build/", "/dist/", "/Pods/", "/tests/")

ЧТЕНИЕ = (
    re.compile(r"os\.getenv\(\s*[\"']([A-Z][A-Z0-9_]+)[\"']"),
    re.compile(r"os\.environ(?:\.get)?[\(\[]\s*[\"']([A-Z][A-Z0-9_]+)[\"']"),
    re.compile(r"import\.meta\.env\.(VITE_[A-Z0-9_]+)"),
    re.compile(r"process\.env\.([A-Z][A-Z0-9_]+)"),
)
#: Поле pydantic-настроек = переменная окружения с тем же именем.
ПОЛЕ_НАСТРОЕК = re.compile(r"^\s{4}([A-Z][A-Z0-9_]+):\s", re.M)
#: Ключ в примере: `KEY=…` или закомментированный `# KEY=…`.
КЛЮЧ_ПРИМЕРА = re.compile(r"^\s*#?\s*([A-Z][A-Z0-9_]+)\s*=")


def _исходники() -> list[Path]:
    файлы: list[Path] = []
    for суффикс in СУФФИКСЫ:
        for путь in КОРЕНЬ.rglob(суффикс):
            если_мимо = str(путь)
            if any(часть in если_мимо for часть in ИСКЛЮЧИТЬ):
                continue
            файлы.append(путь)
    return файлы


def читаемые_ключи() -> dict[str, str]:
    """Ключ → первое место, где код его читает."""
    найдено: dict[str, str] = {}
    for путь in _исходники():
        текст = путь.read_text(errors="ignore")
        for шаблон in ЧТЕНИЕ:
            for совпадение in шаблон.finditer(текст):
                строка = текст[: совпадение.start()].count("\n") + 1
                найдено.setdefault(
                    совпадение.group(1), f"{путь.relative_to(КОРЕНЬ)}:{строка}"
                )
    настройки = (КОРЕНЬ / "api" / "config.py").read_text()
    for поле in ПОЛЕ_НАСТРОЕК.findall(настройки):
        найдено.setdefault(поле, "api/config.py (Settings)")
    return найдено


def ключи_примера() -> dict[str, int]:
    """Ключ → номер строки в `.env.example`, включая закомментированные."""
    найдено: dict[str, int] = {}
    for номер, строка in enumerate(ПРИМЕР.read_text().splitlines(), 1):
        совпадение = КЛЮЧ_ПРИМЕРА.match(строка)
        if совпадение:
            найдено.setdefault(совпадение.group(1), номер)
    return найдено


def test_в_примере_нет_мёртвых_переменных():
    """Ключ в примере, которого не читает никто, — ложная настройка."""
    читаемые = читаемые_ключи()
    мёртвые = {к: н for к, н in ключи_примера().items() if к not in читаемые}
    assert not мёртвые, (
        "в .env.example есть ключи, которых код не читает: "
        + ", ".join(f"{к} (строка {н})" for к, н in sorted(мёртвые.items()))
        + ". Человек будет их править и ждать эффекта"
    )


def test_каждая_переменная_описана():
    """Переменная, которой нет в примере, известна только по исходникам."""
    в_примере = ключи_примера()
    молчком = {
        к: где
        for к, где in читаемые_ключи().items()
        if к not in в_примере and к not in ДАЮТ_ХОСТИНГИ
    }
    assert not молчком, (
        "код читает переменные, которых нет в .env.example: "
        + ", ".join(f"{к} ({где})" for к, где in sorted(молчком.items()))
        + ". Либо в пример, либо в ДАЮТ_ХОСТИНГИ с причиной"
    )


def test_cors_описан_как_обязательный_для_прода():
    """Дефолт CORS сужает прод до localhost — об этом обязано быть сказано."""
    текст = ПРИМЕР.read_text()
    assert re.search(r"^CORS_ORIGINS=\S", текст, re.M), (
        "CORS_ORIGINS в примере закомментирован или пуст: пустое значение "
        "перебивает дефолт и оставляет фронтенд вообще без разрешённых origin'ов"
    )
    описание = текст.split("CORS_ORIGINS=")[0].rsplit("# ── ", 1)[-1]
    assert "localhost" in описание and "прод" in описание.lower(), (
        "рядом с CORS_ORIGINS не сказано, что дефолт — localhost и что в проде "
        "домен обязателен. Симптом (пустые экраны при зелёных логах) не наводит "
        "на CORS сам по себе"
    )


def test_deploy_не_требует_несуществующих_переменных():
    """Инструкция деплоя — тоже документация, и она тоже обязана быть правдой."""
    читаемые = читаемые_ключи()
    deploy = (КОРЕНЬ / "DEPLOY.md").read_text()
    # Только строки таблиц вида `| `VAR` | значение |` — прозу не трогаем:
    # там переменные упоминаются и в объяснениях, почему их задавать не нужно
    требуемые = set(re.findall(r"^\|\s*`([A-Z][A-Z0-9_]+)`\s*\|", deploy, re.M))
    фантомы = sorted(в for в in требуемые if в not in читаемые)
    assert not фантомы, (
        f"DEPLOY.md требует задать переменные, которых код не читает: {фантомы}"
    )


def test_компоуз_не_передаёт_несуществующих_переменных():
    """То же для docker-compose: заданное там выглядит как рабочая настройка."""
    читаемые = читаемые_ключи()
    компоуз = (КОРЕНЬ / "docker-compose.yml").read_text()
    заданные = set(re.findall(r"^\s{6}([A-Z][A-Z0-9_]+):\s", компоуз, re.M))
    фантомы = sorted(
        в for в in заданные if в not in читаемые and в not in ЧУЖИЕ_ОБРАЗЫ
    )
    assert not фантомы, (
        f"docker-compose.yml задаёт переменные, которых код не читает: {фантомы}"
    )
