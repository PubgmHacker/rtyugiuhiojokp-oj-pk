"""Первый кадр нативной обёртки: голова страницы не ждёт чужие серверы.

Единственная строка `<script src="https://telegram.org/js/telegram-web-app.js">`
в `<head>` держала iOS-сборку полностью пустой. Механизм: синхронный внешний
скрипт останавливает разбор HTML до ответа сервера, а telegram.org у части
аудитории заблокирован на уровне провайдера — соединение не отвергается, а висит
до таймаута WebKit. Пока оно висит, `<body>` не разобран: ни разметки, ни стража
загрузки (он живёт в теле), ни консоли, ни адресной строки. Человек видит
однотонный `#080615` — цвет `ios.backgroundColor` из capacitor.config.ts — и
сообщает «приложение не открывается».

Проверено на симуляторе (iPhone 17 Pro, iOS 26.5): с той строкой не рисовалось
ни пикселя, включая статичный `<div>` сразу после `<body>`; без неё сразу
открывается экран входа. Отсюда правило ниже — оно про разбор страницы, а не про
скорость: асинхронный скрипт может не приехать никогда, и приложение всё равно
покажет интерфейс.

Тесты читают файлы, а не поднимают WebView: браузера в этом наборе нет. Зато
инвариант структурный и проверяется точно — HTML разбирается настоящим парсером,
а не регулярками, так что переносом атрибутов или переформатированием его не
обойти.
"""

from __future__ import annotations

from html.parser import HTMLParser
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
ВЕБ = КОРЕНЬ / "web"

#: Исходник и его сгенерированные копии. Исходник обязателен; копии проверяются,
#: если собраны — устаревший бандл в `.app` отдаётся человеку как есть, и
#: правильный `index.html` в репозитории его не спасает.
СТРАНИЦЫ: dict[str, Path] = {
    "исходник": ВЕБ / "index.html",
    "сборка": ВЕБ / "dist" / "index.html",
    "бандл_ios": ВЕБ / "ios" / "App" / "App" / "public" / "index.html",
}


class Голова(HTMLParser):
    """Скрипты и стили из `<head>`, плюс всё, что попало в `<body>`."""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.в_голове = True
        self.скрипты_головы: list[dict[str, str | None]] = []
        self.инлайн_в_теле: list[str] = []
        self._собираем_инлайн = False

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag == "body":
            self.в_голове = False
        значения = dict(attrs)
        if tag == "script":
            if self.в_голове:
                self.скрипты_головы.append(значения)
            elif "src" not in значения:
                self._собираем_инлайн = True

    def handle_endtag(self, tag: str) -> None:
        if tag == "head":
            self.в_голове = False
        if tag == "script":
            self._собираем_инлайн = False

    def handle_data(self, data: str) -> None:
        if self._собираем_инлайн:
            self.инлайн_в_теле.append(data)


def разобрать(путь: Path) -> Голова:
    парсер = Голова()
    парсер.feed(путь.read_text(encoding="utf-8"))
    return парсер


def существующие() -> list[str]:
    """Имена страниц, которые есть на диске: исходник плюс собранные копии."""
    return [имя for имя, путь in СТРАНИЦЫ.items() if путь.is_file()]


def test_исходник_страницы_на_месте():
    """Без него остальные проверки молча выродились бы в пустой набор."""
    assert СТРАНИЦЫ["исходник"].is_file(), f"нет {СТРАНИЦЫ['исходник']}"


@pytest.mark.parametrize("имя", ["исходник", "сборка", "бандл_ios"])
def test_голова_не_ждёт_чужой_сервер(имя: str):
    """Внешний скрипт в `<head>` обязан быть async, defer или module.

    Синхронный — это остановка парсера до ответа. Ответа может не быть: домен
    заблокирован, DNS отвечает, а TCP висит до таймаута. Всё это время у
    человека пустой экран, и никакая обработка ошибок внутри приложения не
    поможет — код приложения ещё не начал выполняться.
    """
    путь = СТРАНИЦЫ[имя]
    if not путь.is_file():
        pytest.skip(f"{имя} не собран — проверять нечего")

    блокирующие = [
        скрипт["src"]
        for скрипт in разобрать(путь).скрипты_головы
        if скрипт.get("src")
        and "async" not in скрипт
        and "defer" not in скрипт
        and (скрипт.get("type") or "").lower() != "module"
    ]
    assert блокирующие == [], (
        f"{путь.relative_to(КОРЕНЬ)}: в <head> синхронные внешние скрипты "
        f"{блокирующие} — пока запрос висит, <body> не разобран и на экране "
        f"нет ничего, даже сообщения об ошибке"
    )


@pytest.mark.parametrize("имя", ["исходник", "сборка", "бандл_ios"])
def test_страж_загрузки_остался_в_теле(имя: str):
    """Страж — последний экран, который может показать хоть что-то.

    Он inline и в `<body>`: из `<head>` ему нечего показывать (тела ещё нет), а
    внешним файлом он не выживет ровно в том случае, для которого написан —
    когда бандл не догрузился.
    """
    путь = СТРАНИЦЫ[имя]
    if not путь.is_file():
        pytest.skip(f"{имя} не собран — проверять нечего")

    инлайн = "\n".join(разобрать(путь).инлайн_в_теле)
    assert "boot-fail-retry" in инлайн, (
        f"{путь.relative_to(КОРЕНЬ)}: в <body> нет стража загрузки — падение "
        f"бандла снова станет чёрным экраном без единого слова"
    )


def test_telegram_sdk_грузится_только_внутри_телеграма():
    """Вне Telegram запрос к telegram.org не нужен и не оправдан.

    В нативном приложении и в обычном браузере `window.Telegram` не появится ни
    при каком ответе сервера: SDK работает только внутри контейнера Telegram.
    Значит вне контейнера этот запрос — чистый риск без выгоды, и его не должно
    быть вовсе, даже асинхронного: он тянет соединение к заблокированному домену
    на каждом старте.
    """
    текст = СТРАНИЦЫ["исходник"].read_text(encoding="utf-8")
    assert "telegram-web-app.js" in текст, (
        "SDK не подключается вовсе — внутри Telegram отвалится вход по initData"
    )
    for признак in ("TelegramWebviewProxy", "tgWebApp"):
        assert признак in текст, (
            f"нет признака контейнера Telegram ({признак}): SDK грузится всем, "
            f"включая нативное приложение, где он бесполезен"
        )


def test_рендер_ждёт_исхода_загрузки_sdk():
    """Иначе внутри Telegram человек получит вход по коду, уже будучи вошедшим.

    `getInitData()` читается при монтировании. Рендер раньше, чем определилась
    судьба SDK, — это гонка: экран входа вместо автоматической авторизации,
    воспроизводится через раз и списывается на «глючит».
    """
    точка = (ВЕБ / "src" / "main.tsx").read_text(encoding="utf-8")
    assert "__telegramSdkReady" in точка, (
        "main.tsx рендерит, не дожидаясь Telegram-SDK — вход по initData "
        "проигрывает гонку загрузке скрипта"
    )
    страница = СТРАНИЦЫ["исходник"].read_text(encoding="utf-8")
    assert "__telegramSdkReady" in страница, (
        "index.html не объявляет __telegramSdkReady, а main.tsx его ждёт — "
        "ожидание выродится в Promise.resolve и гонка вернётся"
    )
