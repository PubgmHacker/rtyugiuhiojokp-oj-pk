"""Возрастной порог — одно число во всём продукте, включая документы.

`MIN_AGE` — не настройка вкуса. Тем же числом продукт отвечает человеку в анкете
(`bot/texts.py`), заявляет его в оферте (`terms.html`), в политике
(`privacy.html`), на лендинге и в описании для поисковиков. Расхождение между
ними — юридическая проблема, а не косметическая: оферта обещает одно, код пускает
другое, и разбираться будут по оферте.

Отдельная ловушка — `APPSTORE.md`. Он утверждал, что онбординг и `terms.html`
говорят «только для лиц старше 18 лет», и на этом успокаивал: рейтинг App Store
18+ якобы совпадает с порогом продукта. В продукте тогда стояло 16, и ревьюер,
открыв `terms.html`, увидел бы ровно то расхождение, от которого документ
предостерегал. Порог с тех пор поднят до 18 и совпадает с рейтингом, но тест
различает два утверждения по-прежнему:

* Возрастной рейтинг App Store пишется как «18+» — это шкала Apple (4+/9+/13+/
  16+/18+), и она не обязана совпадать с порогом регистрации. Такую запись тест
  не трогает.
* Порог регистрации пишется прозой — «с 18 лет», «старше 18 лет», «не менее 18
  полных лет», «младше 18 лет», «вам 18 лет», «от 18 до 99». Каждое такое число
  обязано быть `MIN_AGE` (и `MAX_AGE` для верхней границы) — в любом файле
  продукта, `APPSTORE.md` включительно.

Юридический текст лежит в двух деревьях: `landing/` (публичный сайт) и
`web/public/` (копии, которые отдаёт мини-апп). Проверяются оба — иначе одна
копия тихо расходится с другой, и человек читает не то, что суд.

Помимо прозы есть литералы: бот (`bot/config.py`) и мини-апп
(`web/src/lib/profileOptions.ts` — оттуда границы читают онбординг и экран
редактирования) не импортируют `api/config.py` и держат осознанные копии
границ. Их сверяет test_литералы_клиентов_совпадают_с_конфигом. Туда же
относится закомментированный дефолт в `.env.example`: его копируют в
`.env` руками, и порог, оставшийся в примере, приезжает в чужое окружение
настоящим значением.

Третья запись порога — сокращение «N+» в оглавлениях и описаниях
(`landing/README.md`, `PRODUCT.md`). Это не проза и не литерал, шаблоны
выше её не ловят: `landing/README.md` полгода называл оферту «16+», когда
в самой оферте уже стояло 18. Сверяет test_сокращённый_порог_в_документации,
пропуская строки, где «N+» — не про людей (`Xcode 16+`, шкала Apple).
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]

#: Где продукт говорит о возрасте словами. Пути, которых нет, тест назовёт сам:
#: пропавший файл — это тоже расхождение (текст переехал, порог остался).
ГДЕ_ГОВОРИМ = (
    "landing/index.html",
    "landing/terms.html",
    "landing/privacy.html",
    "landing/support.html",
    "landing/moderation.html",
    "landing/guidelines.html",
    "web/public/terms.html",
    "web/public/privacy.html",
    "web/public/support.html",
    "web/public/moderation.html",
    "web/public/guidelines.html",
    "web/index.html",
    "web/public/manifest.json",
    "web/src/pages/Login.tsx",
    "web/src/pages/Onboarding.tsx",
    "web/src/pages/EditProfile.tsx",
    "bot/texts.py",
    "README.md",
    "APPSTORE.md",
)

#: Проза про нижний порог. «18+» намеренно не подходит ни под один шаблон:
#: это запись рейтинга Apple, а не обещание продукта.
НИЖНИЙ_ПОРОГ = (
    re.compile(r"старше\s+(\d{2})\s+лет"),
    re.compile(r"младше\s+(\d{2})\s+лет"),
    re.compile(r"[Сс]\s+(\d{2})\s+лет"),
    re.compile(r"не\s+менее\s+(\d{2})\s+полных\s+лет"),
    re.compile(r"возрастное\s+ограничение\s+(\d{2})\+"),
    re.compile(r"[Рр]егистрация\s+с\s+(\d{2})\s+лет"),
    re.compile(r"исполнилось\s+(\d{2})\s+лет"),
    re.compile(r"вам\s+(\d{2})\s+лет"),
)

#: Диапазон в подсказке бота: «Укажите возраст от 18 до 99».
ДИАПАЗОН = re.compile(r"от\s+(\d{2})\s+до\s+(\d{2})")


def _порог() -> tuple[int, int]:
    from config import get_settings

    настройки = get_settings()
    return настройки.MIN_AGE, настройки.MAX_AGE


def _заявления(текст: str) -> list[tuple[int, str]]:
    """Все прозаические утверждения о нижнем пороге: (число, что написано)."""
    найдено: list[tuple[int, str]] = []
    for шаблон in НИЖНИЙ_ПОРОГ:
        for совпадение in шаблон.finditer(текст):
            найдено.append((int(совпадение.group(1)), совпадение.group(0)))
    return найдено


def _строка(текст: str, фрагмент: str) -> int:
    позиция = текст.find(фрагмент)
    return текст[:позиция].count("\n") + 1 if позиция >= 0 else 0


@pytest.mark.parametrize("относительный", ГДЕ_ГОВОРИМ)
def test_порог_везде_один(относительный: str):
    """Каждое «с N лет» в продукте — это `MIN_AGE`, иначе оферта врёт коду."""
    минимум, _ = _порог()
    путь = КОРЕНЬ / относительный
    assert путь.exists(), (
        f"{относительный} не найден: текст про возраст мог переехать, а порог "
        f"остаться. Поправьте список ГДЕ_ГОВОРИМ вместе с переездом"
    )

    текст = путь.read_text(encoding="utf-8", errors="ignore")
    чужие = [(n, ф) for n, ф in _заявления(текст) if n != минимум]
    assert not чужие, (
        f"{относительный} обещает возраст, которого нет в MIN_AGE={минимум}: "
        + ", ".join(f"«{ф}» (строка {_строка(текст, ф)})" for _, ф in чужие)
        + ". Оферта и код обязаны говорить одно число"
    )


def test_подсказка_бота_совпадает_с_границами():
    """«от N до M» в тексте ошибки — это MIN_AGE и MAX_AGE, а не два литерала."""
    минимум, максимум = _порог()
    текст = (КОРЕНЬ / "bot" / "texts.py").read_text(encoding="utf-8")
    диапазоны = [(int(a), int(b)) for a, b in ДИАПАЗОН.findall(текст)]
    assert диапазоны, (
        "в bot/texts.py нет подсказки вида «от N до M»: человек, вписавший "
        "возраст неправильно, не узнает допустимые границы"
    )
    неверные = [(a, b) for a, b in диапазоны if (a, b) != (минимум, максимум)]
    assert not неверные, (
        f"bot/texts.py называет границы {неверные}, а код принимает "
        f"({минимум}, {максимум}). Человек упрётся в отказ, следуя подсказке"
    )


def test_appstore_не_путает_рейтинг_с_порогом():
    """Рейтинг «18+» и порог регистрации — разные вещи, и документ обязан их различать.

    Проверяется ровно то, на чём документ однажды соврал: прозаическое
    утверждение о пороге продукта. Запись рейтинга («18+», «рейтинг 18+»,
    шкала Apple) остаётся свободной — она про магазин, а не про регистрацию.
    """
    минимум, _ = _порог()
    текст = (КОРЕНЬ / "APPSTORE.md").read_text(encoding="utf-8")
    чужие = [(n, ф) for n, ф in _заявления(текст) if n != минимум]
    assert not чужие, (
        "APPSTORE.md приписывает продукту порог, которого в нём нет "
        f"(MIN_AGE={минимум}): "
        + ", ".join(f"«{ф}» (строка {_строка(текст, ф)})" for _, ф in чужие)
        + ". Ревьюер откроет terms.html и увидит настоящий порог — "
        "инструкция по подаче обязана называть его честно"
    )
    assert "18+" in текст, (
        "в APPSTORE.md пропало требование рейтинга 18+. Apple ставит сервисам "
        "знакомств с чатом именно его, и в анкете рейтинга это обязательный пункт"
    )


#: Литералы в клиентах: бот и мини-апп не читают api/config.py, у них
#: осознанные копии границ. Копия без стража — это будущий рассинхрон.
ЛИТЕРАЛЫ_КЛИЕНТОВ = (
    ("bot/config.py", re.compile(r"^MIN_AGE:\s*int\s*=\s*(\d+)", re.M), "MIN_AGE"),
    ("bot/config.py", re.compile(r"^MAX_AGE:\s*int\s*=\s*(\d+)", re.M), "MAX_AGE"),
    ("web/src/lib/profileOptions.ts", re.compile(r"const\s+MIN_AGE\s*=\s*(\d+)"), "MIN_AGE"),
    ("web/src/lib/profileOptions.ts", re.compile(r"const\s+MAX_AGE\s*=\s*(\d+)"), "MAX_AGE"),
)


def test_литералы_клиентов_совпадают_с_конфигом():
    """Копии MIN_AGE/MAX_AGE в боте и мини-аппе равны границам из конфига API.

    Пул анкет общий: возраст, который бот пустил в регистрацию, дальше
    валидирует API по своим границам. Разъедутся числа — человек пройдёт
    анкету в одном канале и получит отказ в другом, не понимая за что.
    """
    границы = dict(zip(("MIN_AGE", "MAX_AGE"), _порог()))
    for относительный, шаблон, имя in ЛИТЕРАЛЫ_КЛИЕНТОВ:
        текст = (КОРЕНЬ / относительный).read_text(encoding="utf-8")
        найдено = шаблон.search(текст)
        assert найдено, (
            f"в {относительный} не нашёлся литерал {имя}: либо он переехал, "
            f"либо его убрали — поправьте ЛИТЕРАЛЫ_КЛИЕНТОВ вместе с кодом"
        )
        assert int(найдено.group(1)) == границы[имя], (
            f"{относительный} держит {имя}={найдено.group(1)}, а конфиг API — "
            f"{границы[имя]}. Пул анкет общий, границы обязаны совпадать"
        )


def test_копия_в_ios_обёртке_не_протухла():
    """`web/ios/App/App/public` — то, что реально уезжает в App Store.

    Каталог кладёт `cap sync` из собранного `dist`. tools/ios-build.sh
    пересобирает его сам, но документированный путь «Product → Archive»
    в Xcode — нет, и однажды здесь уже лежала оферта со старым порогом.
    Нет каталога (свежий чекаут без сборки) — пропуск; есть — он обязан
    называть тот же возраст, что исходники.
    """
    копия = КОРЕНЬ / "web" / "ios" / "App" / "App" / "public"
    if not копия.exists():
        pytest.skip("iOS-обёртка ещё не собиралась — сверять нечего")
    минимум, _ = _порог()
    for имя in (
        "terms.html", "privacy.html", "guidelines.html",
        "index.html", "manifest.json",
    ):
        файл = копия / имя
        assert файл.exists(), (
            f"в iOS-копии нет {имя}: cap sync не докопировал web/public — "
            "пересоберите обёртку (tools/ios-build.sh)"
        )
        текст = файл.read_text(encoding="utf-8", errors="ignore")
        чужие = [(n, ф) for n, ф in _заявления(текст) if n != минимум]
        assert not чужие, (
            f"iOS-обёртка везёт устаревший {имя}: "
            + ", ".join(f"«{ф}»" for _, ф in чужие)
            + f" при MIN_AGE={минимум}. Прогоните npm run build и npx cap "
            "sync ios (или tools/ios-build.sh) перед архивом"
        )


def test_две_копии_юридического_текста_говорят_одно():
    """`landing/` и `web/public/` — две копии оферты; разойтись им нельзя.

    Человек открывает ту, которую ему отдали: из бота — лендинг, из мини-аппа —
    копию из `web/public`. Если в одной порог поправили, а в другой нет,
    расхождение обнаружится на том, кто прочитал вторую.
    """
    for имя in ("terms.html", "privacy.html"):
        сайт = КОРЕНЬ / "landing" / имя
        аппа = КОРЕНЬ / "web" / "public" / имя
        assert сайт.exists() and аппа.exists(), f"{имя} есть не в обоих деревьях"
        первое = {n for n, _ in _заявления(сайт.read_text(encoding="utf-8"))}
        второе = {n for n, _ in _заявления(аппа.read_text(encoding="utf-8"))}
        assert первое == второе, (
            f"landing/{имя} и web/public/{имя} называют разный возраст: "
            f"{sorted(первое)} против {sorted(второе)}. Править нужно обе копии"
        )


#: Закомментированный дефолт в примере окружения. Человек копирует `.env.example`
#: в `.env` и раскомментирует строку — порог из примера становится настоящим.
ПРИМЕР_ОКРУЖЕНИЯ = re.compile(r"^#\s*MIN_AGE=(\d+)", re.M)


def test_пример_окружения_называет_тот_же_порог():
    """`.env.example` — инструкция, по которой поднимают новое окружение.

    Строка `# MIN_AGE=…` там закомментирована, но её раскомментируют не глядя:
    это и есть смысл примера. Порог, оставшийся в нём от прошлой политики,
    молча поднимет сервис, который пускает людей младше, чем обещает оферта.
    """
    минимум, _ = _порог()
    текст = (КОРЕНЬ / ".env.example").read_text(encoding="utf-8")
    найдено = ПРИМЕР_ОКРУЖЕНИЯ.search(текст)
    assert найдено, (
        "в .env.example пропала строка `# MIN_AGE=…`: пример окружения "
        "перестал называть порог, и новое окружение поднимут наугад"
    )
    assert int(найдено.group(1)) == минимум, (
        f".env.example предлагает MIN_AGE={найдено.group(1)}, а код держит "
        f"{минимум}. По этому файлу поднимают окружения — он обязан быть верным"
    )


#: Где порог записан сокращением «N+»: оглавления и описания продукта.
ГДЕ_СОКРАЩАЕМ = (
    "landing/README.md",
    "PRODUCT.md",
    "README.md",
)

#: «N+» не всегда про людей: требования тулинга и шкала возрастных рейтингов
#: Apple пишутся так же. Строки с ними тест пропускает — иначе `Xcode 16+`
#: в README придётся вечно объяснять.
НЕ_ПРО_ЛЮДЕЙ = re.compile(
    r"Xcode|Node|npm|Python|Swift|CocoaPods|шкал\w*\s+Apple|4\+\s*/"
)
СОКРАЩЁННЫЙ_ПОРОГ = re.compile(r"(\d{2})\+")


@pytest.mark.parametrize("относительный", ГДЕ_СОКРАЩАЕМ)
def test_сокращённый_порог_в_документации(относительный: str):
    """«18+» в описании продукта — то же обещание, что «с 18 лет» в оферте.

    Оглавление лендинга описывало `terms.html` как «16+» уже после того, как
    порог подняли до 18: прозаические шаблоны сокращение не ловят, и
    расхождение прожило до ручной вычитки. Читатель оглавления при этом
    узнаёт возраст именно оттуда.
    """
    минимум, _ = _порог()
    путь = КОРЕНЬ / относительный
    assert путь.exists(), (
        f"{относительный} не найден: описание продукта могло переехать. "
        f"Поправьте ГДЕ_СОКРАЩАЕМ вместе с переездом"
    )

    чужие: list[str] = []
    for номер, строка in enumerate(
        путь.read_text(encoding="utf-8", errors="ignore").splitlines(), start=1
    ):
        if НЕ_ПРО_ЛЮДЕЙ.search(строка):
            continue
        for совпадение in СОКРАЩЁННЫЙ_ПОРОГ.finditer(строка):
            if int(совпадение.group(1)) != минимум:
                чужие.append(f"«{совпадение.group(0)}» (строка {номер})")
    assert not чужие, (
        f"{относительный} называет возраст, которого нет в MIN_AGE={минимум}: "
        + ", ".join(чужие)
        + ". Сокращение «N+» читают как порог продукта — оно обязано совпадать"
    )
