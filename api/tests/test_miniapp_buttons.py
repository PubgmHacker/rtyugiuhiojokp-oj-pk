"""Кнопки в мини-апп: где HTTPS обязателен, а где сообщение не дойдёт вовсе.

`web_app` Telegram принимает только по HTTPS — и при нарушении отклоняет
СООБЩЕНИЕ ЦЕЛИКОМ (`Bad Request: BUTTON_TYPE_INVALID`), а не отдельную кнопку.
Одна такая кнопка в `main_kb()` означала, что на HTTP-конфигурации главное меню
не приходит: ни текста, ни остальных пяти кнопок. Хуже всего, что это ровно та
конфигурация, где `start_app_kb()` осознанно уводит человека в анкету бота —
рассчитывая, что меню придёт следом.

Отдельно проверяется петля. `http://localhost:5173` в чужом Telegram — адрес
самого телефона получателя: там ничего не слушает, и кнопка мертва у всех, кроме
машины с поднятым vite. Такая кнопка не должна уезжать в сообщение ни в каком
виде, включая обычную ссылку.

Проверки идут по поведению настоящих клавиатур с перечитанным `config.py`
(`скрипты_бота/кнопки_мини_аппа.py`), а не по тексту исходников: вызов
`webapp_https()` легко поставить не в ту ветку, а исходник останется похожим на
правильный.
"""

from __future__ import annotations

import pytest

from tests.test_query_scale import прогнать_в_боте

ПЕТЛИ = ("localhost", "127.0.0.1", "0.0.0.0", "::1")


@pytest.fixture(scope="module")
def кнопки() -> dict:
    """Один прогон на модуль: внутри перебор SITE_URL и живой хендлер деки."""
    return прогнать_в_боте("кнопки_мини_аппа.py")


def _все(набор: dict) -> list[dict]:
    return [к for клава in набор.values() for к in клава]


def test_web_app_только_по_https(кнопки):
    """Кнопка web_app по HTTP убивает всё сообщение, а не себя."""
    for случай, набор in кнопки["клавиатуры"].items():
        for имя, клавиатура in набор.items():
            for кнопка in клавиатура:
                if кнопка["вид"] != "web_app":
                    continue
                assert кнопка["адрес"].startswith("https://"), (
                    f"{случай}/{имя}: web_app на {кнопка['адрес']} — Telegram "
                    f"отклонит сообщение целиком, человек не увидит ничего"
                )


def test_петля_не_уезжает_в_чужой_телеграм(кнопки):
    """На петле кнопки в мини-апп нет вовсе — ни web_app, ни ссылкой."""
    for случай in ("петля", "петля_по_ip"):
        for кнопка in _все(кнопки["клавиатуры"][случай]):
            адрес = кнопка["адрес"] or ""
            assert not any(п in адрес for п in ПЕТЛИ), (
                f"{случай}: кнопка «{кнопка['текст']}» ведёт на {адрес} — "
                f"это адрес телефона получателя, а не наш сервер"
            )


def test_старт_не_упирается_в_тупик(кнопки):
    """`/start` обязан вести дальше при любом SITE_URL.

    На петле — в анкету бота (`onb:start`), по HTTP — ссылкой в браузер, по
    HTTPS — мини-аппом. Пустая клавиатура здесь означала бы, что онбординг
    заканчивается кнопкой, которая ничего не делает.
    """
    ожидание = {
        "петля": "callback",
        "петля_по_ip": "callback",
        "http_домен": "url",
        "http_ip": "url",
        "https_домен": "web_app",
        "туннель": "web_app",
    }
    for случай, вид in ожидание.items():
        клавиатура = кнопки["клавиатуры"][случай]["start_app_kb"]
        assert len(клавиатура) == 1, f"{случай}: у «Начать» не одна кнопка: {клавиатура}"
        assert клавиатура[0]["вид"] == вид, (
            f"{случай}: «Начать» стала {клавиатура[0]}, ожидалось {вид}"
        )
        if вид == "callback":
            assert клавиатура[0]["адрес"] == "onb:start", (
                f"{случай}: откат «Начать» ведёт не в анкету бота: {клавиатура[0]}"
            )


def test_меню_приходит_целиком_на_http(кнопки):
    """Остальные кнопки меню не должны страдать из-за недоступного мини-аппа."""
    for случай in кнопки["клавиатуры"]:
        меню = кнопки["клавиатуры"][случай]["main_kb"]
        адреса = {к["адрес"] for к in меню}
        for обязательный in ("dating:start", "profile:view", "matches:list", "premium", "referral"):
            assert обязательный in адреса, (
                f"{случай}: в главном меню нет {обязательный}: {адреса}"
            )


def test_доступный_мини_апп_остаётся_кнопкой(кнопки):
    """HTTP без петли — не повод терять вход в приложение целиком.

    Тихо выкинуть кнопку на стенде значило бы «починить» падение сообщения
    удалением функции: настройки поиска, которых в боте нет, стали бы
    недостижимы.
    """
    пути = {
        "main_kb": "/discover",
        "no_more_profiles_kb": "/discover",
        "profile_kb": "/profile",
    }
    for случай in ("http_домен", "http_ip", "https_домен", "туннель"):
        for имя, путь in пути.items():
            ведут = [
                к for к in кнопки["клавиатуры"][случай][имя]
                if к["вид"] in ("web_app", "url") and (к["адрес"] or "").endswith(путь)
            ]
            assert len(ведут) == 1, (
                f"{случай}/{имя}: кнопки в мини-апп на {путь} нет "
                f"(или их больше одной): {кнопки['клавиатуры'][случай][имя]}"
            )


def test_текст_обещает_ровно_то_что_есть_рядом(кнопки):
    """«Откройте приложение» без кнопки в приложение — обещание вслепую.

    Текст и клавиатура собираются в разных модулях (`texts.py` и
    `keyboards.py`), поэтому расхождение видно только на настоящем хендлере с
    пустой декой.
    """
    for случай, отправленное in кнопки["дека"].items():
        текст = отправленное["текст"].lower()
        зовёт = "приложение" in текст or "настройки поиска" in текст
        ведёт = any(
            к["вид"] in ("web_app", "url") for к in отправленное["кнопки"]
        )
        assert зовёт == ведёт, (
            f"{случай}: текст {'зовёт' if зовёт else 'не зовёт'} в приложение, "
            f"а кнопка {'есть' if ведёт else 'отсутствует'}: {отправленное}"
        )
        assert "← Меню" in [к["текст"] for к in отправленное["кнопки"]], (
            f"{случай}: из пустой деки нет выхода в меню: {отправленное}"
        )
