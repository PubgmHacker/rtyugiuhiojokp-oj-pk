"""Витрина команд бота: заявленное в Telegram, работающее и описанное в /help.

Меню «/» в поле ввода собирается ровно из `set_my_commands`. Незаявленная
команда есть только у тех, кому её назвали словами: `/menu` в списке не было, и
единственный вход в главное меню оставался ненаходимым — притом что `/help`
обещал меню по `/start`, а `/start` открывал выбор языка. Обратная ошибка так
же плоха: заявленная команда без обработчика видна, нажимается и молчит.

Три места обязаны совпадать: `bot.КОМАНДЫ`, настоящие обработчики в `Dispatcher`
и текст `/help`. Сверка идёт по факту — команды вычитываются из фильтров
диспетчера, собранного продакшеновой `собрать_dispatcher()`: фильтр можно
навесить не на тот роутер, и исходник останется похожим на правильный.

Здесь же поведение `/start` у вернувшегося: язык спрашивается один раз, а
повторный `/start` с готовой анкетой обязан отдавать меню, а не гнать через
онбординг заново — /start самая частая команда в Telegram, и четыре сообщения
вместо одного человек получал именно на ней. Прогон настоящий:
`Dispatcher.feed_update` с подменённой базой (`скрипты_бота/команды_бота.py`).
"""

from __future__ import annotations

import re

import pytest

from tests.test_query_scale import прогнать_в_боте

#: Команды, которым в витрине быть не положено. Пустой набор — осознанно:
#: каждая работающая команда сейчас заявлена. Появится админская или
#: техническая — её место здесь, с причиной в комментарии, а не в тишине.
БЕЗ_ВИТРИНЫ: frozenset[str] = frozenset()

#: Ограничения Bot API на `BotCommand`: команда — 1–32 символа из [a-z0-9_],
#: описание — 1–256. Нарушение отклоняет весь `set_my_commands`, то есть
#: витрина не обновляется целиком, из-за одной опечатки.
КОМАНДА_РЕ = re.compile(r"^[a-z0-9_]{1,32}$")

#: Упоминание команды в тексте: слэш, не приклеенный к слову, схеме или пути.
#: Иначе «https://…» и «support@simp.app/help» читались бы как команды.
УПОМИНАНИЕ_РЕ = re.compile(r"(?<![\w:/.])/([a-z][a-z0-9_]{0,31})\b")

#: Разметка выкусывается до поиска: `/help` отправляется с parse_mode=HTML, и
#: закрывающий тег `</b>` иначе читается как команда «b».
ТЕГ_РЕ = re.compile(r"<[^>]+>")

ФЛАГИ_ЯЗЫКОВ = ("🇷🇺", "🇬🇧", "🇺🇿", "🇪🇸", "🇹🇷", "🇮🇩", "🇨🇳")


@pytest.fixture(scope="module")
def витрина() -> dict:
    """Один прогон на модуль: внутри сборка диспетчера и два живых /start."""
    return прогнать_в_боте("команды_бота.py")


def _заявленные(витрина: dict) -> list[str]:
    return [к["команда"] for к in витрина["заявленные"]]


def _сообщения(шаги: list[dict]) -> list[dict]:
    """Только отправленное человеку: текстом или картинкой с подписью."""
    return [ш for ш in шаги if ш["метод"] in ("SendMessage", "SendPhoto")]


def test_каждая_заявленная_команда_работает(витрина):
    """Команда из меню «/» обязана иметь обработчик."""
    обработчики = витрина["обработчики"]
    мёртвые = [к for к in _заявленные(витрина) if к not in обработчики]
    assert not мёртвые, (
        f"заявлены в Telegram, но не обрабатываются: {мёртвые} — человек видит "
        f"их в меню «/», нажимает и не получает ничего"
    )


def test_рабочая_команда_не_прячется_от_человека(витрина):
    """Обработчик без заявки — функция, о которой никто не узнает."""
    заявлено = set(_заявленные(витрина))
    спрятанные = sorted(
        к for к in витрина["обработчики"] if к not in заявлено and к not in БЕЗ_ВИТРИНЫ
    )
    assert not спрятанные, (
        f"работают, но не заявлены: {спрятанные} — в меню «/» их нет, найти "
        f"можно только случайно. Либо в bot.КОМАНДЫ, либо в БЕЗ_ВИТРИНЫ с причиной"
    )


def test_заявка_принимается_bot_api(витрина):
    """Одна опечатка в списке отклоняет `set_my_commands` целиком."""
    for к in витрина["заявленные"]:
        assert КОМАНДА_РЕ.match(к["команда"]), (
            f"«{к['команда']}»: Bot API ждёт 1–32 символа из [a-z0-9_]"
        )
        описание = (к["описание"] or "").strip()
        assert 1 <= len(описание) <= 256, (
            f"/{к['команда']}: описание длиной {len(описание)} — витрина не обновится"
        )


def test_help_описывает_ровно_заявленное(витрина):
    """`/help` — второй источник правды о командах, и он обязан совпадать."""
    заявлено = set(_заявленные(витрина))
    в_справке = set(УПОМИНАНИЕ_РЕ.findall(ТЕГ_РЕ.sub(" ", витрина["help"])))

    молчком = sorted(заявлено - в_справке)
    assert not молчком, (
        f"есть в меню «/», но не описаны в /help: {молчком} — справка обязана "
        f"объяснять всё, что человек видит"
    )

    призраки = sorted(в_справке - заявлено - БЕЗ_ВИТРИНЫ)
    assert not призраки, (
        f"/help обещает несуществующее: {призраки} — так и появилось «главное "
        f"меню по /start», которого не было"
    )


def test_повторный_старт_отдаёт_меню(витрина):
    """У вернувшегося с готовой анкетой /start — это меню, а не опрос заново."""
    шаги = _сообщения(витрина["старт_с_анкетой"])
    assert шаги, "/start с готовой анкетой не ответил ничего"
    assert len(шаги) == 1, (
        f"на /start ушло {len(шаги)} сообщений: "
        f"{[ш['текст'][:40] for ш in шаги]} — вернувшемуся хватает меню"
    )

    ответ = шаги[0]
    кнопки = ответ["кнопки"]
    assert "🔍 Смотреть анкеты" in кнопки, (
        f"в ответе на /start нет главного действия, только: {кнопки}"
    )
    assert витрина["сетка_языков"] not in ответ["текст"], (
        "/start снова спрашивает язык у того, кто его уже выбрал"
    )
    assert not any(ф in " ".join(кнопки) for ф in ФЛАГИ_ЯЗЫКОВ), (
        f"под меню приехала сетка языков: {кнопки}"
    )


def test_первый_старт_спрашивает_язык(витрина):
    """Без анкеты /start обязан начинать онбординг, а не выдавать меню."""
    шаги = _сообщения(витрина["старт_без_анкеты"])
    assert шаги, "/start без анкеты не ответил ничего — человеку нечего нажать"

    ответ = шаги[0]
    assert витрина["сетка_языков"] in ответ["текст"], (
        f"первое сообщение — не выбор языка, а «{ответ['текст'][:60]}»"
    )
    assert any(ф in " ".join(ответ["кнопки"]) for ф in ФЛАГИ_ЯЗЫКОВ), (
        f"выбор языка без кнопок языков: {ответ['кнопки']}"
    )
