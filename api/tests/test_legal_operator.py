"""Кто отвечает за сервис — одним текстом во всех документах.

Наименование оператора и юрисдикция — единственный юридический факт, которого в
репозитории нет: организация ещё не зарегистрирована (`landing/README.md`, пункт
5). Опасен не сам пропуск, а то, каким он был раньше: §12 условий отсылала к
«праву страны регистрации оператора», не называя оператора, — формулировка
выглядела законченной и не означала ничего. Одновременно «кто оператор» было
описано в двух документах двумя разными фразами.

Поэтому текст об операторе теперь один и тот же блок между маркерами
`ОПЕРАТОР:НАЧАЛО` и `ОПЕРАТОР:КОНЕЦ`, вставленный в оба документа, а этот модуль
держит инварианты, которые иначе разъедутся молча:

* блок есть в обоих документах и совпадает посимвольно;
* пока реквизитов нет, об этом сказано явно и видимой плашкой, а не общей
  фразой, которую никто не заметит;
* признак незаполненности стоит в обоих документах сразу — снять его можно
  только вместе, то есть только по-настоящему заполнив;
* когда его снимут, в блоке обязаны появиться настоящие реквизиты: тест
  переворачивается и начинает требовать их, а не разрешать пустоту;
* пункт в `landing/README.md` жив, пока жива заглушка.

Копии в `web/public` этот модуль не проверяет — их совпадение с лендингом
сторожит `test_legal_sync.py`, и второй перечень файлов здесь был бы третьим
местом с тем же списком.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
ЛЕНДИНГ = КОРЕНЬ / "landing"

#: Документы, в которых обязан быть блок. Условия — потому что это сторона
#: договора, политика — потому что это оператор персональных данных.
ДОКУМЕНТЫ = ("terms.html", "privacy.html")

#: Признак того, что реквизиты ещё не подставлены. Один и тот же атрибут в
#: разметке обоих документов — по нему и ищем, а не по словам в тексте: слова
#: перепишут при первой же правке стиля, атрибут переживёт.
МАРКЕР = 'data-legal-pending="operator-entity"'

_БЛОК = re.compile(
    r"<!-- ОПЕРАТОР:НАЧАЛО.*?<!-- ОПЕРАТОР:КОНЕЦ -->",
    re.S,
)

#: Адреса, по которым к оператору можно обратиться. Заявлены в блоке — значит
#: обязаны быть теми же, что в остальных документах.
АДРЕСА = ("support@simp.app", "privacy@simp.app", "safety@simp.app")


def _текст(имя: str) -> str:
    путь = ЛЕНДИНГ / имя
    assert путь.is_file(), f"нет landing/{имя}"
    return путь.read_text(encoding="utf-8")


def _блок(имя: str) -> str:
    найденный = _БЛОК.search(_текст(имя))
    assert найденный, (
        f"в landing/{имя} нет блока между ОПЕРАТОР:НАЧАЛО и ОПЕРАТОР:КОНЕЦ. "
        f"Пока его нет, документ не называет, кто отвечает за сервис, — и ни "
        f"одна проверка ниже ничего не сторожит"
    )
    return найденный.group(0)


@pytest.mark.parametrize("имя", ДОКУМЕНТЫ)
def test_блок_оператора_есть(имя: str):
    """Оба документа обязаны называть оператора, а не только один из них."""
    блок = _блок(имя)
    assert 'id="operator"' in блок, (
        f"в блоке landing/{имя} нет якоря id=\"operator\": §12 условий ссылается "
        f"на него ссылкой #operator, и она станет битой"
    )


def test_блок_совпадает_посимвольно():
    """Две версии того, кто отвечает за сервис, — хуже одной неполной.

    Расхождение здесь не ломает страницу и не видно в браузере: оба текста
    выглядят настоящими, а какой действует — вопрос к юристу, которого нет.
    """
    варианты = {имя: _блок(имя) for имя in ДОКУМЕНТЫ}
    первый, *остальные = ДОКУМЕНТЫ
    for имя in остальные:
        assert варианты[имя] == варианты[первый], (
            f"блок оператора в landing/{имя} разошёлся с landing/{первый}. "
            f"Правьте один и переносите целиком: это один текст в двух файлах"
        )


@pytest.mark.parametrize("имя", ДОКУМЕНТЫ)
def test_адреса_блока_настоящие(имя: str):
    """Адрес, названный единственным способом связи, обязан быть тем же."""
    блок = _блок(имя)
    for адрес in АДРЕСА:
        assert f"mailto:{адрес}" in блок, (
            f"в блоке оператора landing/{имя} нет {адрес}. Блок объявлен "
            f"единственным перечнем контактов — пропавший адрес человек уже "
            f"нигде не найдёт"
        )


def test_маркер_заглушки_стоит_во_всех_документах_сразу():
    """Снять заглушку можно только везде одновременно.

    Иначе получается худший из вариантов: в условиях реквизиты названы, в
    политике всё ещё «уточняются», и человек не знает, какому документу верить.
    """
    где = {имя for имя in ДОКУМЕНТЫ if МАРКЕР in _блок(имя)}
    assert где in (set(), set(ДОКУМЕНТЫ)), (
        f"признак незаполненных реквизитов остался только в {sorted(где)}, "
        f"а в остальных документах снят. Блок один — состояние обязано быть "
        f"одно"
    )


def test_пока_реквизитов_нет_об_этом_сказано_плашкой():
    """Незаполненность обязана быть видна глазом, а не спрятана в абзаце.

    Ровно так пропуск и жил незамеченным: общая формулировка про «право страны
    регистрации оператора» читалась как готовый юридический текст.
    """
    if МАРКЕР not in _блок(ДОКУМЕНТЫ[0]):
        pytest.skip("реквизиты заполнены — проверять нечего")
    for имя in ДОКУМЕНТЫ:
        блок = _блок(имя)
        абзац = re.search(rf"<p([^>]*){re.escape(МАРКЕР)}([^>]*)>", блок)
        assert абзац, f"в landing/{имя} маркер стоит не на абзаце"
        классы = абзац.group(1) + абзац.group(2)
        assert "callout" in классы, (
            f"в landing/{имя} предупреждение о реквизитах — обычный абзац. "
            f"Нужна плашка (class=\"callout callout--warn\"): незаметная "
            f"оговорка равна её отсутствию"
        )


def test_заполненные_реквизиты_действительно_заполнены():
    """Обратная сторона: маркер снят — значит реквизиты обязаны быть.

    Без этого снять плашку можно было бы одной строкой, ничего не подставив, и
    документ вернулся бы к исходному состоянию — только уже без предупреждения.
    """
    if МАРКЕР in _блок(ДОКУМЕНТЫ[0]):
        pytest.skip("реквизиты ещё не заполнены — это отражено маркером")
    for имя in ДОКУМЕНТЫ:
        блок = _блок(имя)
        # Организационно-правовая форма и номер записи в реестре: без них
        # «наименование» остаётся тем же «командой Симп», что и было.
        assert re.search(r"(ООО|ИП|АО|LLC|Ltd|Inc|GmbH|OÜ|FZ-LLC)", блок), (
            f"в landing/{имя} снят признак заглушки, но наименование "
            f"юридического лица так и не появилось"
        )
        assert re.search(r"(ОГРН|ОГРНИП|ИНН|рег\.|registration no|company no)", блок, re.I), (
            f"в landing/{имя} нет регистрационного номера оператора"
        )


def test_условия_не_ссылаются_на_неназванную_юрисдикцию():
    """§12 обязана разрешаться в что-то конкретное уже сегодня.

    Прежняя редакция отсылала к праву страны регистрации оператора, которого не
    называла: условие без применимого права — это отсутствие условия, но
    выглядит оно как его наличие.
    """
    текст = _текст("terms.html")
    раздел = re.search(r"<h2>12\..*?(?=<!-- ОПЕРАТОР:НАЧАЛО)", текст, re.S)
    assert раздел, "в landing/terms.html не нашлась §12 о применимом праве"
    тело = раздел.group(0)
    assert 'href="#operator"' in тело, (
        "§12 не ссылается на блок оператора: читатель не найдёт, чья "
        "юрисдикция имеется в виду"
    )

    if МАРКЕР not in _блок("terms.html"):
        return  # Юрисдикция названа в блоке — оговорка на переходный период не нужна.

    # Именно привязку правила к незаполненности, а не просто слова «постоянного
    # проживания» где-то в разделе: первый абзац говорит о правах потребителя и
    # содержит их сам по себе, поэтому остался бы на месте, даже если правило о
    # переходном периоде исчезло. Проверка «есть ли эти слова в §12» на такой
    # правке молчала — что и показала мутация.
    оговорка = re.search(
        r"Пока[^.]{0,80}не опубликован[^.]{0,140}постоянного проживания", тело, re.S
    )
    assert оговорка, (
        "в §12 нет правила на переходный период: пока реквизиты оператора не "
        "опубликованы, применимым правом обязано быть право страны постоянного "
        "проживания человека. Иначе раздел снова отсылает к юрисдикции, которую "
        "документ не называет, — то есть ни к какой"
    )


def test_readme_помнит_про_заглушку():
    """Пункт в README жив, пока жива заглушка, и снимается вместе с ней."""
    readme = (ЛЕНДИНГ / "README.md").read_text(encoding="utf-8")
    заглушка_стоит = МАРКЕР in _блок(ДОКУМЕНТЫ[0])
    упомянуто = "реквизит" in readme.lower()
    assert заглушка_стоит == упомянуто, (
        "README и документы разошлись: "
        + (
            "реквизиты не заполнены, но README об этом молчит — перед публикацией "
            "про них никто не вспомнит"
            if заглушка_стоит
            else "реквизиты заполнены, а README всё ещё требует их подставить"
        )
    )
