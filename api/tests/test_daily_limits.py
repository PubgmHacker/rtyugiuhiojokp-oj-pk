def test_слот_возвращается_по_истечении_окна(лимиты):
    """Часового пояса пользователя у нас нет, поэтому окно скользящее.

    «В полночь по Москве» для половины базы неправда, а «через 24 часа после
    первого израсходованного» — правда для всех.
    """
    assert лимиты["лайк_за_окном_прошёл"], (
        f"вчерашние лайки всё ещё занимают квоту: {лимиты}"
    )
    assert лимиты["мэтч_за_окном_открылся"], (
        f"вчерашние открытия всё ещё занимают квоту: {лимиты}"
    )
    # Расход считается ТОЛЬКО внутри окна: вчерашние строки лежат в базе, но
    # в счёт не идут — здесь по единице на каждое сегодняшнее действие
    assert лимиты["лайков_в_окне"] == 1, (
        f"в расход лайков попали строки из прошлого окна: {лимиты}"
    )
    assert лимиты["просмотров_в_окне"] == 1, (
        f"в расход открытий попали строки из прошлого окна: {лимиты}"
    )


def test_старый_мэтч_переоткрывается_без_второй_записи(лимиты):
    """Отметка продлевается на месте, а не дублируется.

    Пара (user_id, match_id) уникальна: вторая вставка — это IntegrityError на
    открытии чата, который человек уже открывал вчера.
    """
    assert лимиты["старый_мэтч_переоткрылся"], (
        f"мэтч из прошлого окна не открывается заново: {лимиты}"
    )
    assert лимиты["просмотров_в_базе_после_окна"] == лимиты["лимит_мэтчей"] + 1, (
        f"открытий в базе больше, чем строк-мэтчей — отметка продублирована "
        f"вместо продления: {лимиты}"
    )


