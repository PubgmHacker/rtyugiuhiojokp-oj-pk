def test_бесплатному_открываются_все_мэтчи_внутри_нормы(лимиты):
    """Последнее открытие внутри квоты разрешено.

    Здесь жила ошибка: `open_match` возвращал состояние ПОСЛЕ записи, а
    вызывающий читал отказ из `exhausted`. Третье открытие из трёх проходило,
    оставляло «осталось 0» — и тем самым выглядело как отказ. Человеку обещали
    три мэтча, а показывали два.
    """
    assert лимиты["закрыт_внутри_квоты_на"] is None, (
        f"мэтч внутри суточной нормы пришёл под замком: {лимиты}"
    )
    assert лимиты["просмотров_в_базе"] == лимиты["лимит_мэтчей"], (
        f"открытий записано не столько, сколько разрешено: {лимиты}"
    )


def test_мэтч_сверх_нормы_приходит_без_признаков_собеседника(лимиты):
    """Замок обязан скрывать, а не намекать.

    Имя, фото или город в «закрытом» ответе выдают даром именно то, за что
    предлагается подписка, и любой из них превращает лимит в декорацию.
    """
    assert лимиты["сверх_квоты_закрыт"], f"мэтч сверх нормы открылся: {лимиты}"
    assert лимиты["в_замке_нет_имени"], f"в закрытом мэтче пришло имя: {лимиты}"
    assert лимиты["в_замке_нет_фото"], f"в закрытом мэтче пришло фото: {лимиты}"
    assert лимиты["мэтч_сверх_квоты_лимит"] == лимиты["лимит_мэтчей"], (
        f"в замке назван не тот лимит: {лимиты}"
    )
    assert лимиты["мэтч_сверх_квоты_есть_reset"], (
        f"в замке нет времени возврата открытия: {лимиты}"
    )


def test_повторный_вход_в_открытый_чат_не_тратит_слот(лимиты):
    """Открытый мэтч остаётся открытым до конца окна.

    Иначе выход и повторный вход в тот же чат съедали бы квоту, и «три мэтча в
    сутки» означало бы «три нажатия в сутки». Проверка идёт при УЖЕ потраченной
    квоте — именно в этом состоянии идемпотентность и ломалась.
    """
    assert лимиты["повтор_открыт"], (
        f"повторный вход в уже открытый чат закрыт лимитом: {лимиты}"
    )
    assert лимиты["повтор_с_именем"] == "Собеседник 1", (
        f"при повторном входе анкета собеседника не пришла: {лимиты}"
    )


def test_проверка_участия_и_пуш_не_тратят_открытия(лимиты):
    """`spend=False` — путь без списания, но с тем же замком.

    К партнёру ведут четыре пути (открыть чат, отправить сообщение, подсказка,
    пуш о мэтче). Списывать на всех — значит терять квоту от прилетевшего
    события, которого человек не открывал; не проверять замок ни на одном —
    значит отдать анкету в обход лимита. Нужно ровно так: не тратим, но
    закрытый мэтч закрыт.
    """
    assert лимиты["без_траты_открыт"], (
        f"уже открытый мэтч не отдаётся без списания: {лимиты}"
    )
    assert лимиты["закрытый_без_траты_закрыт"], (
        f"закрытый мэтч утекает через путь без списания: {лимиты}"
    )


def test_список_мэтчей_не_тратит_квоту_и_редактируется_сервером(лимиты):
    """Список — витрина подписки: мэтчи видны, имена закрытых скрыты.

    Показ списка не тратит открытия (иначе один заход сжигал бы всю квоту), а
    закрытые строки редактируются на сервере: спрятать имя на клиенте нельзя —
    оно уже пришло, и его видно в трафике.
    """
    assert лимиты["закрытых_до_открытий"] == 0, (
        f"мэтчи закрыты до первого открытия — квота тратится на список: {лимиты}"
    )
    assert лимиты["сводка_лайки_осталось"] == лимиты["лимит_лайков"], (
        f"открытие мэтчей списало лайки: {лимиты}"
    )
    assert лимиты["открытые_с_именами"], (
        f"открытый мэтч потерял имя собеседника: {лимиты}"
    )
    assert лимиты["имена_закрытых"] == ["Скрыто"], (
        f"в закрытых строках списка осталось имя: {лимиты}"
    )
    assert лимиты["закрытые_остались_в_списке"], (
        f"закрытые мэтчи исчезли из списка вместо замка: {лимиты}"
    )
    assert лимиты["закрытых_после"] == лимиты["всего_в_списке"] - лимиты["лимит_мэтчей"], (
        f"закрытых в списке не столько, сколько мэтчей сверх нормы: {лимиты}"
    )


def test_лимит_не_подменил_проверку_участия(лимиты):
    """Чужой `match_id` — по-прежнему `None`, а не «замок».

    Если бы проверка участия ушла под ветку лимита, подстановка чужого id
    возвращала бы закрытый мэтч с `user_id` партнёра — то есть IDOR, вернувшийся
    вместе с новой фичей.
    """
    assert лимиты["чужой_мэтч_none"], (
        f"чужой мэтч вернулся как закрытый вместо None: {лимиты}"
    )


