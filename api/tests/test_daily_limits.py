"""Суточные лимиты бесплатного уровня В БОТЕ: 10 лайков и 3 открытых мэтча.

Лимит в API проверяется своими тестами по HTTP. Здесь — бот, и он проверяется
отдельно не ради симметрии: свайпы бота пишут лайки напрямую через
`database/connection.like_and_match`, минуя HTTP API целиком. Лимит, живущий
только в `api/services/quotas.py`, обходился бы одним нажатием «❤️» в чате с
ботом — то есть не существовал бы. Ровно поэтому у бота своя копия
`services/quotas.py`, и ровно поэтому она нуждается в своих проверках.

Бот живёт в отдельном venv (Python 3.12 против 3.14 у API) и импортировать его
код отсюда нечем: сценарий целиком прогоняется его собственным интерпретатором
на SQLite в памяти (`скрипты_бота/суточные_лимиты.py`), а сюда возвращается один
JSON. Каждое утверждение — про поведение, не про форму кода: лимит можно
«поставить» и при этом не считать пропуски, посчитать их дважды или закрыть
последнее разрешённое действие, и ни одна проверка исходника этого не увидит.
"""

from __future__ import annotations

import pytest

from tests.test_query_scale import прогнать_в_боте


@pytest.fixture(scope="module")
def лимиты() -> dict:
    """Один прогон на весь модуль: сценарий поднимает пять баз и не быстр."""
    return прогнать_в_боте("суточные_лимиты.py")


