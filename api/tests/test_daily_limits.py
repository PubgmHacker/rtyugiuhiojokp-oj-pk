def test_подписчику_лимиты_не_применяются(лимиты):
    """Оба лимита, а не только лайки: закрытый чат на Plus — это возврат денег."""
    assert лимиты["платный_уровень"] != "free", (
        f"активная подписка прочитана как бесплатный уровень: {лимиты}"
    )
    assert лимиты["платному_отказали_на"] is None, (
        f"подписчику отказали в лайке: {лимиты}"
    )
    assert лимиты["платному_мэтч_закрыли_на"] is None, (
        f"подписчику закрыли мэтч суточным лимитом: {лимиты}"
    )
    assert лимиты["платный_лайки_безлимит"], f"у подписчика лимит лайков: {лимиты}"
    assert лимиты["платный_мэтчи_безлимит"], f"у подписчика лимит мэтчей: {лимиты}"
    assert лимиты["платный_не_free"], f"сводка считает подписчика бесплатным: {лимиты}"
    # На безлимите «осталось N» не имеет смысла и не должно показываться
    assert лимиты["платному_остаток_none"], (
        f"подписчику показывается остаток лайков: {лимиты}"
    )


def test_код_тарифа_в_колонке_уровня_тоже_считается_оплатой(лимиты):
    """«plus_1m» вместо «plus» не должен молча превращаться в `free`.

    Уровень и код тарифа различаются одной буквой, лежат в соседних словарях и
    попадают в одну и ту же колонку `Subscription.plan` из разных путей оплаты.
    Пока разбор знал только уровни, такая запись читалась как бесплатная:
    человек заплатил и получил десять лайков в сутки — без ошибки в логах, без
    жалобы, которую можно воспроизвести.
    """
    assert лимиты["по_коду_уровень"] != "free", (
        f"подписка с кодом тарифа {лимиты['код_тарифа']!r} прочитана как "
        f"бесплатная: {лимиты}"
    )
    assert лимиты["по_коду_отказали_на"] is None, (
        f"оплатившему отказали в лайке из-за формы записи тарифа: {лимиты}"
    )
    assert лимиты["по_коду_безлимит"], (
        f"у оплатившего остался суточный лимит: {лимиты}"
    )


def test_истёкшая_подписка_снова_бесплатная(лимиты):
    """Иначе платили бы один раз.

    Просроченная запись остаётся в базе навсегда — если читать её без срока,
    подписка становится вечной.
    """
    assert лимиты["просроченному_отказали_на"] == лимиты["лимит_лайков"] + 1, (
        f"истёкшая подписка всё ещё снимает лимит: {лимиты}"
    )


