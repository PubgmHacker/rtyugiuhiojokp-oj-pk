def test_порядок_захвата_локов_совпадает_с_api(лимиты):
    """Личный ключ, потом парный — и так же в `api/routers/likes.py`.

    Оба сервиса берут одни и те же advisory-локи на одном и том же лайке.
    Обратный порядок в одном из них — классический дедлок: бот держит личный и
    ждёт парный, API держит парный и ждёт личный, оба висят до таймаута.
    """
    assert лимиты["первые_локи"] == [
        "dating:likes:F0",
        "dating:pair:F0:T1",
    ], f"порядок захвата локов изменился: {лимиты}"
