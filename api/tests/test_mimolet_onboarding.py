def test_ссылки_политики_не_пустышки():
    конфиг = (БОТ / "config.py").read_text(encoding="utf-8")
    assert "def legal_url" in конфиг
    assert "privacy.html" in конфиг or 'legal_url("privacy")' in (
        БОТ / "handlers" / "onboarding.py"
    ).read_text(encoding="utf-8")
    публичные = {
        "privacy.html",
        "terms.html",
        "styles.css",
    }
    for имя in публичные:
        путь = КОРЕНЬ / "web" / "public" / имя
        # is_symlink() первым и обязательно: exists() и is_file() идут ПО ссылке
        # и рапортуют про файл в landing/. Именно эта слепота и пропускала
        # поломку — в образе веба (контекст `web/`, `../../landing` нет) ссылка
        # висит в воздухе, vite build падает на statSync, и по этому адресу бот
        # отправляет человека читать политику. Полный чекаут показывает зелёное.
        assert not путь.is_symlink(), (
            f"web/public/{имя} — символическая ссылка наружу: сборка образа веба "
            f"упадёт. Починить: npm run sync:landing"
        )
        assert путь.is_file(), f"мини-апп не отдаёт {имя}"


