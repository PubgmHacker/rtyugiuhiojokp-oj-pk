# ════════════════════════════════════════════════════════════════
#  Реклама уходит отложенными пушами, а не сразу
# ════════════════════════════════════════════════════════════════
#
# Проверки выше доказали, что согласие СТАВИТ пуши. Ниже — сама очередь
# (`services/nudges.py`) на настоящей БД в памяти (`скрипты_бота/
