def test_хвостовой_слэш_не_даёт_двойного(адреса):
    """`https://simp.app//privacy.html` — 404 на большинстве статик-хостингов.

    Слэш срезается один раз, при чтении SITE_URL и LANDING_URL. Проверяются и
    адреса документов, и адреса мини-аппа: обе цепочки клеят путь к той же
    базе, и потеря нормализации ломает их вместе.
    """
    цепочки: list[tuple[str, str]] = [
        (f"документы/{случай}/{страница}", адрес)
        for случай, страницы in адреса["адреса"].items()
        for страница, адрес in страницы.items()
    ]
    цепочки += [(f"мини_апп/{случай}", адрес) for случай, адрес in адреса["мини_апп"].items()]
    for метка, адрес in цепочки:
        хвост = адрес.split("://", 1)[-1] if "://" in адрес else адрес
        assert "//" not in хвост, f"{метка}: в адресе двойной слэш — {адрес}"


