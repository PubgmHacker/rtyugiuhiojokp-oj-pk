def test_кнопка_начать_работает_без_состояния(тапы):
    """«Начать» нажимают ровно тогда, когда состояния уже нет.

    `accept_policy` чистит state, поэтому к этому тапу человек приходит без
    состояния. Фильтр, забывший разрешить «нет состояния», убил бы единственный
    путь из бота в анкету — тихо: кнопка есть, тап уходит в никуда.
    """
    assert тапы["старт_готовому_обработан"], (
        f"кнопка «Начать» не работает у человека с готовой анкетой: {тапы}"
    )
    assert тапы["старт_готовому_сообщений"] == 1, (
        f"вместо меню пришло {тапы['старт_готовому_сообщений']} сообщений: {тапы}"
    )
    assert тапы["старт_новичку_состояние"] == "RegistrationStates:waiting_name", (
        f"человека без анкеты «Начать» не завело в регистрацию: {тапы}"
    )
    assert тапы["старт_новичку_сообщений"] == 1, (
        f"первый вопрос анкеты не задан: {тапы}"
    )


