@pytest.mark.parametrize("кнопка", ["согласие", "язык", "старт"])
def test_устаревший_тап_подтверждается_а_не_молчит(тапы, кнопка):
    """Молча проигнорировать тап нельзя: Telegram крутит часики до таймаута.

    Человек жмёт второй раз, третий, и решает, что бот умер. Ответ обязателен,
    и он обязан быть ровно один — `answerCallbackQuery` без сообщений в чат,
    иначе посреди анкеты вылезает текст онбординга.
    """
    assert тапы[f"анкета_{кнопка}_обработан"], (
        f"тап по «{кнопка}» не обработан никем — на кнопке висят часики: {тапы}"
    )
    assert тапы[f"анкета_{кнопка}_методы"] == ["AnswerCallbackQuery"], (
        f"на устаревший тап «{кнопка}» ушло лишнее: "
        f"{тапы[f'анкета_{кнопка}_методы']} — посреди анкеты появился текст "
        f"онбординга: {тапы}"
    )
    assert тапы[f"анкета_{кнопка}_ответ"].strip(), (
        f"тап «{кнопка}» подтверждён пустым ответом — человек не понял, почему "
        f"ничего не произошло: {тапы}"
    )


