def test_кнопки_онбординга_работают_как_раньше(тапы):
    """Фильтр по состоянию не должен убить сам онбординг.

    Первое, что ломается от неверно перечисленных состояний: язык не
    выбирается, согласие не принимается, и бот не проходится дальше первого
    экрана вообще.
    """
    assert тапы["язык_обработан"], f"кнопка языка перестала работать: {тапы}"
    assert тапы["язык_состояние"] == "OnboardingStates:waiting_consent", (
        f"после выбора языка человек не попал на экран согласия: {тапы}"
    )
    assert тапы["язык_локаль"] == "es", f"выбранный язык не сохранён: {тапы}"
    assert тапы["согласие_обработано"], f"кнопка согласия не работает: {тапы}"
    assert тапы["согласие_флаг"], f"согласие не записано: {тапы}"
    # Онбординг закончен: шаг не должен остаться висеть на человеке
    assert тапы["согласие_состояние"] is None, (
        f"после согласия человек остался в состоянии онбординга: {тапы}"
    )


def test_онбординг_живёт_в_одном_сообщении(тапы):
    """Каждый шаг редактирует экран, а не отвечает новым сообщением.

    Кнопки под старыми сообщениями в Telegram нажимаемы вечно: пока экраны
    складывались лестницей, повторные тапы по верхним плодили копии нижних —
    «оно спамит». Правка на месте убирает и лестницу, и сами старые кнопки.
    """
    assert тапы["язык_сообщений"] == 0, (
        f"выбор языка ответил новым сообщением вместо правки экрана: {тапы}"
    )
    assert "EditMessageText" in тапы["язык_методы"], (
        f"экран согласия не показан правкой сетки языков: {тапы}"
    )
    assert тапы["согласие_сообщений"] == 0, (
        f"после согласия ушли отдельные сообщения — снова лестница: {тапы}"
    )
    assert "EditMessageText" in тапы["согласие_методы"], (
        f"экран «жми Начать» не показан правкой экрана согласия: {тапы}"
    )


