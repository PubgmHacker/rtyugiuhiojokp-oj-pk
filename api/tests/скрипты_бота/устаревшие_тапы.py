@contextmanager
def подменить_бд(профиль, язык_в_базе=None, ронять_запись=False):
    """Все входы `onboarding` в базу — на время прогона.

    Живой Postgres тут не нужен и вреден: обработчик, до которого тап дойти не
    должен, обязан пройти свой настоящий путь до конца, а не умереть на
    `connect`. Тогда регрессия видна там, где её увидит человек: в состоянии FSM
    и в отправленных сообщениях, а не в трейсбеке драйвера.

    Возвращаем то, что вернула бы база: `get_or_create_user` — строку
    пользователя, `get_profile` — переданный профиль (`None` значит «анкеты
    нет»), `get_user_locale` — язык аккаунта (`None` значит «аккаунта нет или
    язык не выбран»). Запись языка складывается в `ЗАПИСИ_ЯЗЫКА`.

    `ронять_запись` нужен отдельным флагом: сохранение языка не имеет права
    ломать онбординг. Недоступная база на этом шаге — это потерянный язык, а не
    потерянный человек, и шаг обязан продолжиться.
    """
    настоящий_юзер = onboarding.get_or_create_user
    настоящий_профиль = onboarding.get_profile
    настоящая_запись = onboarding.set_user_locale
    настоящее_чтение = onboarding.get_user_locale
    настоящие_пуши = onboarding.запланировать_пуши_онбординга

    async def _юзер(*_a, **_kw):
        return {"id": "U-1"}

    async def _профиль(*_a, **_kw):
        return профиль

    async def _записать(telegram_id, locale):
        if ронять_запись:
            raise RuntimeError("база недоступна")
        ЗАПИСИ_ЯЗЫКА.append([telegram_id, locale])
        return True

    async def _прочитать(_telegram_id):
        return язык_в_базе

    async def _поставить_пуши(telegram_id, locale):
        ПОСТАВЛЕННЫЕ_ПУШИ.append([telegram_id, locale])

    onboarding.get_or_create_user = _юзер
    onboarding.get_profile = _профиль
    onboarding.set_user_locale = _записать
    onboarding.get_user_locale = _прочитать
    onboarding.запланировать_пуши_онбординга = _поставить_пуши
    try:
        yield
    finally:
        onboarding.get_or_create_user = настоящий_юзер
        onboarding.get_profile = настоящий_профиль
        onboarding.set_user_locale = настоящая_запись
        onboarding.get_user_locale = настоящее_чтение
        onboarding.запланировать_пуши_онбординга = настоящие_пуши


class ФейковаяСессия(BaseSession):
    """Сессия бота без Telegram: запоминает вызовы, отвечает минимумом.

    `make_request` — единственная точка, через которую aiogram уходит в сеть,
    поэтому подменять достаточно её. Возврат обязан быть того типа, который
    ждёт метод: `sendMessage` отдаёт `Message`, остальное здесь — `True`.
    """

    def __init__(self) -> None:
        super().__init__()
        self.вызовы: list[tuple[str, str]] = []

    async def close(self) -> None:
        return None

    async def make_request(self, bot, method, timeout=None):
        имя = type(method).__name__
        текст = getattr(method, "text", None) or getattr(method, "caption", None) or ""
        self.вызовы.append((имя, текст))
        if имя == "SendMessage":
            return Message(
                message_id=len(self.вызовы),
                date=datetime.now(timezone.utc),
                chat=Chat(id=Я, type="private"),
                text=текст,
            )
        return True

    async def stream_content(self, *args, **kwargs):
        yield b""


def _порядок_роутеров() -> list[str]:
    """Продакшеновый порядок включения роутеров, вычитанный из `bot.py`."""
    исходник = Path("bot.py").read_text(encoding="utf-8")
    порядок = re.findall(r"dp\.include_router\((\w+)\.router\)", исходник)
    assert порядок, "в bot.py не нашлось include_router — порядок читать нечем"
    assert порядок[0] == "onboarding", (
        f"роутер онбординга больше не первый ({порядок}) — заглушка устаревших "
        f"тапов перестала выигрывать у чужих обработчиков"
    )
    return порядок


#: Один Dispatcher на весь прогон: роутер aiogram нельзя включить в два
#: диспетчера (у него один родитель), а изоляция сценариев достигается
#: `ctx.clear()` перед каждым.
ПОРЯДОК = _порядок_роутеров()
DP = Dispatcher(storage=MemoryStorage())
for _имя in ПОРЯДОК:
    DP.include_router(importlib.import_module(f"handlers.{_имя}").router)


def _тап(данные: str) -> dict:
    """Сырой update как от Telegram: кнопка под старым сообщением."""
    return {
        "update_id": 1,
        "callback_query": {
            "id": "1",
            "from": {"id": Я, "is_bot": False, "first_name": "Боря"},
            "chat_instance": "1",
            "data": данные,
            "message": {
                "message_id": 1,
                "date": 1700000000,
                "chat": {"id": Я, "type": "private"},
                "from": {"id": 1, "is_bot": True, "first_name": "Бот"},
                "text": "сообщение из прошлого",
            },
        },
    }


async def прогнать(данные: str, состояние=None, начальные: dict | None = None) -> dict:
    """Один тап: выставить состояние, скормить update, вернуть что осталось.

    Update собирается через `model_validate` с контекстом бота, а не
    конструктором: без контекста модель не привязана к боту и `message.answer`
    внутри обработчика падает — то есть проверялся бы не тот путь.
    """
    сессия = ФейковаяСессия()
    bot = Bot(
        token=ТОКЕН,
        session=сессия,
        default=DefaultBotProperties(parse_mode="HTML"),
    )
    ctx = DP.fsm.get_context(bot=bot, chat_id=Я, user_id=Я)
    await ctx.clear()
    if состояние is not None:
        await ctx.set_state(состояние)
    if начальные:
        await ctx.update_data(**начальные)

    сорвалось = ""
    try:
        итог = await DP.feed_update(
            bot, Update.model_validate(_тап(данные), context={"bot": bot})
        )
        обработан = итог is not UNHANDLED
    except Exception as ошибка:
        # Обработчик тап подобрал и не довёл до конца. Сценарии продолжаются:
        # один упавший тап не должен съесть остальные проверки прогона, а его
        # след ляжет в СБОИ и провалит свой отдельный тест.
        обработан = True
        сорвалось = f"{type(ошибка).__name__}: {ошибка}"
        СБОИ.append({
            "кнопка": данные,
            "состояние": getattr(состояние, "state", None) or "нет состояния",
            "сбой": сорвалось,
        })

    данные_после = await ctx.get_data()
    return {
        "обработан": обработан,
        "сорвалось": сорвалось,
        "состояние": await ctx.get_state(),
        "данные": данные_после,
        "методы": [имя for имя, _ in сессия.вызовы],
        "тексты": [текст for _, текст in сессия.вызовы],
        "потеряно": sorted(
            ключ for ключ, значение in АНКЕТА.items()
            if данные_после.get(ключ) != значение
        ),
    }

