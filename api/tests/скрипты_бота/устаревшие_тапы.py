"""Кнопки старта, нажатые посреди другого сценария — на настоящем Dispatcher.

Инлайн-кнопки под старыми сообщениями в Telegram остаются нажимаемыми навсегда:
первое сообщение `/start` с сеткой языков и «✅ Продолжить» лежит в переписке и
через месяц. Обработчики онбординга переводят состояние FSM и чистят данные, и
пока у них не было фильтра по состоянию, тап по такой кнопке посреди заполнения
анкеты стирал ВСЁ введённое — имя, возраст, город, загруженные фото — и уводил
человека обратно в онбординг. Заново он бы это не вводил.

Проверяется поведение, а не форма кода: наличие `StateFilter` в исходнике ничего
не доказывает (фильтр можно навесить не на тот обработчик, перечислить не те
состояния, поставить заглушку раньше нужного хендлера). Поэтому здесь настоящий
`Dispatcher` с продакшеновым порядком роутеров, настоящий `FSMContext` в памяти
и настоящий `Update`, прогнанный через `feed_update`. Утверждается то, что
осталось в state после тапа.

Порядок роутеров не переписан руками, а вычитан из `bot.py`: копия списка
разъехалась бы с продакшеном молча, а порядок здесь существенный — заглушка
устаревших тапов живёт в роутере онбординга, включённом первым.

Телеграма нет: сессия бота подменена на запоминающую вызовы. Внешние
мидлвари (`ThrottleMiddleware`, `RegistrationMiddleware`) не подключены
намеренно — обе только пропускают событие дальше (вторая кладёт `db_user` в
данные) и на выбор обработчика повлиять не могут, зато потребовали бы живой БД.

Запускается интерпретатором бота из `tests/test_query_scale.py`.
Ответ — JSON на последней строке stdout.
"""

