СБОИ: list[dict] = []


@contextmanager
def подменить_бд(профиль):
    """Оба входа `onboarding` в базу — на время прогона.

    Живой Postgres тут не нужен и вреден: обработчик, до которого тап дойти не
    должен, обязан пройти свой настоящий путь до конца, а не умереть на
    `connect`. Тогда регрессия видна там, где её увидит человек: в состоянии FSM
    и в отправленных сообщениях, а не в трейсбеке драйвера.

    Возвращаем то, что вернула бы база: `get_or_create_user` — строку
    пользователя, `get_profile` — переданный профиль (`None` значит «анкеты
    нет»).
    """
    настоящий_юзер = onboarding.get_or_create_user
    настоящий_профиль = onboarding.get_profile

    async def _юзер(*_a, **_kw):
        return {"id": "U-1"}

    async def _профиль(*_a, **_kw):
        return профиль

    onboarding.get_or_create_user = _юзер
    onboarding.get_profile = _профиль
    try:
        yield
    finally:
        onboarding.get_or_create_user = настоящий_юзер
        onboarding.get_profile = настоящий_профиль


class ФейковаяСессия(BaseSession):
    """Сессия бота без Telegram: запоминает вызовы, отвечает минимумом.

    `make_request` — единственная точка, через которую aiogram уходит в сеть,
    поэтому подменять достаточно её. Возврат обязан быть того типа, который
    ждёт метод: `sendMessage` отдаёт `Message`, остальное здесь — `True`.
    """

    def __init__(self) -> None:
        super().__init__()
        self.вызовы: list[tuple[str, str]] = []

    async def close(self) -> None:
        return None

    async def make_request(self, bot, method, timeout=None):
        имя = type(method).__name__
        текст = getattr(method, "text", None) or getattr(method, "caption", None) or ""
        self.вызовы.append((имя, текст))
        if имя == "SendMessage":
            return Message(
                message_id=len(self.вызовы),
                date=datetime.now(timezone.utc),
                chat=Chat(id=Я, type="private"),
                text=текст,
            )
        return True

    async def stream_content(self, *args, **kwargs):
        yield b""


def _порядок_роутеров() -> list[str]:
    """Продакшеновый порядок включения роутеров, вычитанный из `bot.py`."""
    исходник = Path("bot.py").read_text(encoding="utf-8")
    порядок = re.findall(r"dp\.include_router\((\w+)\.router\)", исходник)
    assert порядок, "в bot.py не нашлось include_router — порядок читать нечем"
    assert порядок[0] == "onboarding", (
        f"роутер онбординга больше не первый ({порядок}) — заглушка устаревших "
        f"тапов перестала выигрывать у чужих обработчиков"
    )
    return порядок


#: Один Dispatcher на весь прогон: роутер aiogram нельзя включить в два
#: диспетчера (у него один родитель), а изоляция сценариев достигается
#: `ctx.clear()` перед каждым.
ПОРЯДОК = _порядок_роутеров()
DP = Dispatcher(storage=MemoryStorage())
for _имя in ПОРЯДОК:
    DP.include_router(importlib.import_module(f"handlers.{_имя}").router)


def _тап(данные: str) -> dict:
    """Сырой update как от Telegram: кнопка под старым сообщением."""
    return {
        "update_id": 1,
        "callback_query": {
            "id": "1",
            "from": {"id": Я, "is_bot": False, "first_name": "Боря"},
            "chat_instance": "1",
            "data": данные,
            "message": {
                "message_id": 1,
                "date": 1700000000,
                "chat": {"id": Я, "type": "private"},
                "from": {"id": 1, "is_bot": True, "first_name": "Бот"},
                "text": "сообщение из прошлого",
            },
        },
    }


async def прогнать(данные: str, состояние=None, начальные: dict | None = None) -> dict:
    """Один тап: выставить состояние, скормить update, вернуть что осталось.

    Update собирается через `model_validate` с контекстом бота, а не
    конструктором: без контекста модель не привязана к боту и `message.answer`
    внутри обработчика падает — то есть проверялся бы не тот путь.
    """
    сессия = ФейковаяСессия()
    bot = Bot(
        token=ТОКЕН,
        session=сессия,
        default=DefaultBotProperties(parse_mode="HTML"),
    )
    ctx = DP.fsm.get_context(bot=bot, chat_id=Я, user_id=Я)
    await ctx.clear()
    if состояние is not None:
        await ctx.set_state(состояние)
    if начальные:
        await ctx.update_data(**начальные)

    сорвалось = ""
    try:
        итог = await DP.feed_update(
            bot, Update.model_validate(_тап(данные), context={"bot": bot})
        )
        обработан = итог is not UNHANDLED
    except Exception as ошибка:
        # Обработчик тап подобрал и не довёл до конца. Сценарии продолжаются:
        # один упавший тап не должен съесть остальные проверки прогона, а его
        # след ляжет в СБОИ и провалит свой отдельный тест.
        обработан = True
        сорвалось = f"{type(ошибка).__name__}: {ошибка}"
        СБОИ.append({
            "кнопка": данные,
            "состояние": getattr(состояние, "state", None) or "нет состояния",
            "сбой": сорвалось,
        })

    данные_после = await ctx.get_data()
    return {
        "обработан": обработан,
        "сорвалось": сорвалось,
        "состояние": await ctx.get_state(),
        "данные": данные_после,
        "методы": [имя for имя, _ in сессия.вызовы],
        "тексты": [текст for _, текст in сессия.вызовы],
        "потеряно": sorted(
            ключ for ключ, значение in АНКЕТА.items()
            if данные_после.get(ключ) != значение
        ),
    }

# ── Онбординг обязан работать как раньше ────────────────────────

async def проверить_онбординг() -> dict:
    """Сам онбординг фильтр не сломал: язык выбирается, согласие принимается."""
    язык = await прогнать("onb:lang:es", OnboardingStates.waiting_language)
    согласие = await прогнать(
        "onb:consent", OnboardingStates.waiting_consent, {"onb_locale": "ru"}
    )
    return {
        "язык_обработан": язык["обработан"],
        "язык_состояние": язык["состояние"],
        "язык_локаль": язык["данные"].get("onb_locale"),
        "согласие_обработано": согласие["обработан"],
        "согласие_состояние": согласие["состояние"],
        "согласие_флаг": bool(согласие["данные"].get("onb_consented")),
        # Две рассылки Mimolet: субкультура и почта
        "согласие_рассылок": согласие["методы"].count("SendMessage"),
    }


async def проверить_кнопку_старта() -> dict:
    """`onb:start` после согласия: состояния нет, и кнопка обязана работать.

    Это единственный путь в анкету из бота, и он же — витрина мини-аппа. Если
    фильтр по состоянию задел «нет состояния», кнопка «Начать» умерла бы
    целиком: `accept_policy` state чистит, то есть к этому тапу состояния уже
    нет ни у кого.
    """
    ГОТОВАЯ = {"display_name": "Боря", "photos": ["ФОТО"]}
    with подменить_бд(ГОТОВАЯ):
        готовому = await прогнать("onb:start", None, {"onb_locale": "ru"})
    with подменить_бд(None):
        новичку = await прогнать("onb:start", None, {"onb_locale": "ru"})

    return {
        "старт_готовому_обработан": готовому["обработан"],
        "старт_готовому_сообщений": готовому["методы"].count("SendMessage"),
        "старт_новичку_состояние": новичку["состояние"],
        "старт_новичку_сообщений": новичку["методы"].count("SendMessage"),
    }


# ── Чужие сценарии обязаны выжить ───────────────────────────────

async def проверить_анкету() -> dict:
    """Все три кнопки онбординга посреди заполнения анкеты.

    Проверяются все три, а не одна: фильтр навешивается на каждый обработчик
    отдельно, и забыть его на одном — обычная правка. Каждая кнопка ломала
    анкету по-своему: «Продолжить» стирал данные, язык переводил состояние в
    онбординг (и введённое фото уходило в никуда), «Начать» откатывал человека
    к первому вопросу.

    База подменена на «анкеты нет» — это правда про человека на шаге фото:
    `display_name` он уже вводил, а фотографий в профиле ещё ноль, и `start_app`
    считает такую анкету незаконченной. Без подмены обработчик, случайно
    получивший этот тап, падал бы на `connect` — то есть след в FSM остался бы
    таким же чистым, как при работающем фильтре, и регрессия прошла бы молча.
    """
    ответ: dict = {}
    for метка, кнопка in (
        ("согласие", "onb:consent"),
        ("язык", "onb:lang:ru"),
        ("старт", "onb:start"),
    ):
        with подменить_бд(None):
            итог = await прогнать(кнопка, RegistrationStates.waiting_photo, АНКЕТА)
        ответ[f"анкета_{метка}_обработан"] = итог["обработан"]
        ответ[f"анкета_{метка}_состояние"] = итог["состояние"]
        ответ[f"анкета_{метка}_потеряно"] = итог["потеряно"]
        ответ[f"анкета_{метка}_методы"] = итог["методы"]
        ответ[f"анкета_{метка}_ответ"] = итог["тексты"][0] if итог["тексты"] else ""
    return ответ


async def проверить_чат() -> dict:
    """Анкета — не единственный сценарий с состоянием.

    Фильтр, перечисляющий состояния регистрации вместо состояний онбординга,
    закрыл бы анкету и оставил открытыми чат, удаление аккаунта и ввод
    сообщения к лайку. Здесь беседа: тап по старой кнопке не должен выкидывать
    человека из чата.
    """
    итог = await прогнать("onb:consent", ChatStates.in_chat, {"match_id": "M-1"})
    return {
        "чат_обработан": итог["обработан"],
        "чат_состояние": итог["состояние"],
        "чат_match_id": итог["данные"].get("match_id"),
        "чат_методы": итог["методы"],
    }


def слить(ответ: dict, добавка: dict) -> None:
    """Склеить отчёты сценариев, запретив тихую перезапись ключей.

    Сценарии пишут в одно пространство имён, и `dict.update` затирал бы
    одноимённые ключи последним значением — зелёный тест на разъехавшихся
    данных. Дубликат это ошибка скрипта, и она обязана быть видна сразу.
    """
    for ключ, значение in добавка.items():
        assert ключ not in ответ, f"ключ {ключ!r} пишут два сценария"
        ответ[ключ] = значение


async def main() -> None:
    ответ: dict = {}
    слить(ответ, await проверить_онбординг())
    слить(ответ, await проверить_кнопку_старта())
    слить(ответ, await проверить_анкету())
    слить(ответ, await проверить_чат())
    ответ["порядок_роутеров"] = ПОРЯДОК
    ответ["ключей_в_анкете"] = len(АНКЕТА)
    ответ["сбои"] = СБОИ
    print(json.dumps(ответ, ensure_ascii=False, default=str))


asyncio.run(main())
