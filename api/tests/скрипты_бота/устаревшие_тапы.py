def слить(ответ: dict, добавка: dict) -> None:
    """Склеить отчёты сценариев, запретив тихую перезапись ключей.

    Сценарии пишут в одно пространство имён, и `dict.update` затирал бы
    одноимённые ключи последним значением — зелёный тест на разъехавшихся
    данных. Дубликат это ошибка скрипта, и она обязана быть видна сразу.
    """
    for ключ, значение in добавка.items():
        assert ключ not in ответ, f"ключ {ключ!r} пишут два сценария"
        ответ[ключ] = значение


async def main() -> None:
    ответ: dict = {}
    слить(ответ, await проверить_онбординг())
    слить(ответ, await проверить_кнопку_старта())
    слить(ответ, await проверить_анкету())
    слить(ответ, await проверить_чат())
    слить(ответ, await проверить_язык_на_аккаунте())
    ответ["порядок_роутеров"] = ПОРЯДОК
    ответ["ключей_в_анкете"] = len(АНКЕТА)
    ответ["сбои"] = СБОИ
    print(json.dumps(ответ, ensure_ascii=False, default=str))


asyncio.run(main())
