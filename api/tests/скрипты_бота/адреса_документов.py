"""Ссылки на политику и оферту из бота — на настоящем `bot/config.py`.

Ссылка уходит в чужой Telegram и живёт в переписке вечно. `http://localhost:5173/
privacy.html` на телефоне получателя ведёт в него самого, где ничего не слушает:
человек видит «сайт недоступен» вместо документа, который его просят принять
перед регистрацией. Дефолт `SITE_URL` — как раз петля, поэтому у всех, кто
поднял бота локально и не заполнил `LANDING_URL`, кнопка «политика
конфиденциальности» была мёртвой.

Проверяется поведение, а не форма кода: наличие `_петля` в исходнике ничего не
доказывает — условие можно инвертировать, забыть про `127.0.0.1`, потерять
`LANDING_URL` из приоритета. Здесь настоящий модуль конфигурации, перечитанный с
разным окружением, и утверждается адрес, который в итоге уйдёт в сообщение.

Каждый случай задаёт ВСЕ участвующие переменные явно, в том числе пустыми:
`_load_dotenv` не перетирает уже заданные ключи, поэтому корневой `.env`
разработчика не может подмешаться в результат — иначе тест зеленел бы или падал
в зависимости от чужой машины.

`mini_app_url` проверяется рядом намеренно: правило про петлю не должно течь в
web_app-кнопки. Их открывает тот же человек, который запустил бота, и localhost
там как раз рабочий адрес — запрет сломал бы локальную разработку целиком.

Запускается интерпретатором бота из `tests/test_query_scale.py`.
Ответ — JSON на последней строке stdout.
"""

import importlib
import json
import os
import sys

sys.path.insert(0, ".")

import config as конфиг  # noqa: E402

КЛЮЧИ = ("SITE_URL", "LANDING_URL")


def перечитать(окружение: dict[str, str]):
    """Модуль конфигурации с заданным окружением — константы читаются при импорте."""
    for ключ in КЛЮЧИ:
        os.environ[ключ] = окружение.get(ключ, "")
    return importlib.reload(конфиг)


СЛУЧАИ: dict[str, dict[str, str]] = {
    # Дефолт из .env.example: так выглядит машина разработчика и так же
    # выглядел прод до того, как в него попал настоящий домен
    "локальный_дефолт": {"SITE_URL": "http://localhost:5173"},
    "петля_по_ip": {"SITE_URL": "http://127.0.0.1:5173"},
    "петля_нулями": {"SITE_URL": "http://0.0.0.0:5173"},
    "поддомен_петли": {"SITE_URL": "http://app.localhost:5173"},
    "пустой_сайт": {},
    # Прод: домен мини-аппа сам отдаёт копии документов из web/public
    "боевой_домен": {"SITE_URL": "https://simp.app"},
    "туннель": {"SITE_URL": "https://ab12cd.ngrok-free.app"},
    "хвостовой_слэш": {"SITE_URL": "https://simp.app/"},
    # Осознанная настройка сильнее любых догадок, включая локальную:
    # из десктопного Telegram localhost открывается
    "явный_лендинг": {"SITE_URL": "http://localhost:5173", "LANDING_URL": "http://localhost:8080"},
    "явный_лендинг_поверх_прода": {
        "SITE_URL": "https://simp.app",
        "LANDING_URL": "https://legal.simp.app/",
    },
}


def main() -> None:
    ответ: dict = {"канон": None, "адреса": {}, "мини_апп": {}, "имя_страницы": {}}

    for имя, окружение in СЛУЧАИ.items():
        c = перечитать(окружение)
        ответ["канон"] = c.LEGAL_ORIGIN
        ответ["адреса"][имя] = {
            "privacy": c.legal_url("privacy"),
            "terms": c.legal_url("terms"),
        }
        # web_app-кнопки обязаны остаться на SITE_URL, включая петлю
        ответ["мини_апп"][имя] = c.mini_app_url("/onboarding")

    c = перечитать({"SITE_URL": "https://simp.app"})
    # Вызывающий может передать и «privacy», и «privacy.html» — второй раз
    # расширение приписывать нельзя
    ответ["имя_страницы"] = {
        "без_расширения": c.legal_url("privacy"),
        "с_расширением": c.legal_url("privacy.html"),
        "guidelines": c.legal_url("guidelines"),
        "support": c.legal_url("support"),
    }

    print(json.dumps(ответ, ensure_ascii=False, default=str))


main()
