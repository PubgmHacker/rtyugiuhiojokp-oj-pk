async def test_комнаты_и_приглашения_не_мешают_друг_другу(менеджер_на_двойнике):
    """Читатель теперь развозит два разных вида каналов — и не путает их.

    У канала комнаты `dating:match:М` и личного `dating:voice:invite:u1`
    последний сегмент разбирается одинаково. Уйди приглашение в `broadcast`,
    и оно бы разослалось в комнату с таким же хвостом — а сообщение чата,
    попавшее в обработчик, оборвало бы звонок.
    """
    from tests.test_ws_rooms import ФейковыйСокет

    менеджер, сервер = менеджер_на_двойнике
    обработчик, приглашения = собиратель()
    сокет = ФейковыйСокет("в комнате")

    await менеджер.subscribe_channel("dating:voice:invite:u1", обработчик)
    await менеджер.connect("u1", сокет, "u1")  # комната с тем же хвостом

    await сервер.publish(
        "dating:voice:invite:u1",
        json.dumps({"type": "matched", "call_id": "З1"}),
    )
    await сервер.publish(
        "dating:match:u1",
        json.dumps({"type": "message", "text": "привет", "origin": "ДРУГОЙ"}),
    )
    await asyncio.sleep(ЖДАТЬ)

    assert приглашения == [{"type": "matched", "call_id": "З1"}], (
        f"приглашение не дошло до обработчика: {приглашения}"
    )
    assert сокет.получено == [{"type": "message", "text": "привет"}], (
        f"комната получила не то: {сокет.получено}"
    )


async def test_вторая_вкладка_не_отбирает_приглашения(менеджер_на_двойнике):
    """Канал личный, но вкладок может быть две — и обе на одном инстансе.

    Раньше у каждого сокета был свой pubsub, так что вкладки не мешали друг
    другу. На общем подключении один обработчик на канал означал бы, что
    вторая вкладка молча отбирает приглашения у первой, а её закрытие снимает
    подписку у живой.
    """
    менеджер, сервер = менеджер_на_двойнике
    первый, первой = собиратель()
    второй, второй_пришло = собиратель()
    канал = "dating:voice:invite:u1"

    await менеджер.subscribe_channel(канал, первый)
    await менеджер.subscribe_channel(канал, второй)

    await сервер.publish(канал, json.dumps({"type": "matched", "call_id": "З1"}))
    await asyncio.sleep(ЖДАТЬ)

    assert первой == [{"type": "matched", "call_id": "З1"}], (
        f"первая вкладка перестала получать приглашения: {первой}"
    )
    assert второй_пришло == [{"type": "matched", "call_id": "З1"}], (
        f"вторая вкладка не получила приглашение: {второй_пришло}"
    )

    # Закрылась вторая — подписка нужна первой, она обязана остаться
    await менеджер.unsubscribe_channel(канал, второй)
    assert канал in сервер.выданные_pubsub[0].каналы, (
        "закрытая вкладка сняла подписку, нужную живой"
    )

    await сервер.publish(канал, json.dumps({"type": "matched", "call_id": "З2"}))
    await asyncio.sleep(ЖДАТЬ)
    assert len(первой) == 2, f"живая вкладка осталась без приглашений: {первой}"
    assert len(второй_пришло) == 1, (
        f"закрытая вкладка продолжает получать приглашения: {второй_пришло}"
    )


async def test_закрытый_сокет_снимает_свою_подписку(менеджер_на_двойнике):
    """Последний ушёл — канал уходит из подписки, читатель остаётся.

    Иначе подписка переживает сокет, и приглашения идут в обработчик, у
    которого сокета уже нет: человек соединяется с закрытой вкладкой, а на
    той стороне — тишина.
    """
    менеджер, сервер = менеджер_на_двойнике
    обработчик, _ = собиратель()
    канал = "dating:voice:invite:u1"

    await менеджер.subscribe_channel(канал, обработчик)
    читатель = менеджер._reader
    await менеджер.unsubscribe_channel(канал, обработчик)

    assert канал not in сервер.выданные_pubsub[0].каналы, (
        "канал закрытого сокета остался в подписке"
    )
    assert not читатель.done(), "читатель умер вместе с последним ждущим"
    assert len(сервер.выданные_pubsub) == 1, "открылось второе подключение"


async def test_падение_обработчика_не_уносит_читателя(менеджер_на_двойнике):
    """На читателе висят все комнаты процесса — он не должен падать из-за одной.

    Обработчик пишет в websocket, а тот обрывается в любой момент: человек
    закрыл вкладку ровно между поиском пары и приглашением. Раньше слушатель
    был свой на сокет, и его падение никого не задевало; на общем читателе
    незакрытое исключение уносит чат всего процесса.
    """
    менеджер, сервер = менеджер_на_двойнике
    целый, целому = собиратель()

    async def падучий(_событие: dict) -> None:
        raise RuntimeError("сокет закрыт")

    await менеджер.subscribe_channel("dating:voice:invite:u1", падучий)
    await менеджер.subscribe_channel("dating:voice:invite:u2", целый)
    читатель = менеджер._reader

    await сервер.publish("dating:voice:invite:u1", json.dumps({"type": "matched"}))
    await asyncio.sleep(ЖДАТЬ)

    assert not читатель.done(), "читатель упал вместе с одним обработчиком"

    await сервер.publish(
        "dating:voice:invite:u2", json.dumps({"type": "matched", "call_id": "З2"})
    )
    await asyncio.sleep(ЖДАТЬ)
    assert целому == [{"type": "matched", "call_id": "З2"}], (
        f"после падения соседа приглашения не идут: {целому}"
    )


async def test_после_обрыва_redis_подписки_ждущих_возвращаются(менеджер_на_двойнике):
    """Ждущий в очереди молча перестал бы получать пару после реконнекта.

    Подписки пересобираются по `self.rooms`, а личные каналы там не лежат —
    без отдельного учёта они бы не вернулись. Снаружи это выглядит как
    «рулетка не находит никого», хотя очередь полна.
    """
    менеджер, сервер = менеджер_на_двойнике
    обработчик, пришло = собиратель()
    канал = "dating:voice:invite:u1"

    await менеджер.subscribe_channel(канал, обработчик)
    сервер.выданные_pubsub[0].падать_на_чтении = True
    await asyncio.sleep(1.4)  # пауза перед пересборкой — 1 с

    assert len(сервер.выданные_pubsub) == 2, (
        f"pubsub не пересобран после обрыва: {len(сервер.выданные_pubsub)}"
    )
    assert канал in сервер.выданные_pubsub[1].каналы, (
        "личный канал ждущего не вернулся в подписку после реконнекта"
    )

    await сервер.publish(канал, json.dumps({"type": "matched", "call_id": "З3"}))
    await asyncio.sleep(ЖДАТЬ)
    assert пришло == [{"type": "matched", "call_id": "З3"}], (
        f"после реконнекта приглашения не доходят: {пришло}"
    )


class СокетРулетки:
    """Сокет рулетки: держит соединение, пока его не попросят оборваться.

    Роутер живёт в `while True: await websocket.receive_text()`, поэтому в
    тесте нужен сокет, который умеет ждать, а потом разорваться — иначе до
    блока `finally` со снятием подписки не добраться.
    """

    def __init__(self) -> None:
        self.получено: list[dict] = []
        self.принят = False
        self.оборвать = asyncio.Event()

    async def accept(self) -> None:
        self.принят = True

    async def receive_text(self) -> str:
        await self.оборвать.wait()
        from fastapi import WebSocketDisconnect

        raise WebSocketDisconnect(code=1001)

    async def send_json(self, payload: dict) -> None:
        self.получено.append(payload)


class ПустаяСессия:
    """Сессия, в которой звонка не нашлось: длительность писать некуда."""

    async def execute(self, *_а, **_к):
        class Результат:
            @staticmethod
            def scalar_one_or_none():
                return None

        return Результат()

    async def commit(self) -> None:
        return None

    def add(self, _объект) -> None:
        return None


class ФабрикаСессий:
    async def __aenter__(self):
        return ПустаяСессия()

    async def __aexit__(self, *_а):
        return False


