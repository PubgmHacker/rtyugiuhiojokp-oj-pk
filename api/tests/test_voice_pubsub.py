def test_рулетка_не_открывает_свой_pubsub():
    """Правку легко откатить обратно: `r.pubsub()` в роутере — это возврат.

    Тесты выше работают с `RoomManager` напрямую (поднять настоящий сокет
    рулетки в юните нечем), поэтому форму подписки в самом роутере
    закрепляем отдельно.

    Смотрим на AST, а не на текст: в докстрингах роутера объясняется, что
    именно убрали, и поиск подстроки спотыкался бы об это объяснение.
    """
    import ast
    import inspect

    from routers import voice

    дерево = ast.parse(inspect.getsource(voice))
    вызовы = {
        узел.func.attr
        for узел in ast.walk(дерево)
        if isinstance(узел, ast.Call) and isinstance(узел.func, ast.Attribute)
    }

    assert "pubsub" not in вызовы, (
        "рулетка снова открывает своё подключение к Redis — на 10 000 ждущих "
        "это 10 000 соединений поверх чата"
    )
    assert "listen" not in вызовы, (
        "вернулся listen(): его цикл выходит на последней отписке"
    )
    assert "subscribe_channel" in вызовы, (
        "приглашения больше не подписываются на общем читателе"
    )
    assert "unsubscribe_channel" in вызовы, (
        "подписка не снимается — переживёт закрытый сокет"
    )
