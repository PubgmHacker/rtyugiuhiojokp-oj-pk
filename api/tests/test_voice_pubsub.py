"""Приглашения рулетки — на общем подключении, а не по pubsub на сокет.

`routers/voice.py` поднимал свой `r.pubsub()` на КАЖДЫЙ открытый сокет
рулетки: та же ошибка, что была с комнатами чата, только на другом канале.
10 000 ждущих в очереди = 10 000 подключений к Redis из одного процесса,
поверх подключений чата. Здесь закрепляется, что подписка на личный канал
едет на общем читателе `RoomManager`.

Двойник Redis взят из `test_ws_rooms.py` — семантика pub/sub там уже
воспроизведена, включая идемпотентный повторный SUBSCRIBE.
"""

from __future__ import annotations

import asyncio
import json

import pytest

from tests.test_ws_rooms import ЖДАТЬ, ФейковыйRedis


def собиратель():
    """Асинхронный обработчик + список пришедшего к нему.

    Именно корутина, а не `list.append`: читатель ждёт результат обработчика,
    и синхронная функция упала бы внутри его `except` — тест бы прошёл, а в
    бою приглашение до вкладки не дошло бы.
    """
    пришло: list[dict] = []

    async def обработчик(событие: dict) -> None:
        пришло.append(событие)

    return обработчик, пришло


@pytest.fixture
async def менеджер_на_двойнике(monkeypatch):
    """Свежий RoomManager на двойнике Redis; гасится после теста."""
    import services.ws_manager as wm

    сервер = ФейковыйRedis()

    async def _get_redis():
        return сервер

    monkeypatch.setattr(wm, "get_redis", _get_redis)
    менеджер = wm.RoomManager()
    try:
        yield менеджер, сервер
    finally:
        await менеджер.aclose()


async def test_много_ждущих_живут_на_одном_подключении(менеджер_на_двойнике):
    """Главное следствие правки: подключения не растут с числом ждущих.

    Очередь рулетки — это люди, которые СИДЯТ и ждут. Их тем больше, чем
    меньше повезло с парой, и каждый держал по подключению к Redis — поверх
    тех, что уже открыты под чаты.
    """
    менеджер, сервер = менеджер_на_двойнике
    обработчик, _ = собиратель()

    for i in range(200):
        await менеджер.subscribe_channel(f"dating:voice:invite:u{i}", обработчик)

    assert len(сервер.выданные_pubsub) == 1, (
        f"на 200 ждущих открыто подключений: {len(сервер.выданные_pubsub)} — "
        "вернулось по подключению на сокет"
    )
    задачи = [з for з in asyncio.all_tasks() if "_read_forever" in str(з.get_coro())]
    assert len(задачи) == 1, f"читателей больше одного: {len(задачи)}"
    assert len(сервер.выданные_pubsub[0].каналы) == 200


