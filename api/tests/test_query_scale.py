"""Масштаб запросов: то, что работает на 100 анкетах и умирает на 100 000.

Эти проверки не про результат запроса, а про его ФОРМУ. Дека возвращает те же
анкеты и до, и после правки — разница видна только на объёме, где её уже никто
не чинит по-быстрому. Поэтому форму запроса приходится закреплять тестом.
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

import pytest
from sqlalchemy import and_, select
from sqlalchemy.dialects import postgresql

БОТ = Path(__file__).resolve().parents[2] / "bot"
СКРИПТЫ_БОТА = Path(__file__).resolve().parent / "скрипты_бота"


def прогнать_в_боте(имя_скрипта: str) -> dict:
    """Выполнить скрипт интерпретатором БОТА и вернуть его JSON-ответ.

    У бота свой venv (Python 3.12 против 3.14 у API), импортировать его код
    отсюда нечем. Скрипты лежат отдельными файлами в `скрипты_бота/`: на
    50 строк внутри тройных кавычек не работает ни подсветка, ни линтер.

    Имя без подчёркивания: тем же способом гоняются проверки суточных лимитов
    (`test_daily_limits.py`), и заводить второй такой запускатель значило бы
    расходиться в диагностике падений.
    """
    python = БОТ / ".venv" / "bin" / "python"
    if not python.exists():
        pytest.skip("venv бота не поднят в этом окружении")

    скрипт = СКРИПТЫ_БОТА / имя_скрипта
    assert скрипт.exists(), f"нет скрипта {скрипт}"

    результат = subprocess.run(
        [str(python), str(скрипт)], cwd=БОТ,
        capture_output=True, text=True, timeout=120,
    )
    if результат.returncode != 0 and "aiosqlite" in результат.stderr:
        pytest.skip("в venv бота нет aiosqlite — см. bot/requirements-dev.txt")
    assert результат.returncode == 0, результат.stderr[-1500:]
    return json.loads(результат.stdout.strip().splitlines()[-1])


_СКРИПТ_ДЕКИ_БОТА = """
import asyncio, json, sys
sys.path.insert(0, ".")

from sqlalchemy.dialects import postgresql
import database.connection as c

запросы = []

class ФейковыйРезультат:
    def scalar_one_or_none(self): return None
    def scalars(self): return self
    def all(self): return []

class ФейковаяСессия:
    async def __aenter__(self): return self
    async def __aexit__(self, *a): return False
    async def execute(self, stmt):
        запросы.append(str(stmt.compile(
            dialect=postgresql.dialect(),
            compile_kwargs={"literal_binds": True})))
        return ФейковыйРезультат()

c._session_cls = lambda: ФейковаяСессия

async def main():
    await c.get_deck_profiles("МОЙ-ID", limit=5)
    дека = [q for q in запросы if "dating_profiles" in q and "JOIN" in q]
    print(json.dumps({
        "всего_запросов": len(запросы),
        "анти_джойнов": sum(q.count("NOT (EXISTS") for q in дека),
        "есть_список_id": any(" IN (" in q.replace("EXISTS", "") for q in дека),
        "корреляций": sum(q.count("dating_profiles.user_id") for q in дека),
    }))

asyncio.run(main())
"""


def _sql_деки(user_id: str = "МОЙ-ID") -> str:
    """Скомпилированный SQL условия отбора кандидатов, как его увидит Postgres."""
    from models.models import Profile, User
    from services.matching import _уже_показывали

    запрос = (
        select(Profile.user_id)
        .join(User, Profile.user_id == User.id)
        .where(and_(*_уже_показывали(user_id)))
    )
    return str(
        запрос.compile(
            dialect=postgresql.dialect(), compile_kwargs={"literal_binds": True}
        )
    )


def test_дека_исключает_анти_джойном_а_не_списком_id():
    """`NOT IN (...)` со списком лайков — главный убийца деки на объёме.

    Активный свайпер набирает десятки тысяч лайков. Раньше все они читались в
    Python и уезжали обратно одним `NOT IN` с 50 000 плейсхолдеров: план не
    кэшировался (набор параметров каждый раз новый), а анти-джойн вырождался в
    Seq Scan по `dating_profiles`. Одно планирование занимало секунды — на
    КАЖДЫЙ свайп.
    """
    sql = _sql_деки()

    assert sql.count("NOT (EXISTS") == 3, (
        "ожидались три анти-джойна: свои лайки/пропуски, блокировки в обе "
        f"стороны, чужие «пропустить». Получилось:\n{sql}"
    )
    # Подзапросы обязаны коррелировать с внешней таблицей — иначе это не
    # анти-джойн, а проверка «есть ли вообще хоть один лайк»
    assert sql.count("dating_profiles.user_id") >= 4, (
        f"подзапросы не связаны с кандидатом:\n{sql}"
    )
    assert " IN (" not in sql.replace("EXISTS", ""), (
        f"в деку вернулся список id:\n{sql}"
    )


def test_анти_джойны_деки_опираются_на_существующие_индексы():
    """Анти-джойн без индекса — тот же Seq Scan, только незаметнее.

    Условия подзапросов и индексы живут в разных файлах: колонку в запросе
    поменять легко, индекс при этом останется от старой.
    """
    from models.models import Block, Like

    sql = _sql_деки()

    индексы = {
        и.name: tuple(к.name for к in и.columns)
        for таблица in (Like.__table__, Block.__table__)
        for и in таблица.indexes
    }

    for колонка in (
        "dating_likes.liker_id",
        "dating_likes.liked_id",
        "dating_blocks.blocker_id",
        "dating_blocks.blocked_id",
    ):
        таблица, поле = колонка.split(".")
        assert колонка in sql, f"{колонка} больше не участвует в отборе"
        assert any(поле in кортеж for кортеж in индексы.values()), (
            f"по {колонка} фильтруем, а индекса нет — анти-джойн станет "
            f"полным сканом {таблица}. Индексы: {индексы}"
        )


def test_сборка_деки_не_вычитывает_историю_лайков_в_python():
    """Списки id не должны возвращаться в код обходным путём.

    Правка «просто добавлю ещё одно условие» обычно выглядит как ещё один
    `select(Like.liked_id).where(...)` рядом — и весь выигрыш пропадает.
    """
    import inspect

    from services import matching

    исходник = inspect.getsource(matching.get_deck_profiles)

    for запрещено in (
        "select(Like.liked_id)",
        "select(Like.liker_id)",
        "select(Block.blocked_id)",
        "select(Block.blocker_id)",
    ):
        assert запрещено not in исходник, (
            f"{запрещено} снова читает историю в Python — на активном "
            "свайпере это десятки тысяч строк на каждый запрос деки"
        )
    assert "exclude_ids" not in исходник, "вернулся набор id вместо анти-джойна"


def test_дека_бота_тоже_без_списка_id():
    """У бота своя копия деки, и ломается она ровно так же.

    Бот живёт в отдельном venv, импортировать его код отсюда нечем — поэтому
    запускаем деку его собственным интерпретатором с подставной сессией и
    смотрим на SQL, который ушёл бы в Postgres. Это тот же класс расхождения,
    что и с витриной тарифов: правку в API легко не перенести в бота.
    """
    python = БОТ / ".venv" / "bin" / "python"
    if not python.exists():
        pytest.skip("venv бота не поднят в этом окружении")

    результат = subprocess.run(
        [str(python), "-c", _СКРИПТ_ДЕКИ_БОТА], cwd=БОТ,
        capture_output=True, text=True, timeout=120,
    )
    assert результат.returncode == 0, результат.stderr[-1500:]
    ответ = json.loads(результат.stdout.strip().splitlines()[-1])

    assert ответ["анти_джойнов"] >= 3, (
        "дека бота отбирает кандидатов списком id — на объёме это тот же "
        f"Seq Scan, что был в API: {ответ}"
    )
    assert not ответ["есть_список_id"], (
        f"в деку бота вернулся список исключений: {ответ}"
    )
    # Раньше дека бота делала 4 отдельных запроса за историей лайков и
    # блокировок до самой выборки. Осталась своя анкета + выборка (+ добор).
    assert ответ["всего_запросов"] <= 3, (
        f"бот снова вычитывает историю в Python: {ответ}"
    )


def test_дека_бота_исключает_тех_же_людей_что_и_api():
    """Состав выдачи, а не форма запроса.

    Форму проверяет тест выше, и этого мало: заменить двустороннюю проверку
    блокировок на одностороннюю можно, не тронув ни число анти-джойнов, ни
    корреляции. SQL остаётся «правильной формы», а жертва харассмента снова
    видит обидчика в деке.

    Поэтому дека бота прогоняется целиком на SQLite в памяти — те же четыре
    условия исключения, что и в API (tests/test_deck_exclusions.py).
    """
    ответ = прогнать_в_боте("дека_исключения.py")

    assert ответ["чистый_виден"], (
        f"дека пуста целиком — проверять исключения не на чем: {ответ}"
    )
    assert not ответ["сам_себя"], f"бот показывает меня самому себе: {ответ}"
    assert not ответ["заблокировавший_меня"], (
        f"заблокировавший меня попал в деку бота: {ответ}"
    )
    assert not ответ["кого_лайкнул"], (
        f"тот, кому я уже поставил лайк, снова в деке: {ответ}"
    )
    assert not ответ["кто_пропустил_меня"], (
        f"тот, кто меня пропустил, снова в деке — свайп впустую: {ответ}"
    )


def test_возрастной_фильтр_бота_совпадает_с_api():
    """Возраст бот фильтрует в SQL, API — в Python. Отсюда два расхождения.

    Первое: сравнение `birth_date >= …` с NULL даёт NULL, и анкета без даты
    рождения выпадала из деки бота целиком — а `age_min`/`age_max` имеют
    значения по умолчанию (18/99) и всегда истинны, так что фильтр применялся
    ко всем. Человек исчезал из бота, оставаясь видимым в мини-аппе.

    Второе: API проверяет диапазон в обе стороны — и «подходит ли он мне», и
    «подхожу ли я ему». В боте второй проверки не было, и 31-летний видел
    анкеты тех, кто ищет 18-25.
    """
    ответ = прогнать_в_боте("дека_исключения.py")

    assert ответ["без_даты_рождения_виден"], (
        "анкета без даты рождения выпала из деки бота, хотя в мини-аппе она "
        f"показывается: {ответ}"
    )
    assert not ответ["ищет_молодых_виден"], (
        "бот показывает анкету, в чей возрастной диапазон я не попадаю — "
        f"взаимности не будет, свайп впустую: {ответ}"
    )


def test_список_мэтчей_бота_не_растёт_по_запросу_на_мэтч():
    """Открыть «Мои мэтчи» — постоянное число round-trip'ов, а не по одному на мэтч.

    Раньше `handlers/matches.py` шёл циклом по мэтчам и на каждый звал
    `get_profile` за именем. Каждый вызов БРАЛ СВОЮ СЕССИЮ из пула бота (5
    постоянных плюс 10 сверх), и всё это время занят общий цикл aiogram: у
    человека с полусотней мэтчей одно нажатие кнопки — полсотни
    последовательных запросов к базе.

    Считаются реальные обращения через `before_cursor_execute`, а не форма SQL:
    вернуть цикл можно, не изменив ни одного запроса по отдельности. Проверено
    откатом — со старой реализацией на тех же данных выходит 14 запросов.

    Сравниваются ДВА прогона на разном числе мэтчей, а не число с константой.
    Точное число здесь уже менялось (суточный лимит открытий добавил свои
    запросы за тарифом и счётчиком), и закреплённая константа ловила бы честные
    правки вместо регрессии. Инвариант — независимость от числа мэтчей.
    """
    ответ = прогнать_в_боте("список_мэтчей.py")

    assert ответ["мэтчей"] == 13, (
        f"выборка мэтчей изменилась — остальное проверять не на чем: {ответ}"
    )
    assert ответ["мэтчей_много"] > ответ["мэтчей"], (
        f"оба прогона на одном объёме — сравнивать нечего: {ответ}"
    )
    assert ответ["запросов_на_многих"] == ответ["запросов"], (
        "число запросов выросло вместе с числом мэтчей — список снова "
        f"собирается по одному запросу на мэтч: {ответ}"
    )
    # Верхняя граница — на случай, если запросы станут константными, но их
    # окажется двадцать: инвариант выше такое пропустит
    assert ответ["запросов"] <= 5, (
        f"на список мэтчей уходит слишком много обращений к базе: {ответ}"
    )
    assert ответ["закрытых"] == 0, (
        "мэтчи закрыты лимитом, хотя ни один ещё не открывали — квота "
        f"списывается за просмотр списка: {ответ}"
    )


def test_имя_собеседника_приходит_вместе_с_мэтчем():
    """Состав ответа, а не число запросов.

    Один запрос можно сделать и с INNER JOIN, и с джойном по одному столбцу
    пары — счётчик останется единицей, а список мэтчей испортится: беседа с
    человеком без анкеты пропадёт из интерфейса, а в половине пар партнёром
    окажусь я сам.
    """
    ответ = прогнать_в_боте("список_мэтчей.py")

    assert ответ["все_с_именами"], f"мэтч без имени собеседника: {ответ}"
    assert ответ["себя_в_партнёрах_нет"], (
        f"в партнёрах оказался я сам — CASE разбирает пару в одну сторону: {ответ}"
    )
    # Я — второй участник этой пары, партнёр обязан вычислиться в обратную сторону
    assert ответ["имя_обратной_пары"] == "Партнёр 2", (
        f"перевёрнутая пара разобрана неверно: {ответ}"
    )
    assert ответ["без_анкеты_в_списке"], (
        "мэтч с человеком без анкеты выпал из списка — чат есть, а в "
        f"интерфейсе его нет (INNER JOIN вместо LEFT): {ответ}"
    )
    assert ответ["имя_без_анкеты"] == "Аноним", (
        f"вместо имени брошенной анкеты пришло {ответ['имя_без_анкеты']!r}"
    )
    assert not ответ["разведённый_в_списке"], (
        f"неактивный мэтч вернулся в список: {ответ}"
    )
    # Список открывают ради последних бесед
    assert ответ["порядок_по_убыванию"] == ["M12", "M11", "M10"], (
        f"порядок не по свежести: {ответ}"
    )


def test_обработчик_мэтчей_не_ходит_за_профилями():
    """Страховка от возврата цикла: `get_profile` в списке мэтчей не нужен.

    Тесты выше прогоняют функцию БД, а цикл жил в обработчике. Вернуть его
    можно, не тронув `get_user_matches` — и оба теста останутся зелёными.
    """
    исходник = (БОТ / "handlers" / "matches.py").read_text()
    список = исходник[исходник.index("async def list_matches"):]
    список = список[: список.index("@router.callback_query", 1)]
    # Комментарий в теле объясняет, почему цикла больше нет, и упоминает
    # `get_profile` — ищем именно вызов
    код = "\n".join(
        строка for строка in список.splitlines()
        if not строка.lstrip().startswith("#")
    )

    assert "get_profile(" not in код, (
        "в списке мэтчей снова вызывается get_profile — это запрос и сессия "
        "из пула на каждый мэтч"
    )
