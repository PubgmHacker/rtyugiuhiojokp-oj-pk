"""Комнаты WebSocket: одно pubsub-подключение на процесс, а не на чат.

Раньше `connect` поднимал по asyncio-задаче и по подключению к Redis на
КАЖДУЮ комнату. При 5 000 открытых чатов один процесс API (деплой идёт с
`--workers 1`) держал 5 000 соединений — упирался бы в `maxclients` задолго
до того, как кончится CPU. Здесь закрепляется и число подключений, и то, что
общий читатель переживает всё, от чего раньше умирал.

Redis для этих тестов не нужен: подставляется двойник с той же семантикой
pub/sub. Настоящий Redis проверяется отдельным тестом в конце файла — он
пропускается, если сервер не поднят.
"""

from __future__ import annotations

import asyncio
import json

import pytest

ЖДАТЬ = 0.15  # читателю нужно проснуться на своём таймауте


class ФейковыйPubSub:
    """Подписка на каналы общего двойника Redis."""

    def __init__(self, сервер: "ФейковыйRedis") -> None:
        self.сервер = сервер
        self.очередь: list[dict] = []
        self.каналы: set[str] = set()
        self.закрыт = False
        self.падать_на_чтении = False

    async def subscribe(self, *каналы: str) -> None:
        if self.сервер.лежит:
            raise ConnectionError("redis недоступен")
        for канал in каналы:
            self.каналы.add(канал)
            подписчики = self.сервер.подписчики.setdefault(канал, [])
            # Повторный SUBSCRIBE на тот же канал в настоящем Redis
            # идемпотентен: доставка не задваивается. Без этой проверки
            # двойник врал бы на мгновенном реконнекте, где подписка
            # поднимается заново по уже живому каналу.
            if self not in подписчики:
                подписчики.append(self)

    async def unsubscribe(self, *каналы: str) -> None:
        for канал in каналы:
            self.каналы.discard(канал)
            подписчики = self.сервер.подписчики.get(канал) or []
            if self in подписчики:
                подписчики.remove(self)

    async def get_message(self, ignore_subscribe_messages=False, timeout=0.0):
        if self.падать_на_чтении:
            raise ConnectionError("соединение оборвалось")
        if self.очередь:
            return self.очередь.pop(0)
        # Настоящий get_message возвращает None по таймауту, в том числе
        # на пустой подписке — на этом и держится общий читатель
        await asyncio.sleep(min(timeout or 0.01, 0.02))
        return None

    async def aclose(self) -> None:
        self.закрыт = True
        for канал in list(self.каналы):
            await self.unsubscribe(канал)


class ФейковыйRedis:
    def __init__(self) -> None:
        self.подписчики: dict[str, list[ФейковыйPubSub]] = {}
        self.ключи: dict[str, str] = {}
        self.выданные_pubsub: list[ФейковыйPubSub] = []
        self.лежит = False

    def pubsub(self) -> ФейковыйPubSub:
        ps = ФейковыйPubSub(self)
        self.выданные_pubsub.append(ps)
        return ps

    async def publish(self, канал: str, данные: str) -> None:
        for ps in list(self.подписчики.get(канал, [])):
            ps.очередь.append({"type": "message", "channel": канал, "data": данные})

    async def set(self, key, value, ex=None) -> None:
        self.ключи[key] = value

    async def delete(self, key) -> None:
        self.ключи.pop(key, None)

    async def exists(self, key) -> int:
        return 1 if key in self.ключи else 0


class ФейковыйСокет:
    """Сокет, который запоминает отправленное. `рвётся` — имитация обрыва."""

    def __init__(self, имя: str = "ws", рвётся: bool = False) -> None:
        self.имя = имя
        self.рвётся = рвётся
        self.получено: list[dict] = []

    async def send_json(self, payload: dict) -> None:
        if self.рвётся:
            raise RuntimeError(f"{self.имя}: сокет закрыт")
        self.получено.append(payload)


@pytest.fixture
async def комнаты(monkeypatch):
    """Свежий RoomManager на двойнике Redis; гасится после теста."""
    import services.ws_manager as wm

    сервер = ФейковыйRedis()

    async def _get_redis():
        return сервер

    monkeypatch.setattr(wm, "get_redis", _get_redis)
    менеджер = wm.RoomManager()
    try:
        yield менеджер, сервер
    finally:
        await менеджер.aclose()


async def test_много_комнат_живут_на_одном_подключении(комнаты):
    """Главное следствие правки: подключения к Redis не растут с числом чатов.

    Именно здесь ломался масштаб. 5 000 открытых чатов — 5 000 подключений и
    5 000 задач из одного процесса; счёт упирался в `maxclients`, а не в CPU.
    """
    менеджер, сервер = комнаты

    for i in range(200):
        await менеджер.connect(f"m{i}", ФейковыйСокет(f"ws{i}"), f"u{i}")

    assert len(сервер.выданные_pubsub) == 1, (
        f"на 200 комнат открыто подключений: {len(сервер.выданные_pubsub)} — "
        "вернулось по подключению на чат"
    )
    задачи = [з for з in asyncio.all_tasks() if "_read_forever" in str(з.get_coro())]
    assert len(задачи) == 1, f"читателей больше одного: {len(задачи)}"
    # Подписки при этом настоящие: канал каждой комнаты на месте
    assert len(сервер.выданные_pubsub[0].каналы) == 200


async def test_сообщение_из_redis_доходит_до_своей_комнаты(комнаты):
    """Комната определяется по имени канала, а не по замыканию задачи.

    Читатель один на все чаты, поэтому маршрутизация — его работа. Ошибись
    в разборе канала, и сообщение уйдёт чужому собеседнику.
    """
    менеджер, сервер = комнаты
    свой, чужой = ФейковыйСокет("свой"), ФейковыйСокет("чужой")
    await менеджер.connect("МЭТЧ-А", свой, "u1")
    await менеджер.connect("МЭТЧ-Б", чужой, "u2")

    await сервер.publish(
        "dating:match:МЭТЧ-А",
        json.dumps({"type": "message", "text": "привет", "origin": "ДРУГОЙ-ИНСТАНС"}),
    )
    await asyncio.sleep(ЖДАТЬ)

    assert свой.получено == [{"type": "message", "text": "привет"}], (
        f"адресат не получил сообщение: {свой.получено}"
    )
    assert чужой.получено == [], f"сообщение утекло в чужой чат: {чужой.получено}"


async def test_своё_эхо_не_дублируется(комнаты):
    """`publish` рассылает локально и уходит в Redis — назад оно вернётся.

    Без отсева по origin собеседник на этом же инстансе увидел бы каждое
    сообщение дважды.
    """
    менеджер, _ = комнаты
    сокет = ФейковыйСокет()
    await менеджер.connect("МЭТЧ", сокет, "u1")

    await менеджер.publish("МЭТЧ", {"type": "message", "text": "раз"})
    await asyncio.sleep(ЖДАТЬ)

    assert len(сокет.получено) == 1, f"сообщение задвоилось: {сокет.получено}"
    assert "origin" not in сокет.получено[0], "служебное поле утекло клиенту"


async def test_пустая_комната_отписывается_но_читатель_живёт(комнаты):
    """`listen()` тут не подошёл бы: его цикл выходит на последней отписке.

    Волна «все ушли — кто-то вернулся» — обычное дело, и читатель обязан её
    пережить, иначе задача перезапускается на каждой.
    """
    менеджер, сервер = комнаты
    первый = ФейковыйСокет("первый")
    await менеджер.connect("МЭТЧ", первый, "u1")
    читатель = менеджер._reader

    менеджер.disconnect("МЭТЧ", первый)
    await asyncio.sleep(ЖДАТЬ)

    assert "dating:match:МЭТЧ" not in сервер.выданные_pubsub[0].каналы, (
        "канал опустевшей комнаты остался в подписке"
    )
    assert not читатель.done(), "читатель умер вместе с последней комнатой"

    # Кто-то вернулся: подписка поднимается на том же читателе
    второй = ФейковыйСокет("второй")
    await менеджер.connect("МЭТЧ", второй, "u2")
    assert менеджер._reader is читатель, "читатель перезапустился"
    assert len(сервер.выданные_pubsub) == 1, "открылось второе подключение"

    await сервер.publish(
        "dating:match:МЭТЧ",
        json.dumps({"type": "message", "text": "снова", "origin": "ДРУГОЙ"}),
    )
    await asyncio.sleep(ЖДАТЬ)
    assert второй.получено == [{"type": "message", "text": "снова"}], (
        f"после возврата в комнату сообщения не идут: {второй.получено}"
    )


async def test_мгновенный_реконнект_не_теряет_подписку(комнаты):
    """Отписка асинхронная, вход в комнату — нет. Между ними успевают войти.

    `disconnect` синхронный (его зовут из `broadcast` и из `finally` роутеров),
    поэтому отписка уходит отдельной задачей. Пока она ждёт лока, клиент
    успевает переподключиться — обычное дело при потере сети или закрытой и
    сразу открытой вкладке. Без повторной проверки `self.rooms` отписка снимет
    канал ЖИВОЙ комнаты: локально собеседники видят друг друга, а сообщения с
    других инстансов и от бота молча перестают приходить.
    """
    менеджер, сервер = комнаты
    первый = ФейковыйСокет("первый")
    await менеджер.connect("МЭТЧ", первый, "u1")

    # Без await между ними: задача отписки уже создана, но ещё не выполнялась
    менеджер.disconnect("МЭТЧ", первый)
    второй = ФейковыйСокет("второй")
    await менеджер.connect("МЭТЧ", второй, "u1")
    await asyncio.sleep(ЖДАТЬ)  # здесь отписка добирается до лока

    assert "dating:match:МЭТЧ" in сервер.выданные_pubsub[0].каналы, (
        "отписка сняла канал комнаты, в которую уже вернулись"
    )
    await сервер.publish(
        "dating:match:МЭТЧ",
        json.dumps({"type": "message", "text": "после реконнекта", "origin": "ДРУГОЙ"}),
    )
    await asyncio.sleep(ЖДАТЬ)
    assert второй.получено == [{"type": "message", "text": "после реконнекта"}], (
        f"после мгновенного реконнекта сообщения не доходят: {второй.получено}"
    )


async def test_обрыв_последнего_сокета_во_время_рассылки_не_убивает_читателя(комнаты):
    """Самоотмена: `broadcast` → `disconnect` → отмена ЭТОЙ ЖЕ задачи.

    Мёртвый сокет отцепляется прямо в `broadcast`, а `broadcast` вызывается из
    читателя. Раньше `disconnect` отменял задачу-слушателя комнаты — то есть
    ту, которая в этот момент выполняется. Комната умирала на середине
    итерации, и оставшиеся в ней собеседники переставали получать события.
    """
    менеджер, сервер = комнаты
    мёртвый = ФейковыйСокет("мёртвый", рвётся=True)
    await менеджер.connect("МЭТЧ", мёртвый, "u1")
    читатель = менеджер._reader

    await сервер.publish(
        "dating:match:МЭТЧ",
        json.dumps({"type": "message", "text": "в пустоту", "origin": "ДРУГОЙ"}),
    )
    await asyncio.sleep(ЖДАТЬ)

    assert not читатель.done(), (
        "читатель отменил сам себя, разослав сообщение в мёртвый сокет"
    )
    assert менеджер._reader is читатель
    # И следующая комната работает на том же читателе
    живой = ФейковыйСокет("живой")
    await менеджер.connect("МЭТЧ-2", живой, "u2")
    await сервер.publish(
        "dating:match:МЭТЧ-2",
        json.dumps({"type": "message", "text": "работает", "origin": "ДРУГОЙ"}),
    )
    await asyncio.sleep(ЖДАТЬ)
    assert живой.получено == [{"type": "message", "text": "работает"}]


async def test_после_обрыва_redis_подписки_возвращаются(комнаты):
    """Реконнект без пересборки подписок = чат работает только внутри инстанса.

    Молча: локальные собеседники видят друг друга, а сообщения с других
    инстансов и от бота просто перестают приходить.
    """
    менеджер, сервер = комнаты
    сокет = ФейковыйСокет()
    await менеджер.connect("МЭТЧ", сокет, "u1")
    первый_pubsub = сервер.выданные_pubsub[0]

    первый_pubsub.падать_на_чтении = True
    await asyncio.sleep(1.4)  # пауза перед пересборкой — 1 с

    assert len(сервер.выданные_pubsub) == 2, (
        f"pubsub не пересобран после обрыва: {len(сервер.выданные_pubsub)}"
    )
    assert "dating:match:МЭТЧ" in сервер.выданные_pubsub[1].каналы, (
        "живая комната осталась без подписки после реконнекта"
    )

    await сервер.publish(
        "dating:match:МЭТЧ",
        json.dumps({"type": "message", "text": "после обрыва", "origin": "ДРУГОЙ"}),
    )
    await asyncio.sleep(ЖДАТЬ)
    assert сокет.получено == [{"type": "message", "text": "после обрыва"}], (
        f"после реконнекта сообщения не доходят: {сокет.получено}"
    )


async def test_недоступный_redis_не_ломает_локальный_чат(комнаты):
    """Собеседники на одном инстансе обязаны видеть друг друга без Redis."""
    менеджер, сервер = комнаты
    сервер.лежит = True

    он, она = ФейковыйСокет("он"), ФейковыйСокет("она")
    await менеджер.connect("МЭТЧ", он, "u1")
    await менеджер.connect("МЭТЧ", она, "u2")
    await менеджер.publish("МЭТЧ", {"type": "message", "text": "локально"}, exclude=он)

    assert она.получено == [{"type": "message", "text": "локально"}]
    assert он.получено == [], "отправителю вернулось его же сообщение"


async def test_shutdown_гасит_читателя(комнаты):
    """`aclose` должен быть достижим: метод, который никто не зовёт, — не фикс."""
    менеджер, сервер = комнаты
    await менеджер.connect("МЭТЧ", ФейковыйСокет(), "u1")
    читатель = менеджер._reader

    await менеджер.aclose()

    assert читатель.done(), "задача-читатель пережила остановку"
    assert менеджер._reader is None and менеджер._pubsub is None
    assert сервер.выданные_pubsub[0].закрыт, "подключение к Redis не закрыто"


def test_lifespan_гасит_комнаты_до_закрытия_redis():
    """Читатель живёт на том же соединении — порядок в shutdown важен.

    Закрыть Redis первым значит разбудить читателя на мёртвом сокете и
    отправить его в цикл переподключения прямо во время остановки процесса.
    """
    import inspect

    import main

    исходник = inspect.getsource(main.lifespan)
    _, после_yield = исходник.split("yield", 1)

    assert "room_manager.aclose()" in после_yield, (
        "менеджер комнат не гасится на shutdown: задача-читатель переживёт "
        "остановку приложения"
    )
    assert после_yield.index("room_manager.aclose()") < после_yield.index(
        "_redis.aclose()"
    ), "Redis закрывается раньше читателя комнат"
