"""Имена, которых нет: NameError, доживший до продакшена.

Python не проверяет имена до выполнения строки. Функция с опечаткой или с
исчезнувшим импортом импортируется молча и падает только когда до неё дойдёт
живой пользователь — а в боте это ветка, куда заходят раз в сутки.

Так и случилось при правке списка мэтчей: из `handlers/matches.py` убрали
`get_profile` вместе с циклом, а в `chat_hint` он остался. Тесты были зелёные,
модуль импортировался, кнопка «подсказка» упала бы у первого нажавшего.

Линтера в проекте нет (ни ruff, ни pyflakes ни в одном venv), а бот вдобавок
живёт в отдельном интерпретаторе — его код отсюда не импортировать. Поэтому
разбираем ОБА кодовых дерева стандартным `symtable`: он строит те же таблицы
областей видимости, что и компилятор, и знает про вложенные функции, замыкания,
comprehension'ы и class-скоупы.

Проверка статическая, до запуска, и потому ловит ветки, до которых тесты не
доходят.
"""

from __future__ import annotations

import builtins
import symtable
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]

#: Имена, которые интерпретатор кладёт в модуль сам — в исходнике их не найти
СЛУЖЕБНЫЕ = {
    "__name__",
    "__file__",
    "__doc__",
    "__package__",
    "__builtins__",
    "__spec__",
    "__loader__",
}

#: Что разбираем. Тесты сюда не входят: в них глобальные имена приходят из
#: conftest-фикстур, и symtable об этом не знает
ДЕРЕВЬЯ = ("bot", "api")
ПРОПУСК = {".venv", "node_modules", "__pycache__", "tests", "migrations", "alembic"}


def _модули() -> list[Path]:
    файлы = []
    for дерево in ДЕРЕВЬЯ:
        for файл in sorted((КОРЕНЬ / дерево).rglob("*.py")):
            if ПРОПУСК & set(файл.parts):
                continue
            файлы.append(файл)
    return файлы


def _имена_модуля(таблица: symtable.SymbolTable) -> set[str]:
    """Всё, что модуль определяет у себя наверху: импорты, def, class, присваивания."""
    return {
        символ.get_name()
        for символ in таблица.get_symbols()
        if символ.is_assigned() or символ.is_imported() or символ.is_namespace()
    }


def _необъявленные(таблица, верхние: set[str], найдено: list) -> None:
    """Рекурсивно: имена, которые функция берёт из модуля, а модуль их не знает.

    `is_global()` — вердикт самого компилятора: имя не локальное, не параметр и
    не замыкание из объемлющей функции. Значит, искать его будут в globals, а
    потом в builtins — и если нет ни там, ни там, это NameError на исполнении.
    """
    for область in таблица.get_children():
        for символ in область.get_symbols():
            if not символ.is_global():
                continue
            # Импорт или присваивание внутри самой функции создают локальное
            # имя — такие сюда не попадают, но проверка дешёвая
            if символ.is_assigned() or символ.is_imported():
                continue
            имя = символ.get_name()
            if имя in верхние or имя in СЛУЖЕБНЫЕ or hasattr(builtins, имя):
                continue
            найдено.append((область.get_name(), область.get_lineno(), имя))
        _необъявленные(область, верхние, найдено)


@pytest.mark.parametrize(
    "модуль", _модули(), ids=lambda p: str(p.relative_to(КОРЕНЬ))
)
def test_все_имена_объявлены(модуль: Path):
    """Ни одна функция не зовёт имя, которого в модуле нет."""
    исходник = модуль.read_text()
    try:
        таблица = symtable.symtable(исходник, str(модуль), "exec")
    except SyntaxError as ошибка:  # pragma: no cover — файл просто не собран
        pytest.fail(f"{модуль.relative_to(КОРЕНЬ)} не компилируется: {ошибка}")

    найдено: list[tuple[str, int, str]] = []
    _необъявленные(таблица, _имена_модуля(таблица), найдено)

    assert not найдено, "\n".join(
        f"{модуль.relative_to(КОРЕНЬ)}:{строка} в {где}() → {имя} "
        f"— имени нет ни в модуле, ни в builtins: NameError при вызове"
        for где, строка, имя in найдено
    )


def test_проверка_ловит_исчезнувший_импорт():
    """Сам детектор: на коде с пропавшим импортом он обязан сработать.

    Тест выше зелёный на чистом дереве, и таким же зелёным он останется, если
    разбор сломается и начнёт возвращать пустой список.
    """
    сломанный = (
        "from database import get_or_create_user\n"
        "\n"
        "async def chat_hint(user_id):\n"
        "    me = await get_profile(user_id)\n"
        "    return me\n"
    )
    таблица = symtable.symtable(сломанный, "<тест>", "exec")
    найдено: list[tuple[str, int, str]] = []
    _необъявленные(таблица, _имена_модуля(таблица), найдено)

    assert [(где, имя) for где, _, имя in найдено] == [("chat_hint", "get_profile")]


def test_проверка_не_шумит_на_законных_именах():
    """И обратное: замыкания, локальные импорты и builtins — не находки.

    Без этого детектор легко «починить» до состояния, когда он ругается на всё
    подряд, и его отключат целиком.
    """
    законный = (
        "import json\n"
        "ФЛАГ = 1\n"
        "\n"
        "def внешняя(данные):\n"
        "    накопитель = []\n"
        "    def внутренняя():\n"
        "        return накопитель, ФЛАГ, json.dumps(данные), len(данные)\n"
        "    from database.connection import _session_cls\n"
        "    return внутренняя, _session_cls, [x for x in данные if x]\n"
        "\n"
        "class Штука:\n"
        "    поле = ФЛАГ\n"
        "    def метод(self):\n"
        "        return self.поле\n"
    )
    таблица = symtable.symtable(законный, "<тест>", "exec")
    найдено: list[tuple[str, int, str]] = []
    _необъявленные(таблица, _имена_модуля(таблица), найдено)

    assert найдено == [], f"ложные срабатывания: {найдено}"
