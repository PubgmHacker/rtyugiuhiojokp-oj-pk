"""Проверки демо-переписок (tools/demo_dialogues.py).

С этих данных снимаются скриншоты магазина и на них смотрит ревьюер
App Store, поэтому «нейрослоп» в них — не косметика, а то, что первым
видит человек. Правила, которые здесь заперты:

 · никаких эмодзи и обращений «Привет!» — этого нет во всём продукте;
 · чат не должен быть ровным сценарием «он — я — он»: нужны два пузыря
   подряд, непрочитанный хвост и брошенная ветка;
 · на витрине обязаны быть видны голосовое, кружок, цитата и реакция —
   иначе снимок продаёт мессенджер из 2012 года;
 · формы кружков и ключи реакций сверяются с настоящими константами
   сервера: переименуют ключ — сеятель молча запишет мусор, и пузырь
   на скриншоте окажется пустым.
"""

import re
import sys
from pathlib import Path

import pytest

ИНСТРУМЕНТЫ = Path(__file__).resolve().parents[2] / "tools"
sys.path.insert(0, str(ИНСТРУМЕНТЫ))

from demo_dialogues import ДИАЛОГИ, СУПЕРЛАЙКИ, волна  # noqa: E402

from services.media_notes import VIDEO_NOTE_SHAPES  # noqa: E402
from services.reactions import REACTION_KEYS  # noqa: E402

#: Пиктограммы: эмодзи, дингбаты и вариационный селектор. «))» и тире —
#: обычные знаки и под запрет не попадают.
ЭМОДЗИ = re.compile(
    "[\U0001f000-\U0001faff☀-➿️⬀-⯿←-⇿]"
)

ЗАПРЕЩЕНО = (
    "общие интересы", "зацепило", "расскажи о себе", "как дела",
    "привет!", "хей", "не стесняйся", "буду рад пообщаться",
)


def _все_тексты() -> list[str]:
    return [р.текст for д in ДИАЛОГИ for р in д.реплики if р.текст] + list(СУПЕРЛАЙКИ)


def test_без_эмодзи():
    for текст in _все_тексты():
        найдено = ЭМОДЗИ.findall(текст)
        assert not найдено, f"эмодзи {найдено} в «{текст}»"


def test_без_штампов():
    for текст in _все_тексты():
        низ = текст.lower()
        for штамп in ЗАПРЕЩЕНО:
            assert штамп not in низ, f"штамп «{штамп}» в «{текст}»"


def test_не_начинается_с_приветствия():
    for текст in _все_тексты():
        первое = текст.lower().split()[0].strip(",.!?")
        assert первое not in ("привет", "приветик", "хей", "хай", "здравствуй")


def test_реплики_рваные():
    """Хотя бы где-то два пузыря подряд от одного человека."""
    подряд = 0
    for д in ДИАЛОГИ:
        for a, b in zip(д.реплики, д.реплики[1:]):
            if a.кто == b.кто:
                подряд += 1
    assert подряд >= 4, f"строгое чередование в {len(ДИАЛОГИ)} диалогах: {подряд} повторов"


def test_есть_живой_хвост():
    """Непрочитанное последнее сообщение и брошенная односторонняя ветка."""
    непрочитанные_хвосты = [д for д in ДИАЛОГИ if д.реплики and not д.реплики[-1].прочитано]
    assert len(непрочитанные_хвосты) >= 3

    односторонние = [
        д for д in ДИАЛОГИ if len({р.кто for р in д.реплики}) == 1
    ]
    assert односторонние, "нет ни одной переписки без ответа — так не бывает"


def test_витрина_чата_полная():
    голос = [р for д in ДИАЛОГИ for р in д.реплики if р.голос]
    кружки = [р for д in ДИАЛОГИ for р in д.реплики if р.кружок]
    цитаты = [р for д in ДИАЛОГИ for р in д.реплики if р.ответ is not None]
    реакции = [р for д in ДИАЛОГИ for р in д.реплики if р.реакция]
    assert голос and кружки and цитаты and реакции
    # Формы должны отличаться: одна и та же на всех кружках не показывает
    # саму фишку выбора формы.
    assert len({р.форма for р in кружки}) >= 2


def test_медиа_по_контракту_сервера():
    for д in ДИАЛОГИ:
        for р in д.реплики:
            if р.кружок:
                assert р.форма in VIDEO_NOTE_SHAPES, р.форма
                assert 1 <= р.кружок <= 60
            if р.голос:
                assert 1 <= р.голос <= 60
            if р.реакция:
                assert р.реакция in REACTION_KEYS, р.реакция


def test_цитаты_смотрят_назад():
    for н, д in enumerate(ДИАЛОГИ):
        for i, р in enumerate(д.реплики):
            if р.ответ is not None:
                assert 0 <= р.ответ < i, f"диалог {н}: цитата на {р.ответ} из {i}"


def test_каждая_реплика_что_то_несёт():
    for д in ДИАЛОГИ:
        assert д.пол in ("female", "male")
        assert д.реплики, "пустой диалог"
        for р in д.реплики:
            assert р.кто in ("я", "их")
            assert р.текст or р.голос or р.кружок
            assert р.минут >= 0


def test_время_идёт_от_старых_к_новым():
    """Внутри переписки `минут назад` обязано убывать: иначе разделители
    дней и порядок пузырей на скриншоте соврут."""
    for н, д in enumerate(ДИАЛОГИ):
        минуты = [р.минут for р in д.реплики]
        assert минуты == sorted(минуты, reverse=True), f"диалог {н}: {минуты}"


@pytest.mark.parametrize("секунд", [1, 3, 11, 24, 60])
def test_волна_в_контракте(секунд):
    столбики = волна(секунд * 13, секунд)
    assert 16 <= len(столбики) <= 64
    assert столбики.isdigit()
    # Ровный шум выдаёт заглушку: у речи есть и громкие слоги, и тихие.
    assert len(set(столбики)) >= 4
