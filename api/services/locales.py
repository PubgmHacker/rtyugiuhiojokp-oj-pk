"""Языки интерфейса: канонический список на стороне API.

Список задаёт бот — он рисует сетку выбора на первом шаге онбординга
(bot/texts.py: ONBOARDING_LOCALES). Здесь его копия, потому что API и бот
деплоятся отдельно, у них разные venv и общего модуля нет: API валидирует
входящий код и не может для этого импортировать модуль бота. Рассинхрон
списков ловит тест (api/tests/test_locale.py).

Тексты интерфейса здесь не живут. API хранит и отдаёт код языка; переводить
им — забота бота (bot/texts.py) и мини-аппа (web/src/lib/i18n.ts).
"""
from __future__ import annotations

#: Языки, между которыми человек выбирает на онбординге. Порядок — как в сетке
#: кнопок бота: русский первым, дальше по убыванию доли рынка.
ЯЗЫКИ: tuple[str, ...] = ("ru", "en", "uz", "es", "tr", "id", "zh")

#: Язык до выбора и для всех, кто зарегистрировался до появления колонки.
#: Совпадает с server_default в миграции a1e6f30c74d2 — и это правда о
#: продукте: весь его текст пока русский.
ПО_УМОЛЧАНИЮ = "ru"

#: Регулярка для Field(pattern=...): собирается из списка, чтобы добавленный
#: язык не пришлось дописывать во второе место и получить 422 на валидном коде.
ШАБЛОН = "^(" + "|".join(ЯЗЫКИ) + ")$"


def нормализовать(code: str | None) -> str:
    """Привести код к поддерживаемому. Мусор и пустота — язык по умолчанию.

    Для входящих запросов этого мало: там неизвестный код обязан давать 422
    (см. ШАБЛОН), иначе клиент считает, что язык сменился. Эта функция — для
    чтения уже сохранённого значения, где падать поздно и незачем.
    """
    язык = (code or "").strip().lower()
    return язык if язык in ЯЗЫКИ else ПО_УМОЛЧАНИЮ
