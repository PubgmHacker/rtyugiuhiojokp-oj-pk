def card_for_day(user_id: str, today: date | None = None) -> Card:
    """Карта дня: одна и та же для человека в течение суток.

    Берём хеш от пары «кто + когда», а не случайное число: расклад обязан
    совпадать при повторном запросе, иначе он ничего не стоит. И у разных
    людей в один день карты разные — общий расклад на всех выглядел бы
    рассылкой.
    """
    day = (today or date.today()).isoformat()
    digest = hashlib.sha256(f"{user_id}:{day}".encode()).digest()
    return CARDS[digest[0] % len(CARDS)]


async def phrase_for(card: Card) -> str:
    """Живая фраза от модели. Без ключа возвращает совет из справочника —
    раздел должен работать и на окружении без AI."""
    from config import get_settings
    from services.ai_moderation import _get_zhipu_client

    client = _get_zhipu_client()
    if not client:
        return card.advice

    try:
        import asyncio

        response = await asyncio.to_thread(
            client.chat.completions.create,
            model=get_settings().ZHIPU_TEXT_MODEL,
            messages=[
                {
                    "role": "system",
                    "content": (
                        "Ты пишешь короткий совет дня для приложения знакомств. "
                        "Одно предложение до 120 символов, на русском, "
                        "без мистики и обещаний будущего — только практический "
                        "совет про общение и знакомства."
                    ),
                },
                {
                    "role": "user",
                    "content": f"Карта дня: {card.name}. Смысл: {card.meaning}.",
                },
            ],
            max_tokens=80,
            temperature=0.8,
        )
        text = (response.choices[0].message.content or "").strip()
        # Модель иногда отвечает абзацем или пустой строкой — тогда справочник
        return text[:200] if 10 <= len(text) <= 300 else card.advice
    except Exception as e:
        logger.warning(f"Не удалось получить фразу для расклада: {e}")
        return card.advice
