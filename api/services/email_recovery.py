"""Привязка почты и вход по ней, когда потерян Telegram.

Зачем: до сих пор аккаунт держался на одном Telegram. Потерял его — потерял и
анкету, и оплаченную подписку, и вернуть их было нечем. Для платящего это
прямая потеря денег, а поддержке нечем помочь: доказать, что аккаунт твой,
человек не может.

Почему так сделано:

* Почта хранится только подтверждённой. Непроверенная почта хуже, чем никакой:
  ошибся в букве — и восстановление уводит аккаунт постороннему.
* Код шестизначный, живёт минуты, гасится при первом использовании, попыток
  ввода немного. Шестизначное число перебирается мгновенно, если не считать
  попытки, — поэтому счётчик обязателен, а не «желателен».
* Ограничение на отправку: без него эндпоинт превращается в бесплатную
  рассылку по чужим адресам с нашего домена.
* Коды и счётчики живут в Redis: они короткоживущие, БД для них не нужна.
  Redis недоступен — честно отказываем, а не пропускаем без проверки.
* Сравнение кода — `secrets.compare_digest`: обычное `==` на строках выходит
  из цикла на первом несовпавшем символе, и по времени ответа код подбирается.

Само письмо отправляет `services/mailer.py`; здесь только коды и правила.
"""

from __future__ import annotations

import hashlib
import logging
import re
import secrets

from services.realtime import get_redis

logger = logging.getLogger(__name__)

#: Минуты жизни кода. Больше — шире окно для подбора и перехвата, меньше —
#: человек не успевает переключиться в почту.
CODE_TTL = 900
CODE_LENGTH = 6
#: Попыток ввода на один код. Шестизначное число перебирается мгновенно.
MAX_ATTEMPTS = 5
#: Сколько писем можно запросить с одного аккаунта в час.
MAX_SENDS_PER_HOUR = 5
SEND_WINDOW = 3600

#: Нарочно нестрогая проверка: валидировать почту регуляркой «по RFC»
#: бессмысленно, настоящую проверку делает само письмо с кодом.
_EMAIL_RE = re.compile(r"^[^@\s]+@[^@\s.]+\.[^@\s]+$")


def нормализовать(email: str) -> str:
    """Почта без регистра и пробелов.

    Иначе `Ivan@mail.ru` и `ivan@mail.ru` заводят два аккаунта, а уникальный
    ключ в базе их не поймает.
    """
    return (email or "").strip().lower()


def почта_похожа_на_настоящую(email: str) -> bool:
    return bool(_EMAIL_RE.match(нормализовать(email))) and len(email) <= 254


def _хеш(email: str) -> str:
    """Ключ Redis по почте, а не сама почта.

    В Redis нередко смотрят глазами и его дампят в логи; адреса — персональные
    данные, и складывать их в ключи незачем.
    """
    return hashlib.sha256(нормализовать(email).encode()).hexdigest()[:32]


def _код_ключ(email: str) -> str:
    return f"dating:email:code:{_хеш(email)}"


def _попытки_ключ(email: str) -> str:
    return f"dating:email:attempts:{_хеш(email)}"


def _отправки_ключ(user_id: str) -> str:
    return f"dating:email:sends:{user_id}"


def сгенерировать_код() -> str:
    """Шестизначный код. `secrets`, а не `random`: второй предсказуем."""
    return "".join(secrets.choice("0123456789") for _ in range(CODE_LENGTH))


async def можно_отправлять(user_id: str) -> bool:
    """Не превышен ли лимит писем в час.

    Без него эндпоинт — бесплатная рассылка по чужим адресам от нашего имени,
    и домен быстро уезжает в спам-листы.
    """
    r = await get_redis()
    ключ = _отправки_ключ(user_id)
    сколько = await r.incr(ключ)
    if сколько == 1:
        await r.expire(ключ, SEND_WINDOW)
    return сколько <= MAX_SENDS_PER_HOUR


async def запомнить_код(email: str, код: str, user_id: str) -> None:
    """Сохранить код подтверждения. Прежний код той же почты перестаёт работать."""
    r = await get_redis()
    await r.setex(_код_ключ(email), CODE_TTL, f"{код}:{user_id}")
    await r.delete(_попытки_ключ(email))


async def проверить_код(email: str, код: str) -> str | None:
    """Проверить код и погасить его. Возвращает id пользователя или None.

    Гасим при первом успешном использовании: иначе перехваченный код работает
    все свои минуты повторно.
    """
    r = await get_redis()

    попытки = await r.incr(_попытки_ключ(email))
    if попытки == 1:
        await r.expire(_попытки_ключ(email), CODE_TTL)
    if попытки > MAX_ATTEMPTS:
        # Код сжигаем целиком: продолжать перебор бессмысленно
        await r.delete(_код_ключ(email))
        logger.warning(f"Перебор кода почты, код погашен ({_хеш(email)})")
        return None

    значение = await r.get(_код_ключ(email))
    if not значение:
        return None

    сохранённый, _, user_id = str(значение).partition(":")
    # Сравнение постоянного времени: обычное == выходит на первом несовпадении
    if not secrets.compare_digest(сохранённый, str(код)):
        return None

    await r.delete(_код_ключ(email))
    await r.delete(_попытки_ключ(email))
    return user_id or None
