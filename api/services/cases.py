"""Кейсы: редкая попытка за подписку, награда — только внешний вид анкеты.

Раньше из кейса выпадали суперлайки и минуты буста с суточной квотой. Это
делало его игровым автоматом при аркаде: расходники тратятся и забываются, а
ежедневный «крутни ещё» выглядит дёшево. Теперь кейс — лимитированная
коллекция для оформления анкеты: наклейка-значок на фото
(services/stickers.py) или обложка карточки (services/decor.py). Обе
остаются навсегда и видны другим людям. Расходников в кейсе нет и не будет.

Кейсов три, по одному на набор наклеек: «Керопи», «Star Rail», «Хеллоуин».
Человек выбирает, какой открыть, и получает наклейку именно этого набора —
собирать конкретную коллекцию интереснее, чем тянуть случайную картинку из
общей кучи. Обложка — сквозная награда: она про анкету целиком, а не про
персонажей, поэтому выпадает из любого кейса с одинаковым небольшим шансом.

Попытки месячные, общие на все кейсы и только по подписке: одна в месяц на
базовом платном уровне, три — на максимальном. Редкость попытки и есть
ценность: то, что можно крутить каждый день, коллекцией не ощущается.

Шансы заданы явно и в сумме дают единицу. Проверяется тестом: подкрутить
незаметно нельзя.
"""

from __future__ import annotations

import random
from dataclasses import dataclass
from datetime import datetime

#: Коллекционная наклейка набора кейса. Конкретную выбирает
#: services/stickers.py по редкости — здесь только вероятность того, что
#: выпадет именно наклейка.
REWARD_STICKER = "sticker"
#: Лимитированная обложка карточки. Конкретную выбирает services/decor.py.
REWARD_DECOR = "decor"


@dataclass(frozen=True)
class Case:
    """Один кейс. Код совпадает с кодом набора наклеек в каталоге."""

    code: str
    title: str
    #: Одна строка под названием на плитке — о чём набор.
    hint: str
    #: Цвет свечения плитки в интерфейсе. С сервера, чтобы новый кейс не
    #: требовал правки клиента.
    accent: str


#: Порядок — порядок плиток на экране. Коды заперты в базе (CaseOpening,
#: StickerOwned хранят коды наклеек, а набор читается из каталога) — не
#: переименовывать.
CASES: tuple[Case, ...] = (
    Case("keropi", "Керопи", "Лягушонок Sanrio: пять наклеек", "#7ed957"),
    Case("starrail", "Star Rail", "Март 7, Зеле, Пом-Пом и другие", "#7aa2ff"),
    Case("halloween", "Хеллоуин", "Пепе в костюмах злодеев из хорроров", "#ff8a3c"),
)


def case_by_code(code: str | None) -> Case | None:
    """Кейс по коду из запроса. None — такого кейса нет (или код пустой)."""
    if not code:
        return None
    for c in CASES:
        if c.code == code:
            return c
    return None


@dataclass(frozen=True)
class Reward:
    """Одна возможная награда."""

    code: str
    #: Сколько начисляем. Коллекционные награды всегда по одной.
    amount: int
    #: Вероятность выпадения, 0..1.
    chance: float
    title: str


#: Порядок важен только для витрины «что можно выиграть». Сумма шансов = 1.
#: Обложка заметно реже наклейки: человек открывает кейс ради его набора, а
#: обложек всего пять, и они должны оставаться событием.
REWARDS: tuple[Reward, ...] = (
    Reward(REWARD_STICKER, 1, 0.8, "Наклейка набора"),
    Reward(REWARD_DECOR, 1, 0.2, "Обложка анкеты"),
)

#: Сколько попыток в месяц даёт каждый уровень. Бесплатному — ни одной: кейс
#: доступен только с подпиской, иначе он не помогает её продать.
#:
#: Уровни перечислены поимённо, и новый уровень надо дописывать сюда руками:
#: `openings_per_month` для незнакомого имени вернёт 0, то есть Aurora без
#: этой строки молча осталась бы вовсе без кейсов.
OPENINGS_PER_MONTH: dict[str, int] = {
    "free": 0,
    "plus": 1,
    "ultra": 2,
    "aurora": 3,
}


def openings_per_month(tier: str) -> int:
    """Незнакомый уровень считаем бесплатным: испорченная запись в БД не
    должна выдавать попытки."""
    return OPENINGS_PER_MONTH.get(tier, 0)


def начало_месяца(момент: datetime) -> datetime:
    """Начало календарного месяца — от него считается квота.

    Календарный месяц, а не «30 дней с последнего открытия»: у скользящего
    окна нет даты, которую можно показать («обновится 1 сентября»), и
    человеку пришлось бы вспоминать, когда он крутил в прошлый раз.
    """
    return момент.replace(day=1, hour=0, minute=0, second=0, microsecond=0)


def начало_следующего_месяца(момент: datetime) -> datetime:
    """Когда квота обновится — эту дату показываем под кнопкой."""
    if момент.month == 12:
        return момент.replace(
            year=момент.year + 1, month=1, day=1,
            hour=0, minute=0, second=0, microsecond=0,
        )
    return момент.replace(
        month=момент.month + 1, day=1,
        hour=0, minute=0, second=0, microsecond=0,
    )


def roll() -> Reward:
    """Выбрать тип награды по заданным шансам.

    `random.choices` с весами, а не сравнение с накопленной суммой: последнее
    легко написать так, что последняя награда не выпадет никогда.
    """
    return random.choices(REWARDS, weights=[r.chance for r in REWARDS], k=1)[0]
