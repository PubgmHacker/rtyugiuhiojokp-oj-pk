"""Реакции на сообщения личной переписки.

Набор фиксирован и живёт на сервере, а не приходит от клиента: реакция —
это строка в базе, и свободное поле превратило бы её в канал для текста
мимо модерации. Шесть кодов — столько же, сколько в Tapback у Apple, и по
той же причине: ряд из шести помещается на телефоне одной строкой, ряд из
двенадцати заставляет прокручивать.

Кодов, а не эмодзи. В проекте действует запрет на юникодные эмодзи в
интерфейсе (см. PRODUCT.md), и он тут не формальность: эмодзи рисует шрифт
устройства, поэтому «огонь» на iOS и на Android — разные картинки, а на
части Android — квадрат. Знаки рисует сам интерфейс (web/src/lib/reactions.ts),
сервер хранит только код.
"""

from __future__ import annotations

#: Порядок важен: интерфейс показывает ряд именно в нём.
#:
#: heart — «люблю», fire — «огонь», spark — «восторг»; дальше три знака
#: разговора, которые в наборе икон рисуются словом, а не лицом:
#: haha — смех, wow — удивление, hmm — вопрос. Лиц в наборе нет намеренно:
#: нарисованное лицо неотличимо от плохого эмодзи, а знак — отличим.
REACTION_KEYS: tuple[str, ...] = ("heart", "fire", "spark", "haha", "wow", "hmm")


def нормализовать_реакцию(raw: object) -> str | None:
    """Код реакции из клиента → проверенный код, или None (снять реакцию).

    Пустая строка, None и любой неизвестный код значат одно и то же —
    «реакции нет». Ошибку не бросаем: снятие и опечатка приводят к одному
    состоянию, и отказ 400 на снятой реакции выглядел бы как поломка.
    """
    if not isinstance(raw, str):
        return None
    ключ = raw.strip()
    return ключ if ключ in REACTION_KEYS else None
