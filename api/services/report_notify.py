"""Ответ жалобщику: чем закончилась его жалоба.

Жалоба без ответа — самая дорогая из тихих поломок модерации. Человек нажимал
«Пожаловаться», получал «спасибо» и больше не узнавал ничего: ни что анкету
убрали из поиска, ни что нарушителя забанили, ни что модератор нарушения не
нашёл. Со стороны это неотличимо от кнопки, которая никуда не ведёт, — и
второй раз на неё не жмут. А эскалация в routers/report.py стоит именно на
жалобах тех, кто реально пересекался с нарушителем: перестанут жаловаться —
перестанет работать и автоматика.

Канал тот же, что у бана (services/enforcement.py): публикация в
dating:bot:events, разбирает bot/services/redis_subscriber.py. Своего клиента
к Telegram у API нет, и заводить его ради одного сообщения незачем.

Второй канал — пуш в нативное приложение. Он не дубль: вход по Apple ID не
требует Telegram вовсе, и для такого человека сообщение бота не существует —
`telegram_id` у него пустой, и подписчик молча выходит. Оба канала
независимы: упавший Redis не должен отменять пуш, и наоборот.

Публикация — лучшая попытка. Жалоба к этому моменту записана, а эскалация
применена; падение Redis не должно откатывать модерацию, поэтому все ошибки
глотаются с записью в лог.
"""
from __future__ import annotations

import asyncio
import json
import logging
from collections.abc import Iterable

logger = logging.getLogger(__name__)

#: Итоги, которые умеет отправлять API. Тексты живут на стороне бота
#: (bot/texts.py: report_outcome), здесь только коды — API не знает ни языка,
#: ни разметки Telegram.
#:
#: hidden    — жалоб набралось на скрытие анкеты из поиска (порог 3)
#: banned    — набралось на автобан (порог 5) или модератор забанил руками
#: resolved  — модератор принял меры, отличные от бана
#: dismissed — модератор нарушения не нашёл
ИТОГИ = ("hidden", "banned", "resolved", "dismissed")

#: Заголовок и строка пуша на каждый итог. Своя копия текста, а не заимствование
#: из бота: в пуш идёт одна строка без HTML и без кнопок, а у бота — подробное
#: сообщение с разметкой. Ключи обязаны покрывать ИТОГИ целиком.
ПУШИ = {
    "hidden": (
        "Жалоба сработала",
        "Анкета скрыта из поиска — её проверит модератор.",
    ),
    "banned": (
        "Жалоба подтверждена",
        "Аккаунт заблокирован. Больше он вам не встретится.",
    ),
    "resolved": (
        "Жалоба рассмотрена",
        "Модератор проверил анкету и принял меры.",
    ),
    "dismissed": (
        "Жалоба рассмотрена",
        "Модератор не нашёл нарушения правил. Мешающего человека можно "
        "заблокировать в его анкете.",
    ),
}


async def notify_report_outcome(reporter_ids: Iterable[str], outcome: str) -> None:
    """Разослать жалобщикам итог по их жалобе — в Telegram и пушем.

    Дубли в списке склеиваются: на одну цель человек мог пожаловаться и из
    деки, и из переписки, а сообщение об одном и том же итоге нужно одно.

    Порог переходится один раз — вызывающий обязан звать это на ПЕРЕХОДЕ, а не
    при каждой жалобе выше порога, иначе шестая жалоба присылала бы «аккаунт
    заблокирован» предыдущим пятерым по второму разу.
    """
    if outcome not in ИТОГИ:
        # Не бросаем: молчание лучше падения ручки жалобы. Но в логе это
        # видно, а тест держит согласованность кодов с текстами бота
        logger.error(f"Неизвестный итог жалобы {outcome!r} — уведомление не отправлено")
        return

    кому = list(dict.fromkeys(uid for uid in reporter_ids if uid))
    if not кому:
        return

    await _в_телеграм(кому, outcome)
    await _пушем(кому, outcome)


async def _в_телеграм(кому: list[str], outcome: str) -> None:
    """Событие боту — по одному на человека, как это делает бан."""
    try:
        from services.realtime import get_redis

        r = await get_redis()
        for user_id in кому:
            await r.publish(
                "dating:bot:events",
                json.dumps({
                    "type": "report_outcome",
                    "user_id": user_id,
                    "outcome": outcome,
                }),
            )
    except Exception as e:
        logger.warning(f"Итог жалобы {outcome} не доставлен в Telegram ({len(кому)} чел.): {e}")
        return

    logger.info(f"Итог жалобы {outcome} отправлен: {len(кому)} чел.")


async def _пушем(кому: list[str], outcome: str) -> None:
    """Пуш в нативное приложение — тем, кто зарегистрировал устройство.

    Разослано параллельно, в отличие от пуша о мэтче (routers/likes.py), где
    получателей ровно двое: здесь их до пяти, у каждого свои устройства, и
    разговор с APNs занимает до десяти секунд на устройство. Последовательный
    цикл держал бы ручку жалобы почти минуту.

    `collapse_id` не ставим намеренно. Свернуть пуши можно только по
    получателю — id самой жалобы сюда не доходит, — а у человека жалоб бывает
    несколько на разных людей. Общий collapse_id заменял бы предыдущий итог
    следующим, и из трёх решений человек увидел бы одно.
    """
    from services import push

    # send_to_user сам возвращает 0, когда ключи APNs не заданы, — отдельная
    # проверка здесь только раздвоила бы условие «пуши включены».
    # return_exceptions: сорвавшийся пуш одному жалобщику не должен отменять
    # остальные четыре. Внешний except шире, чем кажется нужным: под ним и
    # ПУШИ[outcome] — код без текста пуша обязан стоить строчки в логе, а не
    # пятисотки на ручке модерации (согласованность держит тест)
    try:
        заголовок, строка = ПУШИ[outcome]
        результаты = await asyncio.gather(
            *(
                push.send_to_user(
                    user_id,
                    title=заголовок,
                    body=строка,
                    data={"kind": "report_outcome", "outcome": outcome},
                )
                for user_id in кому
            ),
            return_exceptions=True,
        )
    except Exception as e:
        logger.warning(f"Пуши об итоге жалобы {outcome} не отправлены: {e}")
        return

    for user_id, итог in zip(кому, результаты):
        if isinstance(итог, Exception):
            logger.warning(f"Пуш об итоге жалобы не ушёл (user={user_id}): {итог}")

