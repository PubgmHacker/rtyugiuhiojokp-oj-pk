"""Обложки карточки — лимитированный декор, выпадающий только из кейсов.

Зачем отдельная сущность, а не ещё одна наклейка: наклейка — маленький знак
характера рядом с именем, обложка меняет всю карточку в деке. Первое можно
менять хоть каждый день, второе — редкая вещь, которую видно издалека.

Обложки лимитированные: их нельзя купить и нельзя открыть прогрессом — только
вытащить из кейса, а попытки кейса даёт подписка. Так обложка на карточке
означает ровно одно: человеку повезло в лимитированной коллекции. Владение
хранится в `DecorOwned`, по строке на выпадение.

Редкость использует тот же словарь, что наклейки (`services/stickers.py`):
две шкалы редкости в одном продукте путали бы, а «легендарная» должна значить
одно и то же везде.

Картинок нет: обложка рисуется CSS на клиенте (web/src/lib/decor.ts). Так она
ничего не весит, не требует хранилища и одинаково выглядит на любой плотности
экрана.
"""

from __future__ import annotations

import random
from collections.abc import Collection
from dataclasses import dataclass

from services.stickers import ВЕС_РЕДКОСТИ, НАЗВАНИЕ_РЕДКОСТИ


@dataclass(frozen=True)
class Оформление:
    code: str
    title: str
    #: Редкость из общего словаря наклеек — общий язык на весь продукт.
    rarity: str

    @property
    def rarity_title(self) -> str:
        return НАЗВАНИЕ_РЕДКОСТИ.get(self.rarity, self.rarity)


#: Каталог намеренно короткий: обложек мало, и каждая заметна. Порядок — от
#: частой к редкой, в этом порядке их показывает витрина.
ОФОРМЛЕНИЯ: tuple[Оформление, ...] = (
    Оформление(code="dawn", title="Рассвет", rarity="common"),
    Оформление(code="frost", title="Изморозь", rarity="rare"),
    Оформление(code="ember", title="Угли", rarity="rare"),
    Оформление(code="nebula", title="Туманность", rarity="epic"),
    Оформление(code="eclipse", title="Затмение", rarity="legend"),
)


def по_коду(code: str) -> Оформление | None:
    for о in ОФОРМЛЕНИЯ:
        if о.code == code:
            return о
    return None


def выпала(имеющиеся: Collection[str] = ()) -> Оформление | None:
    """Случайная обложка среди тех, которых у человека ещё нет.

    Дубликат обложки невозможен по построению: кейс выбирает только из
    недостающих. Когда собраны все, возвращается None — и кейс выдаёт
    наклейку вместо обложки (routers/cases.py).

    Как у наклеек: сначала редкость по весам, потом равновероятно внутри
    неё. Иначе две редкие обложки вместе выпадали бы вдвое чаще эпической,
    и редкость перестала бы значить редкость.
    """
    осталось: dict[str, list[Оформление]] = {}
    for о in ОФОРМЛЕНИЯ:
        if о.code not in имеющиеся:
            осталось.setdefault(о.rarity, []).append(о)
    if not осталось:
        return None

    редкости = list(осталось)
    веса = [ВЕС_РЕДКОСТИ.get(р, 1.0) for р in редкости]
    редкость = random.choices(редкости, weights=веса, k=1)[0]
    return random.choice(осталось[редкость])


def безопасный_код(code: str | None) -> str | None:
    """Код для выдачи наружу. Неизвестный обнуляем.

    Обложку могли убрать из каталога после деплоя, а в анкетах её код
    остался: клиент на неизвестный код нарисует пустоту, и карточка
    поедет. Лучше отдать «без обложки».
    """
    if not code:
        return None
    return code if по_коду(code) else None
