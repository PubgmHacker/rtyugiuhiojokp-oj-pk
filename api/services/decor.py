"""Оформление карточки — рамка, которую видно в деке.

Зачем отдельная сущность, а не ещё одна наклейка: наклейка говорит о
характере, рамка — о времени, вложенном в коллекцию. Первое выбирают,
второе зарабатывают, и путать их значит обесценить оба.

Условие открытия — размер коллекции, а не покупка. У кейса от этого
появляется вторая причина: не «ещё одна картинка», а «до следующей рамки
семь». Одна рамка идёт за подписку — платящему нужно что-то надеть сразу,
не собирая месяц.

Картинок нет: рамка рисуется CSS на клиенте. Так она ничего не весит, не
требует хранилища и одинаково выглядит на любой плотности экрана.
"""

from __future__ import annotations

from dataclasses import dataclass

#: Порядок тарифов для сравнения «не ниже». Держим здесь, а не тянем из
#: реестра функций: реестр отвечает на «можно ли фичу», а тут нужен ранг.
_РАНГ: dict[str, int] = {"free": 0, "plus": 1, "ultra": 2, "aurora": 3}


@dataclass(frozen=True)
class Оформление:
    code: str
    title: str
    #: Условие человеческим языком — его показываем на закрытой рамке.
    #: Без него закрытая ячейка выглядит как ошибка, а не как цель.
    hint: str
    #: Сколько разных наклеек нужно собрать. 0 — условия по коллекции нет.
    нужно_наклеек: int = 0
    #: Минимальный тариф. Пусто — тариф не важен.
    нужен_тариф: str = ""


#: Лестница намеренно неравномерная: первая рамка близко, чтобы человек
#: увидел механику, дальше шаг растёт — иначе всё открывается за вечер и
#: смотреть в коллекцию больше незачем.
ОФОРМЛЕНИЯ: tuple[Оформление, ...] = (
    Оформление(code="dawn", title="Рассвет", hint="5 наклеек в коллекции", нужно_наклеек=5),
    Оформление(code="frost", title="Изморозь", hint="15 наклеек в коллекции", нужно_наклеек=15),
    Оформление(code="ember", title="Угли", hint="30 наклеек в коллекции", нужно_наклеек=30),
    Оформление(code="nebula", title="Туманность", hint="45 наклеек в коллекции", нужно_наклеек=45),
    Оформление(
        code="eclipse",
        title="Затмение",
        hint="Подписка Ultra или выше",
        нужен_тариф="ultra",
    ),
)


def по_коду(code: str) -> Оформление | None:
    for о in ОФОРМЛЕНИЯ:
        if о.code == code:
            return о
    return None


def открыто(о: Оформление, наклеек: int, tier: str) -> bool:
    """Заработано ли право носить.

    Оба условия обязательны, если оба заданы: рамка за подписку не должна
    доставаться бесплатно за коллекцию, а рамка за коллекцию — покупкой.
    Так у каждой один понятный смысл.
    """
    if о.нужно_наклеек and наклеек < о.нужно_наклеек:
        return False
    if о.нужен_тариф and _РАНГ.get(tier, 0) < _РАНГ.get(о.нужен_тариф, 99):
        return False
    return True


def прогресс(о: Оформление, наклеек: int) -> tuple[int, int]:
    """Сколько собрано из нужного — для полоски на закрытой рамке.

    Полоска важнее подписи: «12 из 15» показывает, что цель близко, а
    «нужно 15» читается как «не для меня».
    """
    if not о.нужно_наклеек:
        return (0, 0)
    return (min(наклеек, о.нужно_наклеек), о.нужно_наклеек)


def безопасный_код(code: str | None) -> str | None:
    """Код для выдачи наружу. Неизвестный обнуляем.

    Рамку могли убрать из каталога после деплоя, а в анкетах её код
    остался: клиент на неизвестный код нарисует пустоту, и карточка
    поедет. Лучше отдать «без рамки».
    """
    if not code:
        return None
    return code if по_коду(code) else None
