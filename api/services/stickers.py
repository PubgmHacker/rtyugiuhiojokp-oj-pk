"""Коллекционные наклейки: каталог по наборам, редкость и выбор из кейса.

Зачем они: прежде из кейса выпадали только суперлайки и минуты буста — их
тратят и забывают, повода открыть кейс завтра не оставалось. Наклейка остаётся
навсегда и видна в анкете как значок на фото, поэтому у кейса появляется
вторая причина: собрать набор.

Наборы. Каждая наклейка принадлежит набору (`set`), и каждый набор — это
отдельный кейс (services/cases.py): «Керопи», «Star Rail», «Хеллоуин». Кейс
выдаёт наклейку только своего набора — человек выбирает, что собирать, а не
получает случайную картинку из общей кучи.

Каталог читается из `api/data/stickers.json`, который пишет сборщик
`tools/fetch_stickers.py` вместе с картинками в `web/public/stickers/`. Один
источник правды на картинку и на данные: если завести список кодов вручную,
он разойдётся с папкой, и в анкете появится битая картинка.

Про шансы: они заданы явно, показываются человеку и проверяются тестом. Скрытые
шансы — ровно то, за что не любят гача-механики; здесь их видно до открытия.

Дубликатов при выпадении не бывает, пока набор не собран: кейс передаёт
сюда уже имеющиеся коды, и выбор идёт среди недостающих. Повтор возможен
только у полного набора — там он честно называется повтором.
"""

from __future__ import annotations

import json
import logging
import random
from collections.abc import Collection
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

logger = logging.getLogger(__name__)

#: Каталог лежит внутри api/, а не рядом с картинками в web/public: сервис
#: API на Railway собирается из папки api/ (Dockerfile: COPY . .), и web/ в
#: контейнере нет. Каталог у картинок означал бы пустую коллекцию и 503 на
#: каждом кейсе — ровно в проде, где тесты не бегают. Оба файла пишет один
#: сборщик tools/fetch_stickers.py, так что разойтись им негде.
_КАТАЛОГ = Path(__file__).resolve().parents[1] / "data" / "stickers.json"

#: Вес редкости при выпадении. Сумма не обязана быть единицей: нормируем сами,
#: иначе добавление наклейки требовало бы пересчёта всех чисел руками.
ВЕС_РЕДКОСТИ: dict[str, float] = {
    "common": 60.0,
    "rare": 27.0,
    "epic": 10.0,
    "legend": 3.0,
}

#: Человеческие названия редкости — их видно в интерфейсе.
НАЗВАНИЕ_РЕДКОСТИ: dict[str, str] = {
    "common": "обычная",
    "rare": "редкая",
    "epic": "эпическая",
    "legend": "легендарная",
}


@dataclass(frozen=True)
class Наклейка:
    code: str
    title: str
    rarity: str
    #: Код набора — он же код кейса, из которого наклейка выпадает.
    set: str

    @property
    def rarity_title(self) -> str:
        return НАЗВАНИЕ_РЕДКОСТИ.get(self.rarity, self.rarity)

    @property
    def image(self) -> str:
        """Путь к картинке. Отдаём клиенту его, а не собираем на фронте:
        иначе переезд папки ломает картинки молча."""
        return f"/stickers/{self.set}/{self.code}.webp"


@lru_cache(maxsize=1)
def каталог() -> tuple[Наклейка, ...]:
    """Все наклейки всех наборов. Кэш на процесс: файл меняется только с деплоем.

    Если файла нет (например, фронтенд собирается отдельно и папку не
    выложили), возвращаем пустой каталог: кейс откажет честной 503, а не
    упадёт трейсбеком.

    Запись без кода, набора или с незнакомой редкостью пропускаем с записью в
    журнал: одна кривая строка не должна валить весь каталог.
    """
    try:
        данные = json.loads(_КАТАЛОГ.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as e:
        logger.error(f"Каталог наклеек недоступен ({_КАТАЛОГ}): {e}")
        return ()

    наклейки: list[Наклейка] = []
    for з in данные:
        if not (з.get("code") and з.get("set")) or з.get("rarity") not in ВЕС_РЕДКОСТИ:
            logger.warning(f"Каталог наклеек: пропущена запись {з!r}")
            continue
        наклейки.append(Наклейка(
            code=str(з["code"]), title=str(з.get("title") or з["code"]),
            rarity=str(з["rarity"]), set=str(з["set"]),
        ))
    return tuple(наклейки)


def наборы() -> tuple[str, ...]:
    """Коды наборов в порядке каталога — без повторов."""
    виденные: dict[str, None] = {}
    for н in каталог():
        виденные.setdefault(н.set, None)
    return tuple(виденные)


def набор(code: str) -> tuple[Наклейка, ...]:
    """Наклейки одного набора. Пусто — набора нет или каталог недоступен."""
    return tuple(н for н in каталог() if н.set == code)


def по_коду(code: str) -> Наклейка | None:
    for н in каталог():
        if н.code == code:
            return н
    return None


def шансы_по_редкости(набор_код: str | None = None) -> dict[str, float]:
    """Доли редкостей в процентах — то, что показываем на витрине.

    Считаем от фактического состава: если в наборе нет эпических, их доля не
    показывается, а веса остальных нормируются заново. Так шанс на витрине
    совпадает с тем, как `выпала` выбирает на самом деле.
    """
    источник = набор(набор_код) if набор_код else каталог()
    по_р: dict[str, int] = {}
    for н in источник:
        по_р[н.rarity] = по_р.get(н.rarity, 0) + 1

    всего_веса = sum(ВЕС_РЕДКОСТИ[р] for р in по_р)
    if not всего_веса:
        return {}
    return {р: round(ВЕС_РЕДКОСТИ[р] / всего_веса * 100, 1) for р in по_р}


def выпала(
    исключая: Collection[str] = (), набор_код: str | None = None
) -> Наклейка | None:
    """Случайная наклейка с учётом редкости.

    Сначала выбираем редкость по весам, потом равновероятно наклейку внутри
    неё. Так добавление новой легендарной не делает легендарные в целом чаще —
    иначе каждая новая картинка незаметно разбавляла бы редкость.

    `набор_код` — ограничить выбор одним набором: кейс выдаёт только своё.
    Без него выбор идёт по всему каталогу.

    `исключая` — коды, которые выпасть не должны: кейс передаёт сюда уже
    собранные, и попытка не сгорает на дубликат. None при непустом каталоге
    означает «всё из возможного уже есть».
    """
    источник = набор(набор_код) if набор_код else каталог()
    все = [н for н in источник if н.code not in исключая]
    if not все:
        return None

    по_р: dict[str, list[Наклейка]] = {}
    for н in все:
        по_р.setdefault(н.rarity, []).append(н)

    редкости = list(по_р)
    веса = [ВЕС_РЕДКОСТИ[р] for р in редкости]
    редкость = random.choices(редкости, weights=веса, k=1)[0]
    return random.choice(по_р[редкость])


def картинка_наклейки(code: str | None) -> str | None:
    """Путь к картинке по коду, или None.

    Нужна, потому что код наклейки хранится в анкете, а клиенту нужен путь.
    Собирать его на фронте нельзя: переезд папки сломает картинки молча, а
    несуществующий код (наклейку убрали из набора) даст битую ссылку — здесь
    он превращается в «без наклейки».
    """
    if not code:
        return None
    н = по_коду(code)
    return н.image if н else None
