"""Отправка писем: коды подтверждения и восстановления.

SMTP настраивается переменными окружения. Без них письма не уходят, и это
видно: функция возвращает False, роутер отвечает честной ошибкой, а в
DEBUG код дополнительно пишется в лог, чтобы разработку не блокировала
почта. Молча «делать вид, что отправили» нельзя: человек будет ждать письмо,
которого нет, и решит, что сломан он, а не сервис.

Отправка блокирующая (`smtplib`), поэтому уходит в отдельный поток: в этом
приложении один event loop, и синхронный вызов в нём вешает всех сразу — на
этом уже обжигались с синхронным клиентом AI-модерации.
"""

from __future__ import annotations

import asyncio
import logging
import re
import smtplib
from email.message import EmailMessage

from config import get_settings
from services.email_recovery import хеш_почты

logger = logging.getLogger(__name__)
settings = get_settings()

#: Всё, похожее на адрес, внутри текста ошибки. Нарочно нестрого и без
#: обязательной точки в домене: задача не проверить адрес, а не пропустить его в
#: лог. Лишнее совпадение стоит нечитаемого слова в строке лога, пропущенное —
#: утечки персональных данных. Ограничители (кавычки, скобки, угловые скобки,
#: запятые) в адрес не входят: smtplib печатает адреса как раз внутри них —
#: `{'ivan@mail.ru': (550, b'...')}` и `<ivan@mail.ru>`.
_ПОХОЖЕ_НА_ПОЧТУ = re.compile(r"[^\s<>'\"(),;:]+@[^\s<>'\"(),;:]+")
#: Знаки, которыми кончается фраза, а не адрес: «отказ для ivan@mail.ru.»
_ХВОСТ = ".,;:!?"


def _без_адресов(текст: str) -> str:
    """Заменить в тексте каждый адрес на его хеш, сохранив всё остальное.

    Текст ответа SMTP-сервера нужен целиком: без кода и причины («550 mailbox
    unavailable», «535 auth failed») понять, почему письма не уходят, нельзя.
    Утечкой в нём является только сам адрес.
    """

    def подменить(совпадение: re.Match[str]) -> str:
        адрес = совпадение.group(0)
        хвост = ""
        while адрес and адрес[-1] in _ХВОСТ:
            адрес, хвост = адрес[:-1], адрес[-1] + хвост
        # Хешируется чистый адрес: иначе «ivan@mail.ru.» в конце фразы дало бы
        # хеш, не совпадающий с ключами Redis, и логи перестали бы сходиться
        return f"почта({хеш_почты(адрес)}){хвост}"

    return _ПОХОЖЕ_НА_ПОЧТУ.sub(подменить, текст)


def настроен() -> bool:
    return bool(settings.SMTP_HOST and settings.SMTP_FROM)


def _отправить(адрес: str, тема: str, текст: str) -> None:
    письмо = EmailMessage()
    письмо["From"] = settings.SMTP_FROM
    письмо["To"] = адрес
    письмо["Subject"] = тема
    письмо.set_content(текст)

    if settings.SMTP_PORT == 465:
        сервер = smtplib.SMTP_SSL(settings.SMTP_HOST, settings.SMTP_PORT, timeout=10)
    else:
        сервер = smtplib.SMTP(settings.SMTP_HOST, settings.SMTP_PORT, timeout=10)

    with сервер:
        if settings.SMTP_PORT != 465:
            сервер.starttls()
        if settings.SMTP_USER:
            сервер.login(settings.SMTP_USER, settings.SMTP_PASSWORD)
        сервер.send_message(письмо)


async def отправить_код(адрес: str, код: str) -> bool:
    """Отправить код. `False` — письмо не ушло, и это надо показать человеку."""
    if not настроен():
        if settings.DEBUG:
            # Разработка не должна упираться в почтовый сервер. Адрес и код здесь
            # открыто — осознанно: без них локальный вход невозможен. Ветка
            # недостижима при DEBUG=false, а прод обязан быть с DEBUG=false
            # (см. чек-лист в APPSTORE.md)
            logger.warning(f"SMTP не настроен. Код для {адрес}: {код}")
            return True
        logger.error("SMTP не настроен — код подтверждения не отправлен")
        return False

    текст = (
        f"Ваш код: {код}\n\n"
        "Он нужен, чтобы подтвердить почту в Симпе. Код действует 15 минут.\n"
        "Если вы этого не запрашивали, просто не вводите его — с аккаунтом "
        "ничего не произойдёт."
    )

    try:
        # smtplib блокирующий: в общем event loop он подвесил бы всех сразу
        await asyncio.to_thread(_отправить, адрес, "Код подтверждения — Симп", текст)
        return True
    except Exception as e:
        # Адрес в лог не идёт: он персональные данные, а исключения smtplib несут
        # его внутри себя — `SMTPRecipientsRefused` печатает словарь
        # `{адрес: (код, ответ сервера)}`, `SMTPSenderRefused` — отправителя,
        # ответ сервера часто повторяет адрес в угловых скобках. Логи дейтинга
        # утекают целиком (Sentry, агрегаторы, скриншоты поддержки), и адрес в
        # них — это «этот человек здесь зарегистрирован». В строке остаётся тип
        # ошибки, вычищенный ответ сервера и хеш адреса — тот же, что в ключах
        # Redis у восстановления, так что строки логов по-прежнему сходятся.
        logger.error(
            f"Не удалось отправить письмо ({хеш_почты(адрес)}): "
            f"{type(e).__name__}: {_без_адресов(str(e))}"
        )
        return False
