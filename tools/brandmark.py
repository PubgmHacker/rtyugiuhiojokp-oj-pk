"""Знак марки: две стеклянные линзы, в пересечении — каустика мэтча.

В продукте у каждого человека свой детерминированный цвет — аура
(web/src/lib/aura.ts). Знак: два объёмных диска (малина + фиолет)
сходятся по диагонали; место пересечения — светящаяся линза, не
плоский PowerPoint-Venn.

Глубина без фотореализма: мягкая тень под дисками, радиальный объём,
верхний блик, тонкий ободок, каустика в пересечении. Форма читается
и в 16px (два пятна + свет в центре), и в 1024px.

Геометрия одна на все носители: iOS-иконка, сплэш, favicon, баннеры
бота (make_icons.py, make_banners.py) импортируют её отсюда, SVG на
лендинге и React-компонент (web/src/components/BrandMark.tsx) повторяют
те же пропорции числами. Константы ниже — источник правды.

Пропорции (от радиуса круга R):
    смещение центра по X       dx = 0.560 R
    смещение центра по Y       dy = 0.350 R  (угол диагонали ≈ 32°)
Малиновый диск ниже и левее, фиолетовый выше и правее.
"""

from __future__ import annotations

from PIL import Image, ImageChops, ImageDraw, ImageFilter

# Палитра дизайн-системы (web/src/styles/globals.css)
МАЛИНОВЫЙ = (255, 45, 111)   # --color-accent #ff2d6f — первая аура
ФИОЛЕТОВЫЙ = (139, 92, 246)  # #8b5cf6 — вторая аура, соседний тон
СВЕТ = (250, 251, 252)       # --color-text #fafbfc — ядро каустики

# Приглушённый вариант — для «серых» носителей (баннер «Дальше»)
СЕРЫЙ_А = (99, 105, 115)
СЕРЫЙ_Б = (62, 67, 76)

#: Пропорции знака — доли от радиуса круга.
СМЕЩЕНИЕ_X = 0.560
СМЕЩЕНИЕ_Y = 0.350

#: Полные габариты знака в радиусах — чтобы вписывать его в макет.
ШИРИНА = 2 * (1 + СМЕЩЕНИЕ_X)   # ≈ 3.120 R
ВЫСОТА = 2 * (1 + СМЕЩЕНИЕ_Y)   # ≈ 2.700 R


def _lerp(a: float, b: float, t: float) -> float:
    return a + (b - a) * t


def _mix(c1: tuple[int, int, int], c2: tuple[int, int, int], t: float) -> tuple[int, int, int]:
    return (
        int(_lerp(c1[0], c2[0], t)),
        int(_lerp(c1[1], c2[1], t)),
        int(_lerp(c1[2], c2[2], t)),
    )


def _круг(size: tuple[int, int], cx: float, cy: float, r: float, fill: int = 255) -> Image.Image:
    m = Image.new("L", size, 0)
    if r <= 0:
        return m
    ImageDraw.Draw(m).ellipse([cx - r, cy - r, cx + r, cy + r], fill=fill)
    return m


def _мягкий_круг(
    size: tuple[int, int],
    cx: float,
    cy: float,
    r: float,
    blur: float,
    fill: int = 255,
) -> Image.Image:
    """Круг с размытым краем — для теней, объёма и бликов."""
    pad = max(2, int(blur * 3) + 2)
    m = Image.new("L", (size[0] + pad * 2, size[1] + pad * 2), 0)
    ImageDraw.Draw(m).ellipse(
        [cx + pad - r, cy + pad - r, cx + pad + r, cy + pad + r],
        fill=fill,
    )
    if blur > 0.35:
        m = m.filter(ImageFilter.GaussianBlur(radius=blur))
    return m.crop((pad, pad, pad + size[0], pad + size[1]))


def _вклеить_rgba(
    слой: Image.Image,
    цвет: tuple[int, int, int],
    маска: Image.Image,
    альфа: float = 1.0,
) -> None:
    """Аддитивно-альфа вклейка RGB-цвета через L-маску на RGBA-слой."""
    a = маска.point(lambda p: int(min(255, p * альфа)))
    цветной = Image.new("RGBA", слой.size, (*цвет, 0))
    цветной.putalpha(a)
    слой.alpha_composite(цветной)


def _объёмный_диск(
    слой: Image.Image,
    cx: float,
    cy: float,
    r: float,
    цвет: tuple[int, int, int],
) -> None:
    """Стеклянный диск: аура → тень → тело → объём → ободок → блики."""
    size = слой.size
    тёмный = _mix(цвет, (6, 8, 14), 0.62)
    глубокий = _mix(цвет, (0, 0, 0), 0.45)
    светлый = _mix(цвет, (255, 255, 255), 0.55)
    ядро = _mix(цвет, (255, 255, 255), 0.28)

    # Цветная аура вокруг диска — «свечение стекла»
    аура = _мягкий_круг(size, cx, cy, r * 1.08, blur=r * 0.28, fill=180)
    _вклеить_rgba(слой, цвет, аура, альфа=0.38)

    # Мягкая тень под диском
    тень = _мягкий_круг(size, cx + r * 0.08, cy + r * 0.16, r * 0.98, blur=r * 0.26)
    _вклеить_rgba(слой, (0, 0, 0), тень, альфа=0.55)

    тело = _круг(size, cx, cy, r)

    # База — насыщенный цвет
    _вклеить_rgba(слой, цвет, тело, альфа=1.0)

    # Глубокий полумесяц снизу-справа (объём шара)
    тень_объём = _мягкий_круг(
        size, cx + r * 0.22, cy + r * 0.28, r * 0.85, blur=r * 0.22, fill=255
    )
    тень_объём = ImageChops.multiply(тень_объём, тело)
    _вклеить_rgba(слой, глубокий, тень_объём, альфа=0.72)

    # Затемнение кромки
    край = ImageChops.subtract(
        тело, _мягкий_круг(size, cx - r * 0.06, cy - r * 0.10, r * 0.72, blur=r * 0.20)
    )
    _вклеить_rgba(слой, тёмный, край, альфа=0.65)

    # Верхний «стеклянный» блик-зона
    объём = _мягкий_круг(
        size, cx - r * 0.18, cy - r * 0.26, r * 0.58, blur=r * 0.24, fill=230
    )
    объём = ImageChops.multiply(объём, тело)
    _вклеить_rgba(слой, ядро, объём, альфа=0.70)

    # Светлый ободок (rim light)
    ободок = ImageChops.subtract(тело, _круг(size, cx, cy, r * 0.88))
    _вклеить_rgba(слой, светлый, ободок, альфа=0.70)

    # Главный блик — плотный эллипс сверху-слева
    блик = _мягкий_круг(
        size, cx - r * 0.32, cy - r * 0.38, r * 0.26, blur=r * 0.07, fill=255
    )
    блик = ImageChops.multiply(блик, тело)
    _вклеить_rgba(слой, (255, 255, 255), блик, альфа=0.88)

    # Мягкий ореол вокруг блика
    ореол = _мягкий_круг(
        size, cx - r * 0.26, cy - r * 0.32, r * 0.38, blur=r * 0.16, fill=160
    )
    ореол = ImageChops.multiply(ореол, тело)
    _вклеить_rgba(слой, (255, 255, 255), ореол, альфа=0.28)

    # Микро-блик снизу-справа (отражение)
    микро = _мягкий_круг(
        size, cx + r * 0.30, cy + r * 0.34, r * 0.09, blur=r * 0.05, fill=210
    )
    микро = ImageChops.multiply(микро, тело)
    _вклеить_rgba(слой, (255, 255, 255), микро, альфа=0.40)


def нарисовать_знак(
    img: Image.Image,
    cx: float,
    cy: float,
    r: float,
    приглушить: bool = False,
) -> None:
    """Рисует знак на изображении. (cx, cy) — центр знака, r — радиус круга.

    Порядок: малиновый диск, фиолетовый диск, поверх — каустика пересечения.
    """
    if r < 1:
        return

    а, б = (СЕРЫЙ_А, СЕРЫЙ_Б) if приглушить else (МАЛИНОВЫЙ, ФИОЛЕТОВЫЙ)
    dx, dy = СМЕЩЕНИЕ_X * r, СМЕЩЕНИЕ_Y * r
    ax, ay = cx - dx, cy + dy
    bx, by = cx + dx, cy - dy

    слой = Image.new("RGBA", img.size, (0, 0, 0, 0))
    _объёмный_диск(слой, ax, ay, r, а)
    _объёмный_диск(слой, bx, by, r, б)

    диск_а = _круг(img.size, ax, ay, r)
    диск_б = _круг(img.size, bx, by, r)
    линза = ImageChops.darker(диск_а, диск_б)

    # Мягкое цветное свечение вокруг пересечения (не белая «дырка»)
    микс = _mix(а, б, 0.5)
    светлый_микс = _mix(микс, (255, 255, 255), 0.55)
    glow = линза.filter(ImageFilter.GaussianBlur(radius=max(1.0, r * 0.18)))
    _вклеить_rgba(слой, микс, glow, альфа=0.70)
    _вклеить_rgba(
        слой,
        светлый_микс,
        линза.filter(ImageFilter.GaussianBlur(radius=max(0.6, r * 0.08))),
        альфа=0.75,
    )

    # Ядро каустики — мягкое, сжимаем к центру знака
    ядро_маска = ImageChops.multiply(
        линза.filter(ImageFilter.GaussianBlur(radius=max(0.5, r * 0.05))),
        _мягкий_круг(img.size, cx, cy, r * 0.48, blur=r * 0.14, fill=255),
    )
    _вклеить_rgba(слой, СВЕТ, ядро_маска, альфа=0.88)

    # Горячая точка — искра мэтча
    искра = _мягкий_круг(img.size, cx, cy, r * 0.12, blur=r * 0.07, fill=255)
    искра = ImageChops.multiply(искра, линза)
    _вклеить_rgba(слой, (255, 255, 255), искра, альфа=1.0)

    база = img.convert("RGBA")
    база.alpha_composite(слой)
    img.paste(база.convert(img.mode))
