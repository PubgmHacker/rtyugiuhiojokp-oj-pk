"""Знак марки: две ауры, в пересечении — свет.

В продукте у каждого человека свой детерминированный цвет — аура
(web/src/lib/aura.ts): кольца аватаров, обводки карточек, кольца историй.
Знак строится из этой же идеи: два кольца-ауры разных оттенков
сходятся по диагонали, и место пересечения загорается светом. Мэтч — это
пересечение двух людей, у знака ровно этот смысл и ничего больше.

Кольца, а не залитые диски: залитый Venn на тёмном фоне читается как
схема из PowerPoint / нейрослоп. Обводка держит «ауру», линза — один
яркий фокус (как у сильного знака), без звезды и без клона Мимолёта.

Форма плоская, без градиентов: два цветных кольца и светлая линза
читаются и в favicon 16px, и в 1024px. Диагональ снизу-слева
вверх-вправо — знак «идёт навстречу», а заодно не путается с
горизонтальными кругами платёжных систем.

Геометрия одна на все носители: iOS-иконка, сплэш, favicon, баннеры
бота (make_icons.py, make_banners.py) импортируют её отсюда, SVG на
лендинге и React-компонент (web/src/components/BrandMark.tsx) повторяют
те же пропорции числами. Константы ниже — источник правды.

Пропорции (от радиуса круга R):
    расстояние между центрами  d  = 1.366 R   (линза ≈ 0.63 R — камень, не миндаль)
    смещение центра по X       dx = 0.580 R
    смещение центра по Y       dy = 0.360 R  (угол диагонали ≈ 32°)
    толщина кольца             w  = 0.30 R
Малиновое кольцо ниже и левее, фиолетовое выше и правее.
"""

from __future__ import annotations

from PIL import Image, ImageChops, ImageDraw, ImageFilter

# Палитра дизайн-системы (web/src/styles/globals.css)
МАЛИНОВЫЙ = (255, 45, 111)   # --color-accent #ff2d6f — первая аура
ФИОЛЕТОВЫЙ = (139, 92, 246)  # #8b5cf6 — вторая аура, соседний тон
СВЕТ = (250, 251, 252)       # --color-text #fafbfc — линза пересечения

# Приглушённый вариант — для «серых» носителей (баннер «Дальше»)
СЕРЫЙ_А = (99, 105, 115)
СЕРЫЙ_Б = (62, 67, 76)

#: Пропорции знака — доли от радиуса круга.
СМЕЩЕНИЕ_X = 0.580
СМЕЩЕНИЕ_Y = 0.360
ТОЛЩИНА = 0.30

#: Полные габариты знака в радиусах — чтобы вписывать его в макет.
ШИРИНА = 2 * (1 + СМЕЩЕНИЕ_X)   # ≈ 3.160 R
ВЫСОТА = 2 * (1 + СМЕЩЕНИЕ_Y)   # ≈ 2.720 R


def _круг(size: tuple[int, int], cx: float, cy: float, r: float) -> Image.Image:
    """Маска круга с микро-размытием: сглаживает край без потери формы."""
    m = Image.new("L", size, 0)
    if r <= 0:
        return m
    ImageDraw.Draw(m).ellipse([cx - r, cy - r, cx + r, cy + r], fill=255)
    return m.filter(ImageFilter.GaussianBlur(max(0.4, r * 0.008)))


def _кольцо(
    size: tuple[int, int], cx: float, cy: float, r: float, толщина: float
) -> Image.Image:
    """Маска кольца: внешний круг минус внутренний."""
    внешний = _круг(size, cx, cy, r)
    внутренний = _круг(size, cx, cy, max(0.0, r - толщина))
    return ImageChops.subtract(внешний, внутренний)


def нарисовать_знак(
    img: Image.Image,
    cx: float,
    cy: float,
    r: float,
    приглушить: bool = False,
) -> None:
    """Рисует знак на изображении. (cx, cy) — центр знака, r — радиус круга.

    Порядок слоёв фиксированный: малиновое кольцо, фиолетовое кольцо,
    поверх — светлая линза пересечения полных дисков. Линза считается
    пересечением масок, а не рисуется отдельной формой, поэтому не может
    разъехаться с кольцами.
    """
    а, б = (СЕРЫЙ_А, СЕРЫЙ_Б) if приглушить else (МАЛИНОВЫЙ, ФИОЛЕТОВЫЙ)
    dx, dy = СМЕЩЕНИЕ_X * r, СМЕЩЕНИЕ_Y * r
    w = ТОЛЩИНА * r

    ax, ay = cx - dx, cy + dy
    bx, by = cx + dx, cy - dy

    диск_а = _круг(img.size, ax, ay, r)
    диск_б = _круг(img.size, bx, by, r)
    кольцо_а = _кольцо(img.size, ax, ay, r, w)
    кольцо_б = _кольцо(img.size, bx, by, r, w)
    линза = ImageChops.darker(диск_а, диск_б)

    for маска, цвет in ((кольцо_а, а), (кольцо_б, б), (линза, СВЕТ)):
        img.paste(Image.new("RGB", img.size, цвет), (0, 0), маска)
