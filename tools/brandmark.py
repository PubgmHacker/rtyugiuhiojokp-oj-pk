"""Знак марки: два сплошных диска, в пересечении — свет.

В продукте у каждого человека свой детерминированный цвет — аура
(web/src/lib/aura.ts): кольца аватаров, обводки карточек, кольца историй.
Знак строится из этой же идеи: два залитых диска разных оттенков
сходятся по диагонали, и место пересечения — жёсткая белая линза.
Мэтч — это пересечение двух людей; у знака ровно этот смысл.

Сплошные диски, не кольца и не мягкие glow-пятна: форма читается
как Venn-знак с одним ярким фокусом. Края жёсткие (микро-AA только),
линза считается пересечением масок — не может разъехаться с дисками.

Геометрия одна на все носители: iOS-иконка, сплэш, favicon, баннеры
бота (make_icons.py, make_banners.py) импортируют её отсюда, SVG на
лендинге и React-компонент (web/src/components/BrandMark.tsx) повторяют
те же пропорции числами. Константы ниже — источник правды.

Пропорции (от радиуса круга R):
    расстояние между центрами  d  = 1.366 R   (линза ≈ 0.63 R — камень, не миндаль)
    смещение центра по X       dx = 0.580 R
    смещение центра по Y       dy = 0.360 R  (угол диагонали ≈ 32°)
Малиновый диск ниже и левее, фиолетовый выше и правее.
"""

from __future__ import annotations

from PIL import Image, ImageChops, ImageDraw

# Палитра дизайн-системы (web/src/styles/globals.css)
МАЛИНОВЫЙ = (255, 45, 111)   # --color-accent #ff2d6f — первая аура
ФИОЛЕТОВЫЙ = (139, 92, 246)  # #8b5cf6 — вторая аура, соседний тон
СВЕТ = (250, 251, 252)       # --color-text #fafbfc — линза пересечения

# Приглушённый вариант — для «серых» носителей (баннер «Дальше»)
СЕРЫЙ_А = (99, 105, 115)
СЕРЫЙ_Б = (62, 67, 76)

#: Пропорции знака — доли от радиуса круга.
СМЕЩЕНИЕ_X = 0.580
СМЕЩЕНИЕ_Y = 0.360

#: Полные габариты знака в радиусах — чтобы вписывать его в макет.
ШИРИНА = 2 * (1 + СМЕЩЕНИЕ_X)   # ≈ 3.160 R
ВЫСОТА = 2 * (1 + СМЕЩЕНИЕ_Y)   # ≈ 2.720 R


def _круг(size: tuple[int, int], cx: float, cy: float, r: float) -> Image.Image:
    """Маска круга с жёстким краем — без GaussianBlur / soft-glow."""
    m = Image.new("L", size, 0)
    if r <= 0:
        return m
    ImageDraw.Draw(m).ellipse([cx - r, cy - r, cx + r, cy + r], fill=255)
    return m


def нарисовать_знак(
    img: Image.Image,
    cx: float,
    cy: float,
    r: float,
    приглушить: bool = False,
) -> None:
    """Рисует знак на изображении. (cx, cy) — центр знака, r — радиус круга.

    Порядок слоёв: малиновый диск, фиолетовый диск, поверх — светлая
    линза пересечения. Линза = darker(маска_а, маска_б).
    """
    а, б = (СЕРЫЙ_А, СЕРЫЙ_Б) if приглушить else (МАЛИНОВЫЙ, ФИОЛЕТОВЫЙ)
    dx, dy = СМЕЩЕНИЕ_X * r, СМЕЩЕНИЕ_Y * r

    ax, ay = cx - dx, cy + dy
    bx, by = cx + dx, cy - dy

    диск_а = _круг(img.size, ax, ay, r)
    диск_б = _круг(img.size, bx, by, r)
    линза = ImageChops.darker(диск_а, диск_б)

    for маска, цвет in ((диск_а, а), (диск_б, б), (линза, СВЕТ)):
        img.paste(Image.new("RGB", img.size, цвет), (0, 0), маска)
