@dataclass(frozen=True)
class Реплика:
    """Одно сообщение переписки.

    `минут` — сколько минут назад отправлено; `прочитано` — прочла ли его
    вторая сторона (для своих реплик это галочки, для чужих — счётчик
    непрочитанного). `ответ` — индекс реплики выше в том же диалоге:
    цитату собираем по порядку, а не по тексту, иначе правка формулировки
    молча рвёт связь.
    """

    кто: str
    текст: str = ""
    минут: int = 0
    прочитано: bool = True
    #: Секунды голосового — файл соберётся под нарисованную волну.
    голос: int | None = None
    #: Секунды видеокружка.
    кружок: int | None = None
    #: Форма кружка из VIDEO_NOTE_SHAPES: circle, squircle, heart, star…
    форма: str = "circle"
    ответ: int | None = None
    #: Что вторая сторона поставила на эту реплику (ключ из REACTION_KEYS).
    реакция: str | None = None


