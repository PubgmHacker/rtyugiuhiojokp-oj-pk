#!/usr/bin/env python3
"""Вертикальные ролики для демо-ленты «Видео».

Лента-рилсы — второй формат знакомства в продукте, и пустой экран с
подписью «Пока пусто» показывает ровно ничего: ни ленты, ни прилипания,
ни счётчиков, ни листа комментариев. Смотреть на такое как пользователь
невозможно, поэтому демо-стенд обязан выкладывать в ленту настоящие mp4.

Кадр — тот же абстрактный плакат, что и в анкете (см. докстринг
tools/seed_demo.py: лица настоящих людей в демо-данных мы не кладём
сознательно), обрезанный под 9:16 и оживлённый наездом с дрейфом: ролик
из одного статичного кадра выглядит сломанным плеером, а не видео.

Собирает ffmpeg. Без ffmpeg на машине остаётся обложка — лента покажет
кадр, счётчики и всю обвязку, просто без движения.
"""

from __future__ import annotations

import hashlib
import logging
import shutil
import subprocess
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
ПУБЛИКА = КОРЕНЬ / "web" / "public"
ПАПКА = ПУБЛИКА / "demo-photos" / "reels"

log = logging.getLogger("demo_reels")

#: Кадр ленты. 720×1280 — 9:16 при вменяемом весе: десяток роликов в
#: demo-photos/ не должен весить как настоящая медиатека.
ШИРИНА, ВЫСОТА = 720, 1280

#: Подписи к роликам. Автор задаётся индексом в ЛЮДИ (tools/seed_demo.py),
#: чтобы ролик принадлежал тому же человеку, что и анкета с чатом.
#: (индекс автора, подпись, секунд, лайков, комментариев, просмотров, часов назад)
РОЛИКИ: list[tuple[int, str, int, int, int, int, int]] = [
    (1, "первый прогон номера. вживую будет громче", 8, 214, 12, 1840, 3),
    (7, "спот у моста, третий дубль", 7, 168, 7, 1320, 9),
    (0, "плёнка проявилась, показываю кадры", 9, 341, 24, 2610, 20),
    (4, "монтаж выставки за две минуты", 6, 97, 4, 760, 31),
    (5, "барабаны без глушителей, соседи держатся", 8, 402, 31, 3180, 44),
    (2, "прошла босса с одной жизнью, кричу", 7, 275, 19, 2050, 58),
]

#: Комментарии в ленте: (номер ролика, индекс автора или None для меня, текст).
#: Пустой лист комментариев на ролике с «12» в счётчике — вранье интерфейса.
КОММЕНТАРИИ: list[tuple[int, int | None, str]] = [
    (0, 7, "звук на 0:04 — это что за педаль?"),
    (0, None, "приду на концерт, если позовёшь"),
    (0, 4, "вот это уже похоже на альбом"),
    (2, 3, "вторая слева — лучшая"),
    (2, None, "плёнка тебе идёт больше цифры"),
    (4, 2, "соседи святые люди"),
]

#: Ролики, которые я уже лайкнул — состояние «сердце залито».
МОИ_ЛАЙКИ = (0, 4)


def _ключ(*части: object) -> str:
    сырое = "|".join(str(ч) for ч in части).encode("utf-8")
    return hashlib.sha1(сырое).hexdigest()[:12]


def _обложка(из_фото: str, ключ: str) -> Path:
    """Кадр 720×1280 из вертикального плаката анкеты.

    Плакат 3:4, лента 9:16 — режем по бокам, а не растягиваем: сфера в
    центре кадра обрезку переживает, растяжение делает из неё яйцо.
    """
    from PIL import Image

    ПАПКА.mkdir(parents=True, exist_ok=True)
    файл = ПАПКА / f"cover-{ключ}.jpg"
    if файл.exists():
        return файл

    источник = ПУБЛИКА / из_фото.lstrip("/")
    img = Image.open(источник).convert("RGB")
    нужная_ширина = int(img.height * ШИРИНА / ВЫСОТА)
    if нужная_ширина <= img.width:
        л = (img.width - нужная_ширина) // 2
        img = img.crop((л, 0, л + нужная_ширина, img.height))
    else:
        нужная_высота = int(img.width * ВЫСОТА / ШИРИНА)
        в = (img.height - нужная_высота) // 2
        img = img.crop((0, в, img.width, в + нужная_высота))
    img = img.resize((ШИРИНА, ВЫСОТА), Image.LANCZOS)
    img.save(файл, "JPEG", quality=86)
    return файл


def ролик_файлы(номер: int, из_фото: str, секунд: int) -> tuple[str, str]:
    """Вернуть (url видео, url обложки) для ролика ленты.

    Отпечаток исходного фото входит в имя: когда генератор плакатов
    меняется, ролики пересобираются сами, а не остаются кадром прошлой
    версии — на этом уже один раз попались видеокружки в чате.
    """
    источник = ПУБЛИКА / из_фото.lstrip("/")
    отпечаток = (
        hashlib.sha1(источник.read_bytes()).hexdigest()[:8] if источник.exists() else "нет"
    )
    ключ = _ключ(номер, из_фото, отпечаток, секунд)
    обложка = _обложка(из_фото, ключ)
    обложка_url = f"/demo-photos/reels/{обложка.name}"

    видео = ПАПКА / f"reel-{ключ}.mp4"
    видео_url = f"/demo-photos/reels/{видео.name}"
    if видео.exists():
        return видео_url, обложка_url

    ffmpeg = shutil.which("ffmpeg")
    if not ffmpeg:
        log.warning("ffmpeg не найден: ролик покажет обложку без движения")
        return обложка_url, обложка_url

    fps = 25
    кадров = секунд * fps
    # Наезд с дрейфом: съёмка с руки не стоит ровно, а чистый zoom без
    # сдвига читается как эффект презентации. Плюс медленный уход тона —
    # свет в кадре меняется, и ролик не выглядит зацикленным кадром.
    движение = (
        f"zoompan=z='min(zoom+0.00085,1.20)'"
        f":x='iw/2-(iw/zoom/2)+sin(on/{fps * 2})*26'"
        f":y='ih/2-(ih/zoom/2)+cos(on/{fps * 3})*20'"
        f":d={кадров}:s={ШИРИНА}x{ВЫСОТА}:fps={fps},"
        f"hue=h='sin(t/{секунд})*7':s=1.04"
    )
    команда = [
        ffmpeg, "-y", "-loglevel", "error", "-loop", "1", "-i", str(обложка),
        "-t", str(секунд), "-r", str(fps), "-vf", движение,
        "-c:v", "libx264", "-preset", "veryfast", "-crf", "27",
        "-pix_fmt", "yuv420p", "-movflags", "+faststart", str(видео),
    ]
    итог = subprocess.run(команда, capture_output=True, text=True)
    if итог.returncode != 0 or not видео.exists():
        # Ролик — витрина стенда, а не его смысл: падать целиком из-за
        # кодека неправильно, обложка донесёт всё остальное.
        хвост = (итог.stderr or "").strip().splitlines()[-1:] or ["без вывода"]
        log.warning("ffmpeg не собрал ролик (%s): остаётся обложка", хвост[0])
        return обложка_url, обложка_url
    log.debug("ролик %s (%d с)", видео.name, секунд)
    return видео_url, обложка_url
