"""Превью «как будто в приложении уже 100+ живых людей» — локальный стенд.

В отличие от tools/seed_demo.py (12 анкет с абстрактными градиентами для
review-аккаунта App Store), этот инструмент наполняет базу сотней с лишним
анкет с фотографиями-муляжами людей из открытых заглушечных сервисов
(pravatar.cc, xsgames.co, picsum.photos). Задача — оценить дизайн и
поведение продукта на реалистичном объёме: полная дека, десятки лайков,
переписки, гости профиля, живые комнаты.

Фото скачиваются в web/public/demo-photos/pv/ (папка demo-photos в
.gitignore) и отдаются dev-сервером фронтенда — сеть нужна только на время
скачивания, дальше стенд автономен. НЕ для коммита и НЕ для скриншотов в
App Store: там действует доктрина «никаких человеческих лиц в демо».

Все созданные аккаунты помечены phone = "demo:pv-NN". Повторный запуск
сначала сносит прежних демо-пользователей (любых demo:%, включая набор
seed_demo — смешение градиентов и фото ломает впечатление), затем строит
всё заново. Настоящие аккаунты не трогаются.

Запуск:
    python3 tools/seed_preview.py                    # 110 анкет вокруг dev:audit-jax
    python3 tools/seed_preview.py --me dev:my-device # другой dev-аккаунт
    python3 tools/seed_preview.py --wipe             # только удалить демо
    python3 tools/seed_preview.py --offline          # без сети: градиенты вместо фото
"""

