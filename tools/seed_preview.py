        s.add(UserHabit(user_id=меня.id, name="Стакан воды", target_per_day=3,
                        today_count=1, counted_for_date=полночь))
        # Дублей нет намеренно: кейс выбирает среди недостающих, повтор
        # возможен только у полной коллекции — превью не должно показывать
