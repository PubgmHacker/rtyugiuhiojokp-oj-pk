/**
 * Русское согласование числительных: 1 интерес, 2 интереса, 5 интересов.
 *
 * Живёт в общем месте, а не в экране: подписи со счётчиками есть на лице
 * анкеты, в гостях, в списках друзей и в подсказках заполненности. Три
 * копии одной и той же функции неизбежно разъезжаются — и где-то остаётся
 * «3 Интересы», по которому весь экран читается как машинный перевод.
 */

/** Форма слова для числа: one — 1, few — 2–4, many — 0, 5–20. */
export function plural(n: number, one: string, few: string, many: string): string {
  const десятки = Math.abs(n) % 10;
  const сотни = Math.abs(n) % 100;
  if (десятки === 1 && сотни !== 11) return one;
  if (десятки >= 2 && десятки <= 4 && (сотни < 12 || сотни > 14)) return few;
  return many;
}

/** «5 интересов» — число вместе с согласованным словом. */
export function счёт(n: number, one: string, few: string, many: string): string {
  return `${n} ${plural(n, one, few, many)}`;
}
