/**
 * Согласование числительных — не украшение: «3 Интересы» на лице анкеты
 * читается как машинный перевод, а лицо анкеты видят все.
 */
import { describe, expect, it } from "vitest";
import { plural, счёт } from "../plural";

const форма = (n: number) => plural(n, "интерес", "интереса", "интересов");

describe("plural", () => {
  it("единица — кроме одиннадцати", () => {
    for (const n of [1, 21, 101, 1001]) expect(форма(n)).toBe("интерес");
    expect(форма(11)).toBe("интересов");
    expect(форма(111)).toBe("интересов");
  });

  it("два–четыре — кроме подростковых", () => {
    for (const n of [2, 3, 4, 22, 34, 104]) expect(форма(n)).toBe("интереса");
    for (const n of [12, 13, 14, 112]) expect(форма(n)).toBe("интересов");
  });

  it("ноль, пять и выше — множественное", () => {
    for (const n of [0, 5, 9, 10, 20, 25, 100]) expect(форма(n)).toBe("интересов");
  });

  it("счёт склеивает число со словом", () => {
    expect(счёт(1, "пункт", "пункта", "пунктов")).toBe("1 пункт");
    expect(счёт(3, "пункт", "пункта", "пунктов")).toBe("3 пункта");
    expect(счёт(7, "пункт", "пункта", "пунктов")).toBe("7 пунктов");
  });
});
