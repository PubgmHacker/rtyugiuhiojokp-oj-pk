/**
 * Язык интерфейса: то, что человек выбрал в боте, доезжает до мини-аппа.
 *
 * Бот спрашивает язык первым экраном после /start. До колонки
 * `dating_users.locale` ответ выбрасывался — он жил в FSM-состоянии, которого у
 * мини-аппа нет вовсе, и выбравший узбекский открывал приложение на русском.
 * Здесь сторожится клиентская половина пути.
 *
 * Что именно может сломаться молча:
 *
 * 1. Три копии списка языков в трёх деплоях (API, бот, мини-апп). Общего модуля
 *    между ними быть не может — раздельные деплои и venv, — а разъезд тихий:
 *    мини-апп покажет язык, на который API ответит 422 при первой правке анкеты.
 * 2. Подписи в выборе языка расходятся с клавиатурой бота, и человек не узнаёт
 *    свой же выбор.
 * 3. Ключ без перевода. Пустая строка на кнопке выглядит сломанным
 *    интерфейсом — фолбэк обязан быть, и обязан быть английским, а не русским:
 *    выбравший турецкий скорее прочтёт английский.
 * 4. Форматтер, игнорирующий язык. Тогда вся затея вхолостую: дата остаётся
 *    русской при любом выборе, и проверить это можно только сравнением.
 * 5. Новая зашитая "ru-RU" в коде. Ровно так эти одиннадцать мест и появились.
 */

