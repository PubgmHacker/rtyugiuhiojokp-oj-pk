describe("форматы даты и числа", () => {
  const момент = new Date(Date.UTC(2026, 7, 20, 18, 5));

  it("дата действительно зависит от языка", () => {
    // Главная проверка всей затеи: форматтер, игнорирующий тег, оставил бы
    // русскую дату при любом выборе — и никакой другой тест этого не заметит.
    const русская = форматДаты(момент, "ru");
    expect(форматДаты(момент, "zh")).not.toBe(русская);
    expect(форматДаты(момент, "en")).not.toBe(русская);
    expect(форматДаты(момент, "tr")).not.toBe(русская);
  });

  it("месяц пишется буквами своего языка", () => {
    expect(форматДаты(момент, "ru")).toMatch(/[а-яё]/i);
    expect(форматДаты(момент, "en")).toMatch(/[a-z]/i);
    expect(форматДаты(момент, "zh")).toMatch(/月/);
  });

  it("время отдаёт часы и минуты на всех языках", () => {
    for (const язык of ЯЗЫКИ) {
      expect(форматВремени(момент, язык), язык).toMatch(/\d/);
    }
  });

  it("разделитель дня добавляет год только когда просят", () => {
    expect(форматДняРазделителя(момент, "ru", true)).toContain("2026");
    expect(форматДняРазделителя(момент, "ru", false)).not.toContain("2026");
  });

  it("не падает ни на одном языке", () => {
    // Тег вроде `uz-Latn-UZ` может быть не поддержан старым вебвью — там
    // предусмотрен откат на системный формат, и он обязан работать.
    for (const язык of ЯЗЫКИ) {
      expect(() => форматДаты(момент, язык), язык).not.toThrow();
      expect(() => форматДняРазделителя(момент, язык, true), язык).not.toThrow();
      expect(форматЧисла(1234567, язык), язык).toMatch(/\d/);
    }
  });
});

describe("зашитых форматов не осталось", () => {
  /**
   * Экраны, переведённые на язык аккаунта. Админка сюда не входит намеренно:
   * она целиком по-русски и открыта только своим — локализовать её даты значит
   * добавить работы там, где её никто не увидит.
   */
  const ФАЙЛЫ = [
    "web/src/pages/Chat.tsx",
    "web/src/pages/Matches.tsx",
    "web/src/components/LimitSheet.tsx",
    "web/src/App.tsx",
  ];

  it.each(ФАЙЛЫ)("%s не зашивает локаль в формат даты", (путь) => {
    // Ровно так эти места и появились: `toLocaleDateString("ru-RU")` пишется
    // на автомате, а для турка результат нечитаем.
    const исходник = прочитать(`${К_КОРНЮ}${путь}`);
    expect(исходник).not.toMatch(/toLocale(Date|Time)?String\(\s*["']ru/);
  });
});
