/**
 * Реакции на сообщение: набор, подписи, тона и рисованные знаки.
 *
 * Почему знаки рисованные, а не эмодзи. В интерфейсе продукта эмодзи нет
 * (см. PRODUCT.md): системный шрифт рисует их по-своему на каждой
 * платформе, и один и тот же чат выглядит то Apple, то Google, то серым
 * прямоугольником в Telegram Desktop под Linux. Экспрессия у нас живёт в
 * наклейках — это отдельный, оплаченный слой; реакция же обязана быть
 * частью интерфейса и краситься тоном темы.
 *
 * Почему не буквы и не знаки препинания. Здесь стояли текстовые заглушки
 * «HA», «!!» и «?»: шрифт склеил «!!» в лигатуру «‼», и реакция стала
 * читаться как бейдж системного предупреждения, а не как отклик человека.
 * Поэтому у всех шести — своя фигура в одном языке: сплошная заливка,
 * скруглённые концы, оптический вес на уровне сердца.
 *
 * Ключи заперты: они лежат в базе (`Message.reactions`) и приезжают в
 * WebSocket-кадрах. Переименование ключа стирает чужие реакции.
 */

