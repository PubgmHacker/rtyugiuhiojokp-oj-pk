export function isReactionKey(v: unknown): v is ReactionKey {
  return typeof v === "string" && (REACTION_ORDER as readonly string[]).includes(v);
}

/**
 * Знак реакции. Красится `currentColor` — цвет задаёт чип вокруг, чтобы
 * тон реакции и тон чипа не могли разойтись.
 */
export function ReactionGlyph({
  k,
  size = 18,
  muted,
  style,
}: {
  k: ReactionKey;
  size?: number;
  muted?: boolean;
  style?: CSSProperties;
}) {
  const обводки = ОБВОДКИ[k];
  return (
    <span
      aria-hidden="true"
      className="inline-flex items-center justify-center shrink-0"
      style={{ width: size, height: size, opacity: muted ? 0.55 : 1, ...style }}
    >
      <svg width={size} height={size} viewBox="0 0 24 24" fill="currentColor">
        <path d={ПУТИ[k]} />
        {обводки?.map((о) => (
          <path
            key={о.d}
            d={о.d}
            fill="none"
            stroke="currentColor"
            strokeWidth={о.ширина}
            strokeLinecap="round"
          />
        ))}
      </svg>
    </span>
  );
}
