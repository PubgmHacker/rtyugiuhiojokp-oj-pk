/**
 * Две таблицы арканов живут в разных файлах: номера и значки строк — в
 * Tarot.tsx, рисунки лиц — в TarotArcana.tsx. Разъехаться они могут молча:
 * tsc пропускает Record<string, …> с любым набором ключей, а карта без
 * рисунка не падает — она подставляет запасной и выглядит «просто такой».
 * Один раз правка по регулярке уже съела 21 аркан из 22, и ни сборка, ни
 * типы этого не заметили. Здесь считаем ключи и различимость рисунков.
 */

import { describe, expect, it } from "vitest";
import { renderToStaticMarkup } from "react-dom/server";

import { ИМЕНА_АРКАНОВ, ТаротАркан } from "../TarotArcana";
import { АРКАНЫ } from "../../pages/Tarot";

const разметка = (name: string) => renderToStaticMarkup(<ТаротАркан name={name} />);

describe("старшие арканы", () => {
  it("рисунки и номера описывают одну и ту же колоду из 22 карт", () => {
    expect(ИМЕНА_АРКАНОВ).toHaveLength(22);
    expect(ИМЕНА_АРКАНОВ).toEqual(Object.keys(АРКАНЫ));
  });

  it("у каждой карты своя сцена, а не общий запасной знак", () => {
    const запасной = разметка("Такой карты нет");
    const рисунки = ИМЕНА_АРКАНОВ.map(разметка);

    for (const [i, рисунок] of рисунки.entries()) {
      expect(рисунок, ИМЕНА_АРКАНОВ[i]).not.toBe(запасной);
    }
    expect(new Set(рисунки).size).toBe(22);
  });

  it("незнакомое имя с сервера рисует запасной знак, а не пустой квадрат", () => {
    const запасной = разметка("Аркан, которого не было");
    expect(запасной).toContain("<path");
    expect(запасной).toContain('viewBox="0 0 40 48"');
  });
});
