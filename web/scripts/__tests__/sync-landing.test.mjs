/**
 * Юридические страницы: одна правка — оба дерева, и ни одной мёртвой ссылки.
 *
 * Документы живут в двух местах: `landing/` — публичный сайт, `web/public` — то,
 * что Vite копирует в `dist`. По второму адресу человек читает оферту, когда
 * пришёл по ссылке из бота (`bot/config.py: legal_url` с `SITE_URL` веб-сервиса)
 * или из самого мини-аппа (`src/lib/legal.ts`, ветка «текущий origin»). Обе беды
 * копипасты случались тут сразу:
 *
 * * Расхождение. Порог возраста, адрес поддержки, дата обновления — поправили в
 *   одном дереве, забыли во втором, и человек читает не тот документ, по
 *   которому его будут судить.
 * * Одинаковость. В подвале лендинга — ссылки на его же разделы (`/#how` и
 *   рядом). В мини-аппе корень отдаёт SPA (`serve dist -s`), лендинга там нет:
 *   человек жмёт «Как работает» в оферте и попадает в свою деку. «Открыть в
 *   Telegram» внутри Telegram — оттуда же.
 *
 * Отсюда правило: правится только `landing/`, копии порождаются, различия —
 * закрытый список `ЗАМЕНЫ`. Ниже проверяется и то, что копии не отстали, и то,
 * что различие именно такое, и что генератор падает, а не копирует молча, когда
 * разметка лендинга уехала.
 */

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { afterEach, describe, it, expect } from "vitest";

import {
  ДОКУМЕНТЫ,
  АССЕТЫ,
  ЛЕНДИНГ,
  ПУБЛИЧНОЕ,
  ЗАМЕНЫ,
  РазметкаУшла,
  базаСайта,
  осмотреть,
  положить,
  преобразовать,
  расхождения,
} from "../sync-landing.mjs";

/** Минимальная страница лендинга: канон, кнопка шапки, ссылка на раздел. */
function страница({
  канон = '<link rel="canonical" href="https://example.org/terms.html">',
  кнопка = '<a class="btn btn-primary btn-sm" href="https://t.me/simpmatchbot">Открыть в Telegram</a>',
  подвал = '<a href="/#how">Как работает</a>',
} = {}) {
  return `<!DOCTYPE html>\n${канон}\n${кнопка}\n${подвал}\n`;
}

describe("копии в web/public", () => {
  it("не отстали от лендинга", () => {
    const отставшие = расхождения().map((о) => `public/${о.имя}: ${о.состояние}`);
    expect(
      отставшие,
      "копии отстали от landing/. Человек по ссылке из бота прочитает старый " +
        "документ. Починить: npm run sync:landing"
    ).toEqual([]);
  });

  it.each(ДОКУМЕНТЫ)("%s не ссылается в корень мини-аппа", (имя) => {
    const текст = fs.readFileSync(path.join(ПУБЛИЧНОЕ, имя), "utf8");
    expect(
      текст.match(/href="\/#[^"]*"/g),
      `public/${имя} ссылается в корень: там SPA, а не лендинг — анкор потеряется`
    ).toBeNull();
  });

  it.each(ДОКУМЕНТЫ)("%s возвращает в приложение, а не в Telegram", (имя) => {
    const копия = fs.readFileSync(path.join(ПУБЛИЧНОЕ, имя), "utf8");
    const сайт = fs.readFileSync(path.join(ЛЕНДИНГ, имя), "utf8");

    expect(копия, `public/${имя}: Telegram предлагается внутри Telegram`).not.toContain(
      "Открыть в Telegram"
    );
    expect(
      копия,
      `public/${имя}: из документа нет пути назад — человек упирается в тупик`
    ).toContain("Вернуться в приложение");
    expect(сайт, `landing/${имя} потерял главную кнопку: на сайте она и есть вход`).toContain(
      "Открыть в Telegram"
    );
  });

  it.each(ДОКУМЕНТЫ)("%s помечен как порождённый", (имя) => {
    const начало = fs.readFileSync(path.join(ПУБЛИЧНОЕ, имя), "utf8").slice(0, 400);
    expect(
      начало,
      `public/${имя} не говорит, что он порождён: правку в нём молча потеряет ` +
        `следующая сборка (prebuild)`
    ).toContain("scripts/sync-landing.mjs");
  });

  it("оформление скопировано побайтово", () => {
    for (const имя of АССЕТЫ) {
      const свой = fs.readFileSync(path.join(ПУБЛИЧНОЕ, имя));
      const источник = fs.readFileSync(path.join(ЛЕНДИНГ, имя));
      expect(
        Buffer.compare(свой, источник),
        `public/${имя} отличается от landing/${имя}: документ откроется без вёрстки`
      ).toBe(0);
    }
  });

  it.each(ДОКУМЕНТЫ)("%s — файл, а не ссылка наружу", (имя) => {
    // Из-за ссылки падала вся сборка образа: контекст — web/, ../../landing
    // там не существует, а vite копирует publicDir через statSync без защиты.
    const состояние = fs.lstatSync(path.join(ПУБЛИЧНОЕ, имя));
    expect(состояние.isSymbolicLink(), `public/${имя} — символическая ссылка`).toBe(false);
    expect(состояние.isFile()).toBe(true);
  });
});

describe("лендинг", () => {
  it.each(ДОКУМЕНТЫ)("%s сохранил относительные ссылки на свои разделы", (имя) => {
    const текст = fs.readFileSync(path.join(ЛЕНДИНГ, имя), "utf8");
    expect(
      текст,
      `landing/${имя}: на сайте ссылки на разделы обязаны быть без домена, иначе ` +
        `локальный просмотр и смена домена уводят человека на прод`
    ).toContain('href="/#');
  });
});

describe("преобразование", () => {
  it("ведёт ссылки за каноническим адресом, а не за домом в коде", () => {
    const получилось = преобразовать(страница(), "terms.html");
    expect(получилось).toContain('href="https://example.org/#how"');
    expect(получилось, "домен зашит в генератор — разойдётся с лендингом").not.toContain(
      "simp.app"
    );
  });

  it("меняет кнопку шапки на возврат в приложение", () => {
    const получилось = преобразовать(страница(), "terms.html");
    expect(получилось).toContain('<a class="btn btn-primary btn-sm" href="/">Вернуться в приложение</a>');
    expect(получилось).not.toContain("Открыть в Telegram");
  });

  it("помечает результат и не теряет доктайп", () => {
    const получилось = преобразовать(страница(), "terms.html");
    expect(получилось.startsWith("<!DOCTYPE html>\n<!-- Сгенерировано")).toBe(true);
    expect(получилось).toContain("landing/terms.html");
  });

  it("падает, если кнопки шапки в лендинге больше нет", () => {
    // Молчаливая копия без замен хуже отсутствия генератора: она выглядит рабочей.
    expect(() => преобразовать(страница({ кнопка: "<span>вход</span>" }), "terms.html")).toThrow(
      РазметкаУшла
    );
  });

  it("падает без канонического адреса", () => {
    expect(() => преобразовать(страница({ канон: "" }), "terms.html")).toThrow(/canonical/);
  });

  it("падает, если ссылка в корень пережила замены", () => {
    // Предохранитель на выходе — не украшение: он единственное, что ловит
    // случай «список ЗАМЕНЫ больше не покрывает разметку». Проверяется тем, что
    // замена временно превращается в пустую операцию.
    const был = ЗАМЕНЫ[0].стало;
    ЗАМЕНЫ[0].стало = ЗАМЕНЫ[0].было;
    try {
      expect(() => преобразовать(страница(), "terms.html")).toThrow(/остались ссылки в корень/);
    } finally {
      ЗАМЕНЫ[0].стало = был;
    }
    // И после восстановления генератор снова рабочий — тест не оставил мусора.
    expect(преобразовать(страница(), "terms.html")).not.toMatch(/href="\/#/);
  });

  it("список документов и оформления не пересекается и не пуст", () => {
    expect(ДОКУМЕНТЫ.length).toBeGreaterThan(0);
    expect(АССЕТЫ.length).toBeGreaterThan(0);
    expect(ДОКУМЕНТЫ.filter((и) => АССЕТЫ.includes(и))).toEqual([]);
  });

  it("каждый документ из списка есть в обоих деревьях", () => {
    for (const имя of ДОКУМЕНТЫ) {
      expect(fs.existsSync(path.join(ЛЕНДИНГ, имя)), `нет landing/${имя}`).toBe(true);
      expect(осмотреть(имя).состояние).toBe("совпадает");
    }
  });

  it("база сайта берётся без хвостового слэша", () => {
    expect(базаСайта('<link rel="canonical" href="https://simp.app/terms.html">', "тест")).toBe(
      "https://simp.app"
    );
  });
});

/**
 * Распознавание символической ссылки — на временном дереве, а не в репозитории.
 *
 * Это та самая поломка, из-за которой скрипт и появился: `web/public/*` были
 * ссылками на `../../landing/*`, образ веба собирается из контекста `web/`, где
 * этой цели нет, и `vite build` падал целиком на `statSync` от `app.js`.
 *
 * Тише всего это именно с оформлением: оно копируется побайтово, и содержимое
 * по ссылке равно источнику. Если осмотр пойдёт `stat`, а не `lstat`, он
 * отрапортует «совпадает» — CI зелёный, образ не собирается.
 */
describe("осмотр не идёт по ссылке", () => {
  const времянки = [];

  function дерево() {
    const корень = fs.mkdtempSync(path.join(os.tmpdir(), "sync-landing-"));
    времянки.push(корень);
    const лендинг = path.join(корень, "landing");
    const публичное = path.join(корень, "public");
    fs.mkdirSync(лендинг);
    fs.mkdirSync(публичное);
    return { лендинг, публичное };
  }

  afterEach(() => {
    while (времянки.length) {
      fs.rmSync(времянки.pop(), { recursive: true, force: true });
    }
  });

  it("оформление-ссылка распознаётся как ссылка, а не как совпадение", () => {
    const откуда = дерево();
    fs.writeFileSync(path.join(откуда.лендинг, "styles.css"), "body{color:red}\n");
    fs.symlinkSync("../landing/styles.css", path.join(откуда.публичное, "styles.css"));

    const осмотр = осмотреть("styles.css", откуда);
    expect(
      осмотр.состояние,
      "ссылка на оформление принята за копию: содержимое по ней совпадает с " +
        "источником, но в образе веба этой цели нет и сборка падает"
    ).toBe("ссылка");
    expect(осмотр.куда).toBe("../landing/styles.css");
  });

  it("документ-ссылка тоже не считается копией", () => {
    const откуда = дерево();
    fs.writeFileSync(path.join(откуда.лендинг, "terms.html"), страница());
    fs.symlinkSync("../landing/terms.html", path.join(откуда.публичное, "terms.html"));

    expect(осмотреть("terms.html", откуда).состояние).toBe("ссылка");
  });

  it("положить снимает ссылку, а не пишет сквозь неё в лендинг", () => {
    // Запись ПО ссылке — это открытие источника правды на запись.
    const откуда = дерево();
    const источник = path.join(откуда.лендинг, "styles.css");
    fs.writeFileSync(источник, "body{color:red}\n");
    fs.symlinkSync("../landing/styles.css", path.join(откуда.публичное, "styles.css"));

    положить(осмотреть("styles.css", откуда));

    const цель = path.join(откуда.публичное, "styles.css");
    expect(fs.lstatSync(цель).isSymbolicLink()).toBe(false);
    expect(fs.readFileSync(источник, "utf8"), "лендинг обнулён записью сквозь ссылку").toBe(
      "body{color:red}\n"
    );
    expect(осмотреть("styles.css", откуда).состояние).toBe("совпадает");
  });

  it("отсутствие копии и отсутствие источника различаются", () => {
    const откуда = дерево();
    expect(осмотреть("styles.css", откуда).состояние).toBe("нет источника");
    fs.writeFileSync(path.join(откуда.лендинг, "styles.css"), "body{}\n");
    expect(осмотреть("styles.css", откуда).состояние).toBe("нет копии");
  });
});
