#!/usr/bin/env node
/**
 * Юридические страницы лендинга → web/public настоящими файлами.
 *
 * Зачем вообще копировать. Мини-апп обязан отдавать privacy.html и terms.html:
 * именно на них ссылается экран согласия в боте (`bot/config.py: legal_url`) и
 * сам мини-апп (`web/src/lib/legal.ts`, ветка «текущий origin»), и на них же
 * смотрит ревью App Store. Раньше они лежали в `web/public`
 * символическими ссылками на `../../landing/*`, и это ломало продовую сборку:
 * образ веба собирается из контекста `web/` (Railway Root Directory: web,
 * `web/Dockerfile`: `COPY . .`), где `../../landing` не существует — ссылки
 * висят в воздухе, а `vite build` копирует publicDir через `statSync` без
 * защиты и падает целиком:
 *
 *   ✓ 2129 modules transformed.
 *   ✗ Build failed in 1.36s
 *   error during build: ENOENT: no such file or directory,
 *     stat '/private/tmp/webctx_verify/public/app.js'
 *
 * Полный чекаут этого не показывает — там ссылки разрешаются, — поэтому и CI, и
 * локальная сборка были зелёными, пока прод не отдавал 404 на ссылку из бота.
 *
 * Почему копия не побайтовая. Копировать один в один тоже нельзя, и это вторая
 * половина той же поломки. В подвале лендинга есть ссылки на его собственные
 * разделы — `/#how`, `/#features`, `/#safety`, `/#faq`. В мини-аппе корень занят
 * приложением: `web/Dockerfile` отдаёт `serve dist -s`, то есть на `/` лежит SPA,
 * лендинга по этому адресу нет вообще. Человек жмёт в оферте «Как работает» и
 * попадает в свою деку с проигнорированным анкором. Кнопка «Открыть в Telegram»
 * внутри Telegram — из той же серии: она ведёт туда, откуда человек уже пришёл,
 * вместо возврата к приложению.
 *
 * Поэтому источник правды один — `landing/` (там канонические URL, sitemap и свой
 * деплой), а `web/public` — производная: документы преобразуются по закрытому
 * списку `ЗАМЕНЫ`, оформление копируется побайтово. Чтобы производная не
 * разъезжалась молча, скрипт вызывается автоматически перед каждой сборкой
 * (`prebuild` в package.json), а `--check` тем же списком проверяет совпадение в
 * CI. Что различается — видно здесь и проверяется тестами
 * `web/scripts/__tests__/sync-landing.test.mjs` и `api/tests/test_legal_sync.py`.
 *
 * Адрес сайта не задаётся флагом и не хранится в этом файле второй раз: он
 * берётся из `<link rel="canonical">` самой страницы. Сменится домен — сменится
 * он в лендинге, и ссылки в копиях поедут за ним сами.
 *
 * В контексте Docker `../landing` отсутствует — тогда режим синхронизации ничего
 * не делает и выходит с нулём: в образ едут уже готовые файлы из репозитория.
 *
 * Использование:
 *   node scripts/sync-landing.mjs            # синхронизировать
 *   node scripts/sync-landing.mjs --check    # только проверить, ничего не писать
 */

import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ЭТОТ_ФАЙЛ = fileURLToPath(import.meta.url);
export const КОРЕНЬ_ВЕБА = path.resolve(path.dirname(ЭТОТ_ФАЙЛ), "..");
export const ЛЕНДИНГ = path.resolve(КОРЕНЬ_ВЕБА, "..", "landing");
export const ПУБЛИЧНОЕ = path.join(КОРЕНЬ_ВЕБА, "public");

/**
 * Документы, которые обязаны быть в обоих деревьях.
 *
 * Пять штук — то, на что ссылаются бот, мини-апп и App Store. Каждый проходит
 * через `преобразовать`.
 */
export const ДОКУМЕНТЫ = [
  "privacy.html",
  "terms.html",
  "guidelines.html",
  "moderation.html",
  "support.html",
];

/**
 * Их оформление. Копируется побайтово: без этих файлов документы открываются
 * голым HTML. styles.css держит всю вёрстку, app.js — раскрытие пунктов,
 * icon.svg — логотип в шапке, og-image.png нужен, когда ссылку на документ
 * вставляют в мессенджер.
 */
export const АССЕТЫ = ["styles.css", "app.js", "icon.svg", "og-image.png"];

/** Всё, что синхронизируется, — для сообщений и тестов. */
export const ФАЙЛЫ = [...ДОКУМЕНТЫ, ...АССЕТЫ];

/** Ставится первой строкой в копию: файл производный, править его бессмысленно. */
export const ШАПКА =
  "<!-- Сгенерировано web/scripts/sync-landing.mjs из landing/{имя}. " +
  "Правьте landing/, затем: npm run sync:landing -->";

const КАНОНИЧЕСКИЙ = /<link rel="canonical" href="(https?:\/\/[^"]+?)\/[^"/]*">/;
const ССЫЛКА_В_КОРЕНЬ = /href="\/#[^"]*"/g;

/** Ожидаемого фрагмента в лендинге нет — молча копировать нельзя. */
export class РазметкаУшла extends Error {
  constructor(сообщение) {
    super(сообщение);
    this.name = "РазметкаУшла";
  }
}

/**
 * Чем копия отличается от источника. Закрытый список: всё, что здесь не
 * перечислено, обязано совпадать побайтово.
 */
export const ЗАМЕНЫ = [
  {
    зачем: "ссылки на разделы лендинга — в мини-аппе такого корня нет",
    было: 'href="/#',
    стало: 'href="{база}/#',
  },
  {
    зачем: "«Открыть в Telegram» внутри Telegram — возврат в приложение",
    было:
      '<a class="btn btn-primary btn-sm" ' +
      'href="https://t.me/simpmatchbot">Открыть в Telegram</a>',
    стало: '<a class="btn btn-primary btn-sm" href="/">Вернуться в приложение</a>',
  },
];

/** Адрес сайта из `<link rel="canonical">` страницы, без хвостового слэша. */
export function базаСайта(текст, откуда) {
  const совпадение = КАНОНИЧЕСКИЙ.exec(текст);
  if (!совпадение) {
    throw new РазметкаУшла(
      `${откуда}: нет <link rel="canonical">, а из него берётся адрес сайта для ` +
        `ссылок в копии. Второго места с доменом в проекте нет и быть не должно`
    );
  }
  return совпадение[1];
}

/** Страница лендинга → страница мини-аппа. */
export function преобразовать(текст, имя) {
  const база = базаСайта(текст, `landing/${имя}`);
  let результат = текст;

  for (const замена of ЗАМЕНЫ) {
    if (!результат.includes(замена.было)) {
      throw new РазметкаУшла(
        `landing/${имя}: не найден фрагмент «${замена.было.slice(0, 60)}» ` +
          `(${замена.зачем}). Разметка лендинга изменилась — поправьте ЗАМЕНЫ в ` +
          `web/scripts/sync-landing.mjs, иначе копия уедет в мини-апп с ` +
          `нерабочими ссылками`
      );
    }
    результат = результат.replaceAll(замена.было, замена.стало.replace("{база}", база));
  }

  const осталось = результат.match(ССЫЛКА_В_КОРЕНЬ);
  if (осталось) {
    throw new РазметкаУшла(
      `landing/${имя}: после замен остались ссылки в корень ${осталось.join(", ")} — ` +
        `в мини-аппе они ведут в приложение, а не в лендинг`
    );
  }

  const шапка = ШАПКА.replace("{имя}", имя);
  const маркер = "<!DOCTYPE html>";
  return результат.startsWith(маркер)
    ? результат.replace(маркер, `${маркер}\n${шапка}`)
    : `${шапка}\n${результат}`;
}

/** Что обязано лежать в web/public по этому имени. */
function ожидаемое(имя, источник) {
  const данные = fs.readFileSync(источник);
  return ДОКУМЕНТЫ.includes(имя)
    ? Buffer.from(преобразовать(данные.toString("utf8"), имя), "utf8")
    : данные;
}

/** Короткая подпись содержимого — сравнивать побайтово, но печатать коротко. */
function подпись(данные) {
  return createHash("sha256").update(данные).digest("hex").slice(0, 12);
}

/**
 * Состояние одного файла в web/public относительно лендинга.
 *
 * Корни принимаются параметром, а не только берутся из модуля: без этого
 * единственный способ проверить распознавание символической ссылки — подсунуть
 * ссылку в рабочее дерево, то есть сломать репозиторий на время теста.
 */
export function осмотреть(имя, откуда = { лендинг: ЛЕНДИНГ, публичное: ПУБЛИЧНОЕ }) {
  const источник = path.join(откуда.лендинг, имя);
  const цель = path.join(откуда.публичное, имя);

  if (!fs.existsSync(источник)) {
    return { имя, цель, источник, состояние: "нет источника" };
  }
  // lstat, а не stat: stat идёт по ссылке и рапортует про файл в landing/,
  // то есть ровно та слепота, из-за которой поломку не замечали. Для
  // оформления это особенно тихо — оно копируется побайтово, и содержимое по
  // ссылке совпадает с источником: `--check` сказал бы «совпадает», а сборка
  // образа падала на statSync того же app.js.
  let свой = null;
  try {
    свой = fs.lstatSync(цель);
  } catch {
    return { имя, цель, источник, состояние: "нет копии" };
  }
  if (свой.isSymbolicLink()) {
    return { имя, цель, источник, состояние: "ссылка", куда: fs.readlinkSync(цель) };
  }
  if (!свой.isFile()) {
    return { имя, цель, источник, состояние: "не файл" };
  }
  const надо = ожидаемое(имя, источник);
  const одинаковые = Buffer.compare(fs.readFileSync(цель), надо) === 0;
  return { имя, цель, источник, состояние: одинаковые ? "совпадает" : "разошлась" };
}

/** Записать копию, предварительно убрав ссылку, если на её месте была ссылка. */
export function положить(осмотр) {
  // Снять обязательно: запись ПО ссылке уходит в landing/, то есть при
  // совпадении путей это открытие источника правды на запись. Терять его
  // из-за скрипта синхронизации нельзя.
  if (осмотр.состояние === "ссылка") {
    fs.unlinkSync(осмотр.цель);
  }
  fs.mkdirSync(path.dirname(осмотр.цель), { recursive: true });
  const данные = ожидаемое(осмотр.имя, осмотр.источник);
  fs.writeFileSync(осмотр.цель, данные);
  return данные;
}

/**
 * Сверить всё и (если не проверка) обновить. Возвращает список расхождений —
 * им пользуются и CLI, и тесты, чтобы не повторять логику сравнения.
 */
export function расхождения(откуда = { лендинг: ЛЕНДИНГ, публичное: ПУБЛИЧНОЕ }) {
  // Стрелка, а не `map(осмотреть)`: map передаёт вторым аргументом индекс, и он
  // молча встал бы на место корней вместо значения по умолчанию.
  return ФАЙЛЫ.map((имя) => осмотреть(имя, откуда)).filter((о) => о.состояние !== "совпадает");
}

export function main(аргументы = process.argv.slice(2)) {
  const проверка = аргументы.includes("--check");

  if (!fs.existsSync(ЛЕНДИНГ)) {
    if (проверка) {
      console.error(
        `нет каталога ${ЛЕНДИНГ} — сверять не с чем. --check запускают там, ` +
          `где есть весь репозиторий (CI, локальная машина), а не в контексте Docker.`
      );
      return 1;
    }
    console.log(
      `landing/ рядом нет — синхронизация пропущена. Так выглядит сборка образа ` +
        `из контекста web/: в public/ уже лежат готовые файлы из репозитория.`
    );
    return 0;
  }

  let плохие;
  try {
    плохие = расхождения();
  } catch (сбой) {
    if (!(сбой instanceof РазметкаУшла)) throw сбой;
    console.error(String(сбой.message));
    return 2;
  }

  if (проверка) {
    for (const о of плохие) {
      const хвост = о.состояние === "ссылка" ? ` → ${о.куда}` : "";
      console.error(`✗ public/${о.имя}: ${о.состояние}${хвост}`);
    }
    if (плохие.length) {
      console.error(
        `\n${плохие.length} из ${ФАЙЛЫ.length} юридических файлов в web/public ` +
          `не совпадают с landing/. Ссылка наружу роняет сборку образа веба ` +
          `(контекст — web/, ../../landing там нет), расхождение отдаёт человеку ` +
          `не тот документ, который он открывает по ссылке из бота.\n` +
          `Починить: npm run sync:landing`
      );
      return 1;
    }
    console.log(`✓ ${ФАЙЛЫ.length} юридических файлов в web/public совпадают с landing/`);
    return 0;
  }

  const нет_источника = плохие.filter((о) => о.состояние === "нет источника");
  if (нет_источника.length) {
    console.error(
      `в landing/ нет: ${нет_источника.map((о) => о.имя).join(", ")} — ` +
        `копировать нечего, а мини-апп обязан отдавать эти страницы`
    );
    return 1;
  }

  for (const о of плохие) {
    const данные = положить(о);
    console.log(`↻ public/${о.имя} ← landing/${о.имя} (${о.состояние}, ${подпись(данные)})`);
  }
  console.log(
    плохие.length
      ? `синхронизировано: ${плохие.length}, без изменений: ${ФАЙЛЫ.length - плохие.length}`
      : `все ${ФАЙЛЫ.length} юридических файлов уже совпадают с landing/`
  );
  return 0;
}

// Запуск только напрямую: тесты импортируют функции и не должны ничего писать.
if (process.argv[1] && path.resolve(process.argv[1]) === ЭТОТ_ФАЙЛ) {
  process.exit(main());
}
